proc essentialNames*(index: AptIndex): seq[string] =
  ## Every package the index marks ``Essential: yes``, sorted.
  for rec in index.records:
    if rec.essential: result.add(rec.name)
  result.sort(cmp)
  result = result.deduplicate(isSorted = true)

proc priorityRank(p: string): int =
  case p
  of "required": 0
  of "important": 1
  of "standard": 2
  of "optional": 3
  else: 4

proc providersOf(index: AptIndex; atom: string): seq[string] =
  ## A real package of that name first, then the virtual's providers by
  ## ``Priority:`` (required first — how ``awk`` resolves to ``mawk``, as
  ## on an installed Debian base) and then name.
  ##
  ## No closure here: a closure capturing ``index`` copies the whole
  ## parsed archive index (tens of thousands of records) on every call.
  if atom in index.byName: result.add(atom)
  if atom in index.virtuals:
    var ranked: seq[(int, string)] = @[]
    for n in index.virtuals[atom]:
      ranked.add((priorityRank(index.records[index.byName[n]].priority), n))
    ranked.sort()
    for (_, p) in ranked:
      if p notin result: result.add(p)

proc resolveAptClosureRecords*(index: AptIndex; roots: seq[string];
                               includeEssential = true):
    seq[AptPackageRecord] =
  ## The member set of a closure (spec §8.3 item 3): the transitive
  ## ``Depends:`` + ``Pre-Depends:`` closure of ``roots`` and, unless
  ## ``includeEssential`` is false, of the index's ``Essential: yes`` set.
  ## ``Recommends:`` is not followed.
  ##
  ## Alternatives and virtual packages are resolved preferring a package
  ## already chosen or queued, then the first alternative present in the
  ## index (for a virtual, its provider ordered by ``providersOf``). The walk is
  ## breadth-first from the roots, then the essential set, so the result is
  ## a function of the index and the request. Raises ``AptClosureError`` for
  ## a root or dependency the index cannot satisfy. Sorted by name.
  var chosen = initHashSet[string]()
  var queue: seq[string] = @[]
  var queued = initHashSet[string]()  ## everything ever added to ``queue``
  for r in roots:
    if r notin index.byName:
      var e = newException(AptClosureError,
        "root package '" & r & "' is not in the index")
      e.rootPackage = r
      e.missingDep = r
      raise e
    queue.add(r)
    queued.incl(r)
  if includeEssential:
    for n in essentialNames(index):
      queue.add(n)
      queued.incl(n)
  var head = 0
  while head < queue.len:
    let name = queue[head]
    inc head
    if name in chosen: continue
    chosen.incl(name)
    let rec = index.records[index.byName[name]]
    result.add(rec)
    for clauses in [rec.preDepends, rec.depends]:
      for clause in clauses:
        var pick = ""
        # Pass 1: something already chosen or queued satisfies the clause.
        block already:
          for alt in clause.alternatives:
            for p in providersOf(index, alt.name):
              if p in chosen or p in queued:
                pick = p
                break already
        # Pass 2: the first alternative the index can satisfy.
        if pick.len == 0:
          block first:
            for alt in clause.alternatives:
              let ps = providersOf(index, alt.name)
              if ps.len > 0:
                pick = ps[0]
                break first
        if pick.len == 0:
          var e = newException(AptClosureError,
            "dependency '" & clause.alternatives[0].name & "' of '" & name &
            "' is not in the index")
          e.rootPackage = (if roots.len > 0: roots[0] else: "")
          e.missingDep = clause.alternatives[0].name
          raise e
        if pick notin queued:
          queue.add(pick)
          queued.incl(pick)
  result.sort(proc (a, b: AptPackageRecord): int = cmp(a.name, b.name))

proc buildAptClosureLock*(archive, suite: string; components: seq[string];
                          architecture, snapshot, inReleaseSha256: string;
                          indexes: seq[AptIndexDigest];
                          roots: seq[string];
                          members: seq[AptPackageRecord]): AptClosureLock =
  ## Assemble and validate a lock from a resolved member set.
  result = AptClosureLock(archive: archive.strip(chars = {'/'},
      leading = false), suite: suite, components: components,
    architecture: architecture, snapshot: snapshot,
    inReleaseSha256: inReleaseSha256.toLowerAscii(), indexes: indexes,
    roots: roots)
  for m in members:
    result.debs.add(AptLockedDeb(name: m.name, version: m.version,
      architecture: m.architecture, filename: m.filename,
      size: m.sizeBytes, sha256: m.sha256.toLowerAscii()))
  result.debs.sort(proc (a, b: AptLockedDeb): int = cmp(a.name, b.name))
  validateAptClosureLock(result)

