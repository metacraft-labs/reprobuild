type
  AptLockedDeb* = object
    ## One member of a closure, pinned by its archive bytes.
    name*: string          ## ``Package:``
    version*: string       ## ``Version:`` (may carry an epoch ``N:``)
    architecture*: string  ## ``Architecture:`` (``armhf``, ``all``, ...)
    filename*: string      ## pool path relative to the archive URL
    size*: int64           ## ``Size:``
    sha256*: string        ## ``SHA256:`` (lowercase hex)

  AptIndexDigest* = object
    ## A ``Packages`` index that was read, with the digest the signed
    ## ``InRelease`` gave for it. Provenance only; realisation does not
    ## re-read indexes.
    path*: string          ## e.g. ``main/binary-armhf/Packages.xz``
    sha256*: string

  AptClosureLock* = object
    archive*: string            ## archive base URL, no trailing ``/``
    suite*: string              ## codename, e.g. ``trixie``
    components*: seq[string]    ## e.g. ``@["main"]``
    architecture*: string       ## host architecture, e.g. ``armhf``
    snapshot*: string           ## snapshot timestamp, ``""`` when none
    inReleaseSha256*: string    ## digest of the verified ``InRelease``
    indexes*: seq[AptIndexDigest]
    roots*: seq[string]         ## requested packages, in request order
    debs*: seq[AptLockedDeb]    ## every member, sorted by name

const
  NameChars = {'a'..'z', '0'..'9', '.', '+', '-'}
  VersionChars = {'A'..'Z', 'a'..'z', '0'..'9', '.', '+', '~', ':', '-'}
  ArchChars = {'a'..'z', '0'..'9', '-'}
  HexChars = {'0'..'9', 'a'..'f'}
  # Pool filenames are Debian package filenames under ``pool/``; ``%``
  # (systemd specifier), whitespace, quotes and ``\`` never occur in them.
  FilenameChars = {'A'..'Z', 'a'..'z', '0'..'9', '.', '+', '~', '-', '_',
                   '/', ':'}
  UrlChars = {'A'..'Z', 'a'..'z', '0'..'9', '.', '-', '_', '/', ':', '~',
              '+'}

proc raiseLock(msg: string) {.noreturn.} =
  raise newException(EAptClosureLock, "apt closure lock: " & msg)

proc allIn(s: string; chars: set[char]): bool =
  if s.len == 0: return false
  for c in s:
    if c notin chars: return false
  true

proc checkName(field, v: string) =
  if not allIn(v, NameChars) or v[0] notin {'a'..'z', '0'..'9'}:
    raiseLock(field & " '" & v & "' is not a Debian package name")

proc checkVersion(field, v: string) =
  if not allIn(v, VersionChars) or v[0] notin {'0'..'9'}:
    raiseLock(field & " '" & v & "' is not a Debian version")

proc checkArch(field, v: string) =
  if not allIn(v, ArchChars):
    raiseLock(field & " '" & v & "' is not a Debian architecture")

proc checkSha(field, v: string) =
  if v.len != 64 or not allIn(v, HexChars):
    raiseLock(field & " '" & v & "' is not a lowercase SHA-256")

proc checkRelPath(field, v: string) =
  if not allIn(v, FilenameChars) or v.startsWith("/") or
      v.split('/').anyIt(it.len == 0 or it == "." or it == ".."):
    raiseLock(field & " '" & v & "' is not a clean relative path")

proc checkUrl(v: string) =
  if not (v.startsWith("http://") or v.startsWith("https://")) or
      not allIn(v, UrlChars) or v.endsWith("/"):
    raiseLock("archive '" & v &
      "' is not an http(s) URL without a trailing '/'")

proc validateAptClosureLock*(lock: AptClosureLock) =
  ## Raise ``EAptClosureLock`` unless every field is well-formed and the
  ## roots are members. Called by the parser and by the builder, so a lock
  ## value that exists is always one the realiser can act on.
  checkUrl(lock.archive)
  checkName("suite", lock.suite)
  if lock.components.len == 0:
    raiseLock("no components")
  for c in lock.components: checkName("component", c)
  checkArch("architecture", lock.architecture)
  if lock.architecture == "all":
    raiseLock("architecture 'all' is not a host architecture")
  if lock.snapshot.len > 0 and not allIn(lock.snapshot,
      {'0'..'9', 'T', 'Z'}):
    raiseLock("snapshot '" & lock.snapshot & "' is not a timestamp")
  checkSha("inrelease-sha256", lock.inReleaseSha256)
  for ix in lock.indexes:
    checkRelPath("index path", ix.path)
    checkSha("index sha256", ix.sha256)
  if lock.roots.len == 0:
    raiseLock("no root packages")
  if lock.debs.len == 0:
    raiseLock("no members")
  var names = initHashSet[string]()
  var prev = ""
  for d in lock.debs:
    checkName("deb name", d.name)
    checkVersion("deb " & d.name & " version", d.version)
    checkArch("deb " & d.name & " architecture", d.architecture)
    if d.architecture notin [lock.architecture, "all"]:
      raiseLock("deb " & d.name & " is " & d.architecture &
        ", not " & lock.architecture & " or all")
    checkRelPath("deb " & d.name & " filename", d.filename)
    if d.size <= 0:
      raiseLock("deb " & d.name & " has a non-positive size")
    checkSha("deb " & d.name & " sha256", d.sha256)
    if d.name in names:
      raiseLock("deb " & d.name & " appears twice")
    if prev.len > 0 and cmp(d.name, prev) < 0:
      raiseLock("debs are not sorted by name ('" & d.name & "' after '" &
        prev & "')")
    names.incl(d.name)
    prev = d.name
  var seenRoots = initHashSet[string]()
  for r in lock.roots:
    checkName("root", r)
    if r in seenRoots:
      raiseLock("root " & r & " appears twice")
    seenRoots.incl(r)
    if r notin names:
      raiseLock("root " & r & " is not a member of the closure")

proc renderAptClosureLock*(lock: AptClosureLock): string =
  ## Canonical text of a lock: one ``key value`` per line, members sorted by
  ## name. Two equal locks render to identical bytes. The text contains no
  ## ``"`` and no ``#`` so it embeds verbatim in a ``system.nim`` string
  ## field.
  validateAptClosureLock(lock)
  result = AptClosureLockHeader & "\n"
  result.add("archive " & lock.archive & "\n")
  result.add("suite " & lock.suite & "\n")
  result.add("components " & lock.components.join(",") & "\n")
  result.add("architecture " & lock.architecture & "\n")
  result.add("snapshot " & (if lock.snapshot.len > 0: lock.snapshot
                            else: "-") & "\n")
  result.add("inrelease-sha256 " & lock.inReleaseSha256 & "\n")
  for ix in lock.indexes:
    result.add("index " & ix.path & " " & ix.sha256 & "\n")
  for r in lock.roots:
    result.add("root " & r & "\n")
  for d in lock.debs:
    result.add("deb " & d.name & " " & d.version & " " & d.architecture &
      " " & d.filename & " " & $d.size & " " & d.sha256 & "\n")

proc parseAptClosureLock*(text: string): AptClosureLock =
  ## Strict parser for ``renderAptClosureLock``'s format. Unknown keys,
  ## repeated singleton keys, comments and malformed values are refusals:
  ## the lock is machine-written and a deviation means it was edited or
  ## corrupted.
  var lines: seq[string] = @[]
  for raw in text.splitLines():
    let l = raw.strip(leading = false, trailing = true, chars = {'\r'})
    if l.strip().len == 0: continue
    lines.add(l.strip())
  if lines.len == 0 or lines[0] != AptClosureLockHeader:
    raiseLock("missing '" & AptClosureLockHeader & "' header")
  var seen = initHashSet[string]()
  proc single(key: string) =
    if key in seen: raiseLock("key '" & key & "' appears twice")
    seen.incl(key)
  for l in lines[1 .. ^1]:
    let sp = l.find(' ')
    if sp <= 0: raiseLock("line '" & l & "' has no value")
    let key = l[0 ..< sp]
    let val = l[sp + 1 .. ^1]
    let parts = val.splitWhitespace()
    case key
    of "archive": single(key); result.archive = val
    of "suite": single(key); result.suite = val
    of "components":
      single(key)
      result.components = val.split(',')
    of "architecture": single(key); result.architecture = val
    of "snapshot":
      single(key)
      result.snapshot = if val == "-": "" else: val
    of "inrelease-sha256": single(key); result.inReleaseSha256 = val
    of "index":
      if parts.len != 2: raiseLock("index line '" & l & "' is malformed")
      result.indexes.add(AptIndexDigest(path: parts[0], sha256: parts[1]))
    of "root":
      if parts.len != 1: raiseLock("root line '" & l & "' is malformed")
      result.roots.add(parts[0])
    of "deb":
      if parts.len != 6: raiseLock("deb line '" & l & "' is malformed")
      var size: int64
      try: size = parseBiggestInt(parts[4]).int64
      except ValueError: raiseLock("deb line '" & l & "' has a bad size")
      result.debs.add(AptLockedDeb(name: parts[0], version: parts[1],
        architecture: parts[2], filename: parts[3], size: size,
        sha256: parts[5]))
    else:
      raiseLock("unknown key '" & key & "'")
  for k in ["archive", "suite", "components", "architecture", "snapshot",
            "inrelease-sha256"]:
    if k notin seen: raiseLock("missing key '" & k & "'")
  validateAptClosureLock(result)

