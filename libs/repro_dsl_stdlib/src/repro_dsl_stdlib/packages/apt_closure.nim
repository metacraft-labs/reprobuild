## ``package(apt, ...)`` closures for system units: lock, store realiser and
## the native systemd binding.
##
## Governing spec: ``reprobuild-pm/spec/ReproOS-Add-On-Mode.md`` §2.3 and
## §8.3 ("Foreign (`apt`) package closures in system units" and "How a
## closure is pinned, stored and bound"). The public counterpart is
## ``docs/foreign-package-runtime.md`` §"System units: native binding".
##
## Three pieces, each usable on its own:
##
##   * **The closure lock** (``AptClosureLock``). A closure is resolved once,
##     ahead of planning, from a verified archive index into a plain-text
##     lock (``repro-apt-closure-lock v1``) that pins every ``.deb`` by pool
##     filename, size and SHA-256. ``resolveAptClosureRecords`` computes the
##     member set (``Depends:`` + ``Pre-Depends:`` of the roots plus the
##     archive's ``Essential: yes`` set — Debian Policy §3.8,
##     https://www.debian.org/doc/debian-policy/ch-binary.html#essential-packages);
##     ``buildAptClosureLock`` / ``renderAptClosureLock`` /
##     ``parseAptClosureLock`` are the lock's constructor and codec. The lock
##     is generated by ``repro-harvest-apt --emit-lock``.
##
##   * **The realiser** (``realiseAptClosure``). Downloads each member,
##     verifies it against the lock, unpacks ``data.tar.*`` into a
##     content-addressed per-``.deb`` prefix, and builds the closure prefix
##     as a hard-link union of the members. No maintainer script runs and
##     nothing outside the store root is written: in particular nothing is
##     installed into ``/usr`` and ``apt``/``dpkg`` are never invoked.
##
##   * **The unit binding** (``renderUnitWithAptClosure``). Adds
##     ``BindReadOnlyPaths=<closure>/usr:/usr`` and
##     ``InaccessiblePaths=-/etc/ld.so.preload`` to a unit's ``[Service]``
##     section, so the daemon runs from its closure with no wrapper process
##     between systemd and it — ``AmbientCapabilities=``, ``DynamicUser=``,
##     ``LoadCredential=`` and ``DeviceAllow=`` keep their native meaning.
##     See https://www.freedesktop.org/software/systemd/man/latest/systemd.exec.html#BindPaths=
##     and #ReadWritePaths= (``InaccessiblePaths=``).
##
## The closure prefix path is a pure function of the lock, so the planner can
## render the unit offline and the host realises exactly the path the unit
## names.

