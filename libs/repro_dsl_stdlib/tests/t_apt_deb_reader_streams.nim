## The ``.deb`` reader (``apt_jammy.extractDebDataMemberToTar``, which the
## add-on's apt closure realiser builds on) reads an archive's ``ar``
## headers by offset and copies the data member in fixed-size chunks: its
## memory does not grow with the archive. An add-on apply unit runs under
## ``MemoryMax=``, and a closure member can be hundreds of MB.
##
## Falsifying build (scripts/run_addon_unit_mutation.sh
## t_apt_deb_reader_streams apt-deb-reader-reads-whole-file): the reader
## loads the whole archive, and the peak-RSS check goes red.
##
## Mocks: none. The archive is a real ar(5) file written here (the format
## dpkg-deb writes: the magic, then 60-byte member headers, payloads padded
## to even offsets), read by the real reader. The test runs the large case
## first, in its own binary, so the peak resident set before it is this
## binary's baseline.

import std/[os, posix, strutils, unittest]

import repro_dsl_stdlib/packages/apt_jammy

proc peakRssKiB(): int64 =
  var ru: Rusage
  doAssert getrusage(RUSAGE_SELF, addr ru) == 0
  ru.ru_maxrss.int64

proc arHeader(name: string; size: int64): string =
  ## One ar(5) member header: name/16, mtime/12, uid/6, gid/6, mode/8,
  ## size/10, "`\n".
  result = alignLeft(name & "/", 16) & alignLeft("0", 12) &
    alignLeft("0", 6) & alignLeft("0", 6) & alignLeft("100644", 8) &
    alignLeft($size, 10) & "`\n"
  doAssert result.len == 60

proc byteAt(i: int64): char = char((i * 131 + (i shr 17)) and 0xff)

proc writeDeb(path: string; dataSize: int64; truncateData = false) =
  ## A .deb with debian-binary, control.tar, a data.tar of ``dataSize``
  ## generated bytes, and one more member after it.
  var f = open(path, fmWrite)
  defer: f.close()
  f.write("!<arch>\n")
  f.write(arHeader("debian-binary", 4)); f.write("2.0\n")
  f.write(arHeader("control.tar", 10)); f.write("0123456789")
  f.write(arHeader("data.tar", dataSize))
  var chunk = newString(1024 * 1024)
  var written = 0'i64
  let limit = if truncateData: dataSize div 2 else: dataSize
  while written < limit:
    let n = int(min(int64(chunk.len), limit - written))
    for i in 0 ..< n: chunk[i] = byteAt(written + i)
    doAssert f.writeBuffer(addr chunk[0], n) == n
    written += n
  if truncateData: return
  if (dataSize and 1) == 1: f.write("\n")
  f.write(arHeader("_trailer", 2)); f.write("ok")

let root = getTempDir() / ("t_deb_reader_" & $getCurrentProcessId())
removeDir(root)
createDir(root)

suite "the .deb reader streams":
  test "a 256 MiB data member is extracted with bounded memory":
    const Size = 256'i64 * 1024 * 1024 + 1   # odd: the ar padding matters
    let deb = root / "big.deb"
    writeDeb(deb, Size)
    let before = peakRssKiB()
    extractDebDataMemberToTar(deb, root / "big.tar")
    let grown = peakRssKiB() - before
    checkpoint "peak RSS grew by " & $grown & " KiB"
    # A few chunks plus allocator noise; loading the archive adds 256 MiB.
    check grown < 32 * 1024
    check getFileSize(root / "big.tar") == Size
    # Every byte where it belongs (sampled across the member, both ends).
    var f = open(root / "big.tar", fmRead)
    for at in [0'i64, 1, 4095, 1_000_003, Size div 2, Size - 2, Size - 1]:
      f.setFilePos(at)
      var c: char
      check f.readBuffer(addr c, 1) == 1
      check c == byteAt(at)
    f.close()
    removeFile(deb)
    removeFile(root / "big.tar")

suite "the .deb reader's refusals":
  test "a data member that runs past the end is not a data member":
    let deb = root / "truncated.deb"
    writeDeb(deb, 4096, truncateData = true)
    expect AptExtractError:
      extractDebDataMemberToTar(deb, root / "t.tar")

  test "a file that is not an ar archive has no data member":
    writeFile(root / "not.deb", "not an archive at all")
    expect AptExtractError:
      extractDebDataMemberToTar(root / "not.deb", root / "n.tar")

  test "a small member is copied byte for byte":
    let deb = root / "small.deb"
    writeDeb(deb, 3)
    extractDebDataMemberToTar(deb, root / "small.tar")
    check readFile(root / "small.tar") == $byteAt(0) & $byteAt(1) & $byteAt(2)

removeDir(root)
