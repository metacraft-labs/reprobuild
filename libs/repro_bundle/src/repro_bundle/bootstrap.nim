## `restore.sh`: the bootstrap a machine without `repro` runs
## (Workspace-Bundles.md §7). It restores the Nix half with nothing but
## bash, curl, tar, sha256sum, df and nix-store, then hands over to the
## `repro` that half contains, which restores the remaining halves.
##
## Everything it needs is baked in at create time (the half's id, parts,
## hashes and, for a GitHub source, each file's branch; the zstd and repro
## store paths), so it reads no JSON and needs no interpreter beyond bash.
##
## It is a cloud session's setup script, and a failing setup script stops the
## session from starting. So it logs every failure and exits 0, unless
## `REPRO_BUNDLE_STRICT=1`.

import std/[json, strutils]
import ./nix_half
import ./github

proc q(s: string): string =
  "'" & s.replace("'", "'\\''") & "'"

proc renderRestoreScript*(latest: JsonNode; hasNix: bool;
                          h: NixHalf): string =
  let system = latest["system"].getStr()
  let name = latest["name"].getStr()
  var s = """#!/usr/bin/env bash
# restore.sh — generated by `repro bundle create` for bundle """ & q(name) &
    " (" & system & """).
#
# Usage: curl -fsS <base>/<bundle>/<system>/restore.sh | bash -s -- <source> [flags]
#        bash restore.sh <source> [flags]
# <source> is the bundle's URL or directory (<base>/<bundle>), or
# github:OWNER/REPO@COMMIT/<bundle> for a bundle published to GitHub. The
# flags are passed on to `repro bundle restore` (for example --activate).
#
# Restores the bundle's Nix half without repro and without evaluation, then
# runs `repro bundle restore` from that half for the sources and native-store
# halves. Logs to $REPRO_BUNDLE_LOG (/var/log/repro-bundle.log) and exits 0
# even on failure, so the session still starts; REPRO_BUNDLE_STRICT=1 makes
# a failure an error. See reprobuild's docs/workspace-bundles.md.
set -uo pipefail
SRC="${1:-${REPRO_BUNDLE_BASE:-}}"
[ $# -gt 0 ] && shift
LOG="${REPRO_BUNDLE_LOG:-/var/log/repro-bundle.log}"
{ mkdir -p "$(dirname "$LOG")" && touch "$LOG"; } 2>/dev/null || LOG=/dev/null
exec > >(tee -a "$LOG") 2>&1
start=$(date +%s)
log() { echo "[repro-bundle +$(( $(date +%s) - start ))s] $*"; }
done_with() { log "$*"; [ "${REPRO_BUNDLE_STRICT:-0}" = 1 ] && exit 1; exit 0; }
echo "[repro-bundle] $(date -u +%FT%TZ) bundle=""" & q(name) & """ source=$SRC"
[ -n "$SRC" ] || done_with "usage: restore.sh <bundle-url-dir-or-github-source> [repro bundle restore flags]"
SRC="${SRC%/}"
PARALLEL="${REPRO_BUNDLE_PARALLEL:-16}"
# Tests only: restore the Nix half into another store root instead of /.
ROOT="${REPRO_BUNDLE_NIX_ROOT:-/}"
store=(); [ "$ROOT" != / ] && store=(--store "$ROOT")
case "$SRC" in
  github:*)
    GH="${SRC#github:}"; GH_REPO="${GH%%@*}"; GH_REST="${GH#*@}"; GH_COMMIT="${GH_REST%%/*}"
    RAW="${REPRO_BUNDLE_GITHUB_RAW:-https://raw.githubusercontent.com}"
    API="${REPRO_BUNDLE_GITHUB_API:-https://api.github.com}" ;;
esac
# nix.sh reads variables a setup script may not have; -u would end the script.
set +u; [ -r /etc/profile.d/nix.sh ] && . /etc/profile.d/nix.sh >/dev/null 2>&1; set -u
"""
  if hasNix:
    let rel = system & "/" & NixHalfDir & "/" & h.id
    let files = halfFiles(NixManifestName, h.parts, @[h.registration.file])
    var sums = ""
    for p in h.parts:
      sums.add(p.sha256 & "  " & p.file & "\n")
    sums.add(h.registration.sha256 & "  " & h.registration.file & "\n")
    # file<TAB>branch, for a GitHub source (§6.1: deterministic layout).
    var refs = ""
    for p in h.parts:
      refs.add(p.file & "\t" & githubRefOf(name, rel, files, p.file) & "\n")
    refs.add(h.registration.file & "\t" &
      githubRefOf(name, rel, files, h.registration.file) & "\n")
    var roots = ""
    for r in h.shellRoots: roots.add(" " & q(r))
    var partFiles = ""
    for p in h.parts: partFiles.add(" " & q(p.file))
    s.add("NIX_DIR=" & q(rel) & "\n")
    s.add("ZSTD=" & q(h.zstd) & "\nREPRO=" & q(h.repro) & "\n")
    s.add("NIX_UNPACKED=" & $h.unpackedBytes & "\nNIX_COMPRESSED=" &
      $h.compressedBytes & "\n")
    s.add("ROOTS=(" & roots & " )\nPARTS=(" & partFiles & " )\n")
    s.add("SUMS=" & q(sums) & "\nREFS=" & q(refs) & "\n")
    s.add("""
command -v nix-store >/dev/null || done_with "nix is not installed; nothing restored"
if nix-store "${store[@]}" --check-validity "${ROOTS[@]}" >/dev/null 2>&1; then
  log "nix half already present"
else
  mkdir -p "$ROOT"
  avail=$(df --output=avail -B1 "$( [ "$ROOT" = / ] && [ -d /nix ] && echo /nix || echo "$ROOT" )" | tail -1)
  need=$(( NIX_UNPACKED + (1 << 30) ))
  (( avail >= need )) || done_with "not enough disk: the nix half unpacks to $(( NIX_UNPACKED >> 20 )) MiB, $(( avail >> 20 )) MiB free (1 GiB margin)"
  case "$SRC" in
    http://*|https://*|github:*)
      shm=$(df --output=avail -B1 /dev/shm 2>/dev/null | tail -1 || echo 0)
      if (( NIX_COMPRESSED * 2 < ${shm:-0} )); then work=$(mktemp -d /dev/shm/repro-bundle.XXXXXX)
      else work=$(mktemp -d /var/tmp/repro-bundle.XXXXXX); fi
      trap 'rm -rf "$work"' EXIT
      log "nix half: $(( NIX_COMPRESSED >> 20 )) MiB to download, $(( NIX_UNPACKED >> 20 )) MiB to unpack"
      case "$SRC" in
        github:*)
          get() { curl -fsSL --retry 3 -o "$work/$1" "$RAW/$GH_REPO/$2/$1" 2>/dev/null \
                    || curl -fsSL --retry 3 -H 'Accept: application/vnd.github.raw' \
                         -o "$work/$1" "$API/repos/$GH_REPO/contents/$1?ref=${2//\//%2F}"; }
          export -f get; export work RAW API GH_REPO
          printf '%s' "$REFS" | tr '\t\n' '\0\0' | xargs -0 -n2 -P "$PARALLEL" bash -c 'get "$0" "$1"' \
            || done_with "nix half download from $GH_REPO failed" ;;
        *)
          printf '%s' "$SUMS" | awk '{print $2}' \
            | xargs -P "$PARALLEL" -I{} curl -fsS --retry 3 -o "$work/{}" "$SRC/$NIX_DIR/{}" \
            || done_with "nix half download failed" ;;
      esac
      dir="$work" ;;
    *) dir="$SRC/$NIX_DIR" ;;
  esac
  ( cd "$dir" && printf '%s' "$SUMS" | sha256sum --quiet -c - ) || done_with "nix half did not verify"
  if command -v zstd >/dev/null; then Z=zstd; else
    nix-store --realise "$ZSTD" >/dev/null 2>&1 || done_with "cannot realise $ZSTD"
    Z="$ZSTD/bin/zstd"
  fi
  ( cd "$dir" && cat "${PARTS[@]}" ) | "$Z" -q -dc --long=27 | tar -C "$ROOT" --skip-old-files -xf - \
    || done_with "nix half unpack failed"
  "$Z" -q -dc "$dir/registration" | nix-store "${store[@]}" --load-db || done_with "nix-store --load-db failed"
  nix-store "${store[@]}" --check-validity "${ROOTS[@]}" >/dev/null || done_with "registration incomplete"
  [ "$dir" = "${work:-}" ] && rm -f "$work"/*
  log "nix half restored"
fi
prefix=""; [ "$ROOT" != / ] && prefix="$ROOT"
command -v zstd >/dev/null || export PATH="$prefix$ZSTD/bin:$PATH"
R="$prefix$REPRO/bin/repro"
[ -n "$REPRO" ] && [ -x "$R" ] || R="$(command -v repro)" || done_with "no repro: the bundle carries none and none is on PATH"
extra=(); [ "$ROOT" != / ] && extra=(--nix-root="$ROOT")
"$R" bundle restore "$SRC" --after-bootstrap "${extra[@]}" "$@" || done_with "repro bundle restore failed (exit $?)"
log "done"
""")
  else:
    s.add("""
R="$(command -v repro)" || done_with "this bundle has no Nix half to bootstrap from; install repro first"
"$R" bundle restore "$SRC" "$@" || done_with "repro bundle restore failed (exit $?)"
log "done"
""")
  s
