## `restore.sh`: the bootstrap a machine without `repro` runs
## (Workspace-Bundles.md §7). It restores the Nix half with nothing but
## bash, curl, tar, sha256sum, df, flock, nix-store and nix-hash, then hands
## over to
## the `repro` that half contains, which restores the remaining halves.
##
## Everything it needs is baked in at create time (the half's id, parts,
## hashes and, for a GitHub source, each file's branch; the zstd and repro
## store paths), so it reads no JSON and needs no interpreter beyond bash.
## It also carries the SHA-256 of the `latest.json` it was generated beside
## and hands it over with `--latest-sha256`, so the `repro` it restored reads
## that `latest.json` or none: a writer of a local source directory cannot
## replace it once the Nix half has been verified (Workspace-Bundles.md §7,
## §9).
##
## It is a cloud session's setup script, and a failing setup script stops the
## session from starting. So it logs every failure and exits 0, unless
## `REPRO_BUNDLE_STRICT=1`.
##
## It applies the same confinement as `restoreNixHalf`, in bash and awk:
## before anything is written or removed it lists the archive with the tar
## that unpacks it and refuses unless every member lies inside a registered
## store path (the rules of `repro_local_store/tar_members` and
## `nix_half.nixListingProblem`), the unpack excludes the paths Nix already
## holds as valid, and a plain `http://` source or GitHub transport is
## refused, with every curl limited to https:// (and file://).

import std/[json, strutils]
import ./nix_half
import ./github

proc q(s: string): string =
  "'" & s.replace("'", "'\\''") & "'"

proc renderRestoreScript*(latest: JsonNode; hasNix: bool; h: NixHalf;
                          latestSha256: string): string =
  ## `latestSha256` is the SHA-256 of the bytes of the `latest.json` written
  ## beside this script. The handoff passes it on, and `repro bundle
  ## restore` refuses any other `latest.json`.
  if latestSha256.len != 64 or
      not latestSha256.allCharsInSet({'0' .. '9', 'a' .. 'f'}):
    raise newException(ValueError,
      "restore.sh needs the SHA-256 of its latest.json, got " &
      latestSha256.escape)
  let system = latest["system"].getStr()
  let name = latest["name"].getStr()
  var s = """#!/usr/bin/env bash
# restore.sh — generated by `repro bundle create` for bundle """ & q(name) &
    " (" & system & """).
#
# Usage: curl --proto '=https' -fsS <base>/<bundle>/<system>/restore.sh | bash -s -- <source> [flags]
#        bash restore.sh <source> [flags]
# <source> is the bundle's URL or directory (<base>/<bundle>), or
# github:OWNER/REPO@COMMIT/<bundle> for a bundle published to GitHub. The
# flags are passed on to `repro bundle restore` (for example --activate).
#
# Restores the bundle's Nix half without repro and without evaluation, then
# runs `repro bundle restore` from that half for the sources and native-store
# halves. Logs to $REPRO_BUNDLE_LOG (/var/log/repro-bundle.log) and exits 0
# even on failure, so the session still starts; REPRO_BUNDLE_STRICT=1 makes
# a failure an error. See reprobuild's docs/workspace-bundles.md.
set -uo pipefail
SRC="${1:-${REPRO_BUNDLE_BASE:-}}"
[ $# -gt 0 ] && shift
LOG="${REPRO_BUNDLE_LOG:-/var/log/repro-bundle.log}"
{ mkdir -p "$(dirname "$LOG")" && touch "$LOG"; } 2>/dev/null || LOG=/dev/null
exec > >(tee -a "$LOG") 2>&1
start=$(date +%s)
log() { echo "[repro-bundle +$(( $(date +%s) - start ))s] $*"; }
done_with() { log "$*"; [ "${REPRO_BUNDLE_STRICT:-0}" = 1 ] && exit 1; exit 0; }
echo "[repro-bundle] $(date -u +%FT%TZ) bundle=""" & q(name) & """ source=$SRC"
[ -n "$SRC" ] || done_with "usage: restore.sh <bundle-url-dir-or-github-source> [repro bundle restore flags]"
SRC="${SRC%/}"
# Nothing in a bundle is signed: its parts are checked against hashes from the
# same place. A plain http:// source would let anyone on the path choose them.
case "$SRC" in
  [Hh][Tt][Tt][Pp]://*) done_with "refusing the plain http:// source $SRC: a bundle is fetched over https:// (or from a directory or a github: source)" ;;
esac
# Every download: https:// or file:// only, and a redirect only to https://.
CURL_PROTO="--proto =https,file --proto-redir =https"
PARALLEL="${REPRO_BUNDLE_PARALLEL:-16}"
# Tests only: restore the Nix half into another store root instead of /.
ROOT="${REPRO_BUNDLE_NIX_ROOT:-/}"
store=(); [ "$ROOT" != / ] && store=(--store "$ROOT")
case "$SRC" in
  github:*)
    GH="${SRC#github:}"; GH_REPO="${GH%%@*}"; GH_REST="${GH#*@}"; GH_COMMIT="${GH_REST%%/*}"
    RAW="${REPRO_BUNDLE_GITHUB_RAW:-https://raw.githubusercontent.com}"
    API="${REPRO_BUNDLE_GITHUB_API:-https://api.github.com}"
    for v in "REPRO_BUNDLE_GITHUB_RAW=$RAW" "REPRO_BUNDLE_GITHUB_API=$API"; do
      case "${v#*=}" in
        https://*|file://*) ;;
        *) done_with "refusing ${v}: the GitHub transport is fetched over https:// (or file:// in tests)" ;;
      esac
    done ;;
esac
# nix.sh reads variables a setup script may not have; -u would end the script.
set +u; [ -r /etc/profile.d/nix.sh ] && . /etc/profile.d/nix.sh >/dev/null 2>&1; set -u
"""
  if hasNix:
    let rel = system & "/" & NixHalfDir & "/" & h.id
    let files = halfFiles(NixManifestName, h.parts, @[h.registration.file])
    var sums = ""
    for p in h.parts:
      sums.add(p.sha256 & "  " & p.file & "\n")
    sums.add(h.registration.sha256 & "  " & h.registration.file & "\n")
    # bytes<SPACE>file: a local source is copied no further than this.
    var sizes = ""
    for p in h.parts:
      sizes.add($p.bytes & " " & p.file & "\n")
    sizes.add($h.registration.bytes & " " & h.registration.file & "\n")
    # file<TAB>branch, for a GitHub source (§6.1: deterministic layout).
    var refs = ""
    for p in h.parts:
      refs.add(p.file & "\t" & githubRefOf(name, rel, files, p.file) & "\n")
    refs.add(h.registration.file & "\t" &
      githubRefOf(name, rel, files, h.registration.file) & "\n")
    var roots = ""
    for r in h.shellRoots: roots.add(" " & q(r))
    var partFiles = ""
    for p in h.parts: partFiles.add(" " & q(p.file))
    s.add("NIX_DIR=" & q(rel) & "\n")
    s.add("LATEST_SHA256=" & latestSha256 & "\n")
    s.add("ZSTD=" & q(h.zstd) & "\nREPRO=" & q(h.repro) & "\n")
    s.add("NIX_UNPACKED=" & $h.unpackedBytes & "\nNIX_COMPRESSED=" &
      $h.compressedBytes & "\n")
    s.add("ROOTS=(" & roots & " )\nPARTS=(" & partFiles & " )\n")
    s.add("SUMS=" & q(sums) & "\nSIZES=" & q(sizes) & "\nREFS=" & q(refs) &
      "\n")
    s.add("""
command -v nix-store >/dev/null || done_with "nix is not installed; nothing restored"
if nix-store "${store[@]}" --check-validity "${ROOTS[@]}" >/dev/null 2>&1; then
  log "nix half already present"
else
  mkdir -p "$ROOT"
  avail=$(df --output=avail -B1 "$( [ "$ROOT" = / ] && [ -d /nix ] && echo /nix || echo "$ROOT" )" | tail -1)
  need=$(( NIX_UNPACKED + (1 << 30) ))
  (( avail >= need )) || done_with "not enough disk: the nix half unpacks to $(( NIX_UNPACKED >> 20 )) MiB, $(( avail >> 20 )) MiB free (1 GiB margin)"
  # Every source is staged in a directory only this run can write, and only
  # the staged files are verified and read: a local source's directory may
  # be writable by others, who could otherwise swap a part between its hash
  # check and the unpack (Workspace-Bundles.md §7 step 2, §9).
  shm=$(df --output=avail -B1 /dev/shm 2>/dev/null | tail -1 || echo 0)
  if (( NIX_COMPRESSED * 2 < ${shm:-0} )); then work=$(mktemp -d /dev/shm/repro-bundle.XXXXXX)
  else work=$(mktemp -d /var/tmp/repro-bundle.XXXXXX); fi \
    || done_with "cannot create a staging directory"
  trap 'rm -rf "$work"' EXIT
  case "$SRC" in
    https://*|github:*)
      log "nix half: $(( NIX_COMPRESSED >> 20 )) MiB to download, $(( NIX_UNPACKED >> 20 )) MiB to unpack"
      case "$SRC" in
        github:*)
          get() { curl -fsSL --retry 3 $CURL_PROTO -o "$work/$1" "$RAW/$GH_REPO/$2/$1" 2>/dev/null \
                    || curl -fsSL --retry 3 $CURL_PROTO -H 'Accept: application/vnd.github.raw' \
                         -o "$work/$1" "$API/repos/$GH_REPO/contents/$1?ref=${2//\//%2F}"; }
          export -f get; export work RAW API GH_REPO CURL_PROTO
          printf '%s' "$REFS" | tr '\t\n' '\0\0' | xargs -0 -n2 -P "$PARALLEL" bash -c 'get "$0" "$1"' \
            || done_with "nix half download from $GH_REPO failed" ;;
        *)
          printf '%s' "$SUMS" | awk '{print $2}' \
            | xargs -P "$PARALLEL" -I{} curl -fsS --retry 3 $CURL_PROTO -o "$work/{}" "$SRC/$NIX_DIR/{}" \
            || done_with "nix half download failed" ;;
      esac ;;
    *)
      # At most each file's declared size is copied: a part replaced by
      # something larger, or by a link to /dev/zero, cannot fill the staging
      # filesystem, and its truncated copy fails the hash check.
      from="${SRC#file://}/$NIX_DIR"
      log "nix half: $(( NIX_COMPRESSED >> 20 )) MiB to copy from $from, $(( NIX_UNPACKED >> 20 )) MiB to unpack"
      printf '%s' "$SIZES" | while read -r n f; do
        head -c "$n" -- "$from/$f" > "$work/$f" || exit 1
      done || done_with "nix half copy from $from failed" ;;
  esac
  dir="$work"
  ( cd "$dir" && printf '%s' "$SUMS" | sha256sum --quiet -c - ) || done_with "nix half did not verify"
  if command -v zstd >/dev/null; then Z=zstd; else
    nix-store --realise "$ZSTD" >/dev/null 2>&1 || done_with "cannot realise $ZSTD"
    Z="$ZSTD/bin/zstd"
  fi
  # Only the half's invalid paths are restored; a valid path is Nix's. What
  # an interrupted unpack or substitution left at an invalid path is deleted
  # first, so --skip-old-files never keeps a truncated file; each restored
  # path's NAR hash must match the registration before it is registered.
  # A run killed anywhere leaves those paths invalid, and the next starts
  # them over (Workspace-Bundles.md §7 step 3). Each invalid path's Nix lock
  # is held from the validity re-check to the registration (step 3.3).
  command -v nix-hash >/dev/null || done_with "nix-hash is not installed; nothing restored"
  command -v flock >/dev/null || done_with "flock (util-linux) is not installed; nothing restored"
  meta=$(mktemp -d "${TMPDIR:-/tmp}/repro-bundle-meta.XXXXXX") || done_with "cannot create a scratch directory"
  # Nix's lock release (PathLocks with deletion): unlink the lock file, then
  # write a byte to it, so a waiter that gets it next sees it is stale. A
  # lock file something else deleted is only closed: by now the name may be
  # another writer's lock file.
  lock_files=(); lock_fds=(); gc_fd=""
  linked() { [ "$(stat -L -c %h "/dev/fd/$1" 2>/dev/null)" != 0 ]; }
  release_locks() {
    local i
    for i in "${!lock_fds[@]}"; do
      if linked "${lock_fds[$i]}"; then rm -f "${lock_files[$i]}"; printf d >&"${lock_fds[$i]}"; fi
      eval "exec ${lock_fds[$i]}>&-"
    done
    lock_files=(); lock_fds=()
    [ -z "$gc_fd" ] || eval "exec ${gc_fd}>&-"
    gc_fd=""
  }
  trap 'release_locks; rm -rf "$meta" "${work:-}"' EXIT
  "$Z" -q -dc "$dir/registration" > "$meta/db" || done_with "cannot decompress the registration"
  # nix-store --dump-db: <path> <narHash> <narSize> <deriver> <n> <n refs>.
  # Each path must be /nix/store/<one store-path name>: the registered paths
  # decide where the half's members may be written.
  LC_ALL=C awk -v out="$meta/expected" -v paths="$meta/paths" '
    s == 0 { p = $0; if (p !~ /^\/nix\/store\/[A-Za-z0-9+._?=-]+$/ || substr(p, 12, 1) == ".") { bad = 1; exit 1 }
             s = 1; next }
    s == 1 { h = $0; s = 2; next }
    s == 2 { s = 3; next }  s == 3 { s = 4; next }
    s == 4 { n = $0 + 0; print p "\t" h > out; print p > paths; s = (n > 0) ? 5 : 0; next }
    s == 5 { if (--n == 0) s = 0 }
    END { if (bad || s != 0) exit 1 }' "$meta/db" && [ -s "$meta/paths" ] \
    || done_with "malformed nix half registration"
  # Before anything is written or removed: list the archive with the tar that
  # unpacks it, over the same verified parts, and refuse unless every member
  # lies inside a registered store path. The part hashes come from the same
  # unsigned place as the parts, so this is what confines the unpack. Names
  # are compared in tar's C-quoted form (deterministic: "/" and "." are never
  # escaped), so nothing needs decoding.
  ( cd "$dir" && cat "${PARTS[@]}" ) | "$Z" -q -dc --long=27 \
    | LC_ALL=C tar -tvf - --quoting-style=c --numeric-owner --full-time > "$meta/listing" 2> "$meta/listing.err" \
    || done_with "cannot list the nix half: $(tail -n 3 "$meta/listing.err" | tr '\n' ' ')"
  problem=$(LC_ALL=C awk -v regs="$meta/paths" '
    BEGIN { while ((getline l < regs) > 0) reg[substr(l, 2)] = 1 }
    function fail(msg) { print msg; bad = 1; exit 1 }
    # The index of the quote closing the C-quoted string that opens at s[i].
    function qend(s, i,   c) {
      for (i++; i <= length(s); i++) {
        c = substr(s, i, 1)
        if (c == "\\") i++
        else if (c == "\"") return i
      }
      return 0
    }
    # "" when name n is canonical and lies inside a registered store path.
    function placed(n,   k, c, j) {
      k = split(n, c, "/")
      for (j = 1; j <= k; j++)
        if (c[j] == "" || c[j] == "." || c[j] == "..") return "is not a canonical relative name"
      if (k < 3 || c[1] != "nix" || c[2] != "store" || !(("nix/store/" c[3]) in reg))
        return "lies outside the store paths the half registers"
      return ""
    }
    {
      t = substr($0, 1, 1); q = index($0, "\""); e = q ? qend($0, q) : 0
      if (!e) fail("archive listing line " NR " is not a member: " $0)
      n = substr($0, q + 1, e - q - 1); rest = substr($0, e + 1)
      if (t == "d" && length(n) > 1 && substr(n, length(n)) == "/") n = substr(n, 1, length(n) - 1)
      if (t != "-" && t != "h" && t != "l" && t != "d") fail("member \"" n "\" has type " t ", which a bundle never carries")
      if (t == "h") {
        if (substr(rest, 1, 10) != " link to \"" || qend($0, e + 10) != length($0)) fail("archive listing line " NR " is not a member: " $0)
        g = substr($0, e + 11, length($0) - e - 11)
      } else if (t == "l") {
        if (substr(rest, 1, 5) != " -> \"" || qend($0, e + 5) != length($0)) fail("archive listing line " NR " is not a member: " $0)
      } else if (rest != "") fail("archive listing line " NR " is not a member: " $0)
      p = placed(n); if (p != "") fail("member \"" n "\" " p)
      if (n in kind) fail("member \"" n "\" occurs more than once")
      if (t == "h") {
        p = placed(g); if (p != "") fail("hard link \"" n "\": its target \"" g "\" " p)
        if (!(g in kind) || kind[g] != "-") fail("hard link \"" n "\" names \"" g "\", which is not an earlier regular-file member")
      }
      kind[n] = t; if (t == "l") links++
    }
    END {
      if (bad) exit 1
      if (links) for (n in kind) {
        k = split(n, c, "/"); a = c[1]
        for (j = 2; j <= k; j++) {
          if ((a in kind) && kind[a] == "l") { print "member \"" n "\" lies below the symlink member \"" a "\""; exit 1 }
          a = a "/" c[j]
        }
      }
    }' "$meta/listing") || done_with "refusing the nix half before restoring it, nothing was written: ${problem:-the member check failed}"
  at=""; [ "$ROOT" != / ] && at="${ROOT%/}"
  xargs nix-store "${store[@]}" --check-validity --print-invalid < "$meta/paths" > "$meta/unlocked" \
    || done_with "nix-store --check-validity failed"
  mkdir -p "$at/nix/store" || done_with "cannot create $at/nix/store"
  n=$(wc -l < "$meta/unlocked") || done_with "cannot count the invalid paths"
  lim=$(ulimit -n)
  if [ "$lim" != unlimited ] && (( lim < n + 64 )); then
    ulimit -Sn $(( n + 64 )) 2>/dev/null \
      || done_with "restoring $n store paths holds a lock on each, but the open-file limit is $lim; raise it (ulimit -n) to at least $(( n + 64 ))"
  fi
  if [ "$ROOT" = / ]; then state="${NIX_STATE_DIR:-/nix/var/nix}"; else state="$at/nix/var/nix"; fi
  # A rerun with nothing invalid writes nothing: no state directory, no gc.lock.
  [ "$n" -eq 0 ] || mkdir -p "$state" || done_with "cannot create $state"
  # Nix's PathLocks: in sorted order, an exclusive flock on <path>.lock,
  # waiting while a Nix writer holds it; a non-empty lock file is stale (its
  # holder deleted it) and is opened again. Then gc.lock, shared: the
  # collector ignores path locks and holds gc.lock exclusively while it
  # collects, so no collection deletes what is restored before --load-db.
  # In that order because Nix holds a path lock while it waits for a
  # collection. A collection that ran before gc.lock was ours may have
  # deleted a held lock file, or a path that was valid and so is unlocked:
  # then let everything go and start over, for every path now invalid. The
  # lock descriptors are inherited by tar and nix-store, so a killed
  # restore's locks last until its writers have exited too.
  LC_ALL=C sort -u -o "$meta/unlocked" "$meta/unlocked" || done_with "cannot sort the invalid paths"
  while :; do
    while IFS= read -r p; do
      l="$at$p.lock"
      while :; do
        exec {fd}<>"$l" || done_with "cannot open the store lock $l"
        flock "$fd" || done_with "cannot lock $l"
        [ -s "/dev/fd/$fd" ] || break
        eval "exec ${fd}>&-"
      done
      lock_files+=("$l"); lock_fds+=("$fd")
    done < "$meta/unlocked"
    if [ -s "$meta/unlocked" ]; then
      exec {gc_fd}<>"$state/gc.lock" || done_with "cannot open $state/gc.lock"
      flock -s "$gc_fd" || done_with "cannot lock $state/gc.lock"
    fi
    intact=1
    for f in "${lock_fds[@]}"; do linked "$f" || intact=0; done
    # Checked again under the locks: a path a Nix writer made valid while
    # we waited is Nix's now, and tar adds nothing to it.
    xargs nix-store "${store[@]}" --check-validity --print-invalid < "$meta/paths" > "$meta/invalid" \
      || done_with "nix-store --check-validity failed"
    LC_ALL=C sort -u -o "$meta/invalid" "$meta/invalid" || done_with "cannot sort the invalid paths"
    missed=$(LC_ALL=C comm -13 "$meta/unlocked" "$meta/invalid") || done_with "cannot compare the invalid paths"
    (( intact )) && [ -z "$missed" ] && break
    release_locks
    LC_ALL=C sort -u -o "$meta/unlocked" "$meta/unlocked" "$meta/invalid" || done_with "cannot sort the invalid paths"
  done
  LC_ALL=C sort -u "$meta/paths" | LC_ALL=C comm -23 - "$meta/invalid" | sed 's|^/||' > "$meta/exclude" \
    || done_with "cannot list the valid paths to leave alone"
  while IFS= read -r p; do
    t="$at$p"
    if [ -d "$t" ] && [ ! -L "$t" ]; then chmod -R u+w "$t"; fi
    if [ -e "$t" ] || [ -L "$t" ]; then rm -rf "$t" || done_with "cannot remove the partial store path $t"; fi
  done < "$meta/invalid"
  # No owner and no mode from the archive: as root, tar's defaults would
  # restore its owners and setuid bits. Then Nix's canonical modes, before
  # the hash check (tar_members.NixExtractModeShell, NixCanonicalModes).
  ( cd "$dir" && cat "${PARTS[@]}" ) | "$Z" -q -dc --long=27 \
    | ( umask 022 && exec tar -C "$ROOT" --no-same-owner --no-same-permissions \
        --skip-old-files --anchored --no-wildcards -X "$meta/exclude" -xf - ) \
    || done_with "nix half unpack failed"
  while IFS= read -r p; do
    t="$at$p"
    if [ -L "$t" ] || [ ! -e "$t" ]; then continue; fi
    chmod -R a+rX,a-w -- "$t" || done_with "cannot set the modes of $t"
  done < "$meta/invalid"
  # In sh -c: $0 is nix-hash, $1 the root's prefix, $2 one store path.
  tr '\n' '\0' < "$meta/invalid" \
    | xargs -0 -r -P "$PARALLEL" -n 1 sh -c 'printf "%s\t%s\n" "$2" "$("$0" --type sha256 "$1$2" 2>/dev/null)"' "$(command -v nix-hash)" "$at" \
    > "$meta/actual.unsorted" || done_with "hashing the restored store paths failed"
  # join needs both inputs in the collation it compares with: use C's.
  LC_ALL=C sort "$meta/actual.unsorted" > "$meta/actual"
  LC_ALL=C sort "$meta/invalid" | LC_ALL=C join -t "$(printf '\t')" - <(LC_ALL=C sort "$meta/expected") > "$meta/want"
  if ! cmp -s "$meta/want" "$meta/actual"; then
    diff "$meta/want" "$meta/actual" | sed -n 's/^< //p' | cut -f1 > "$meta/bad"
    while IFS= read -r p; do
      t="$at$p"
      if [ -d "$t" ] && [ ! -L "$t" ]; then chmod -R u+w "$t" 2>/dev/null; fi
      rm -rf "$t"
    done < "$meta/bad"
    done_with "nix half content does not match its registration, nothing registered:" $(tr '\n' ' ' < "$meta/bad")
  fi
  awk -v want="$meta/invalid" '
    BEGIN { while ((getline l < want) > 0) w[l] = 1 }
    s == 0 { p = $0; e = $0 "\n"; s = 1; next }
    s < 4 { e = e $0 "\n"; s++; next }
    s == 4 { n = $0 + 0; e = e $0 "\n"; if (n == 0) { if (p in w) printf "%s", e; s = 0 } else s = 5; next }
    s == 5 { e = e $0 "\n"; if (--n == 0) { if (p in w) printf "%s", e; s = 0 } }' "$meta/db" \
    | nix-store "${store[@]}" --load-db || done_with "nix-store --load-db failed"
  release_locks
  rm -rf "$meta"
  nix-store "${store[@]}" --check-validity "${ROOTS[@]}" >/dev/null || done_with "registration incomplete"
  rm -f "$work"/*
  log "nix half restored"
fi
prefix=""; [ "$ROOT" != / ] && prefix="$ROOT"
command -v zstd >/dev/null || export PATH="$prefix$ZSTD/bin:$PATH"
R="$prefix$REPRO/bin/repro"
[ -n "$REPRO" ] && [ -x "$R" ] || R="$(command -v repro)" || done_with "no repro: the bundle carries none and none is on PATH"
extra=(); [ "$ROOT" != / ] && extra=(--nix-root="$ROOT")
# The repro restored above reads the latest.json this script was made from,
# or none: a local source directory may be writable by others, who could
# otherwise replace it now that the Nix half has been verified, and choose
# the other halves and the shell environment --activate installs.
"$R" bundle restore "$SRC" --after-bootstrap --latest-sha256="$LATEST_SHA256" "${extra[@]}" "$@" || done_with "repro bundle restore failed (exit $?)"
log "done"
""")
  else:
    s.add("""
R="$(command -v repro)" || done_with "this bundle has no Nix half to bootstrap from; install repro first"
"$R" bundle restore "$SRC" "$@" || done_with "repro bundle restore failed (exit $?)"
log "done"
""")
  s
