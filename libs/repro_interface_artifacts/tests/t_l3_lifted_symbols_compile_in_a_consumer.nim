## Shared-Development-Services L3 — the lifted service/activity symbols
## reach a consumer THROUGH THE INTERFACE ARTIFACT, and the artifact's
## emitter agrees with the producer's own.
##
## This is the other half of
## ``libs/repro_project_dsl/tests/dsl_port/
## t_dsl_lifted_service_reference_is_typed.nim``. That file exercises the
## WORKSPACE-SIBLING route, where a consumer imports the producer's own
## macro expansion. This one exercises the LIFT-ARTIFACT route: the
## producer's interface is lifted to a ``ProjectInterfaceArtifact``, the
## artifact is rendered to a Nim stub by ``writeNimInterfaceStub``, and a
## consumer module that has never seen the producer's source compiles
## against the stub. That is what "travel through the interface lift as
## typed symbols" means, and it is the route a cross-REPOSITORY consumer
## takes.
##
## Two emitters produce the same surface — ``emitLiftedServiceSymbols``
## here and ``l3LiftedExportSurface`` in ``macros_b.nim`` — because one
## cannot call the other (``repro_interface_artifacts`` imports
## ``repro_project_dsl``, not the reverse). A divergence between them
## would mean a consumer compiling against a different member set
## depending on which route it took, and NOTHING would fail. The last
## suite in this file is the guard against that: it checks the stub's
## emitted member set against the names the producer's own macro recorded
## in the interface registry.
##
## MOCK POLICY — NO MOCKS. The producer is a real ``package`` block in
## ``l3_lift_fixtures.nim``, the artifact is produced by the real
## ``toProjectInterface`` / ``artifactFor``, the stub is written by the
## real ``writeNimInterfaceStub``, and the consumer is compiled by the
## real ``nim``.
##
## WHICH DISCRIMINATOR IS LOAD-BEARING. ``probe.ok`` is, for the consumer
## compiles: at the base commit the stub carries no handle types at all,
## so ``l3LiftProducer.sso`` is an undeclared field and the compile
## fails. The stub-text and registry-agreement assertions name
## ``publicActivities`` and so do not compile at the base.

import std/[os, osproc, strutils, unittest]

import repro_project_dsl
import repro_interface_artifacts

import ./l3_lift_fixtures

proc repoRoot(): string =
  currentSourcePath().parentDir().parentDir().parentDir().parentDir()

proc nimExe(): string =
  let found = findExe("nim")
  if found.len > 0: found else: "nim"

proc producerArtifact(): ProjectInterfaceArtifact =
  for pkg in registeredPackages():
    if pkg.packageName == "l3LiftProducer":
      return artifactFor(toProjectInterface(pkg))
  raise newException(ValueError,
    "fixture drift: l3LiftProducer not registered")

proc stubText(): string =
  let dir = repoRoot() / "build" /
    ("l3-stub-text-" & $getCurrentProcessId())
  createDir(dir)
  defer:
    try: removeDir(dir)
    except CatchableError: discard
  let path = dir / "stub.nim"
  writeNimInterfaceStub(path, producerArtifact())
  readFile(path)

type ConsumerProbe = object
  ok: bool
  output: string

proc compileAgainstStub(consumerSource, tag: string): ConsumerProbe =
  ## Write the producer's lifted stub and a consumer module beside it,
  ## then compile the consumer.
  ##
  ## ``nim c --compileOnly`` rather than ``nim check`` for the same
  ## reason ``service_block_compile_probe.nim`` gives: the DSL's
  ## macro-time filesystem work does not happen under ``check``. Under
  ## the repository rather than the system temp dir so Nim's walk-up
  ## finds this repo's ``config.nims``, which is what puts every
  ## ``libs/*/src`` on the module path.
  let dir = repoRoot() / "build" /
    ("l3-stub-probe-" & tag & "-" & $getCurrentProcessId())
  createDir(dir)
  defer:
    try: removeDir(dir)
    except CatchableError: discard
  writeNimInterfaceStub(dir / "l3prod_stub.nim", producerArtifact())
  let consumerPath = dir / "consumer.nim"
  writeFile(consumerPath, consumerSource)
  let nimcache = repoRoot() / "build" /
    ("l3-stub-probe-nimcache-" & $getCurrentProcessId())
  let (output, exitCode) = execCmdEx(
    nimExe() & " c --compileOnly --hints:off --colors:off --nimcache:" &
      quoteShell(nimcache) & " " & quoteShell(consumerPath),
    workingDir = repoRoot())
  ConsumerProbe(ok: exitCode == 0, output: output)

const WellFormedConsumer = """
import ./l3prod_stub

## `l3LiftProducer` is the producer's package const, regenerated by the
## stub; `sso` is its lifted activity handle and `standalone` its lifted
## package-level service. Neither name appears in this file's imports --
## they came out of the interface artifact.
let sso = l3LiftProducer.sso
doAssert sso.port == 0           ## declared with its type; L7 fills it
doAssert sso.externalSecure == false
doAssert sso.externalDomain == ""
doAssert sso.zitadel.serviceName == "zitadel"
doAssert sso.zitadel.activityName == "sso"
doAssert sso.zitadel.packageName == "l3LiftProducer"
doAssert sso.bootstrap.serviceName == "bootstrap"
doAssert l3LiftProducer.edge.nginx.serviceName == "nginx"
doAssert l3LiftProducer.standalone.serviceName == "standalone"
doAssert l3LiftProducer.standalone.activityName == ""
echo "ok"
"""

suite "L3 — a consumer compiles against the LIFTED stub":

  test "the positive control: every lifted symbol resolves and typechecks":
    let probe = compileAgainstStub(WellFormedConsumer, "wellformed")
    checkpoint(probe.output)
    check probe.ok

  test "a misspelled export does not compile":
    # No DSL refusal here on purpose: this consumer is a plain Nim
    # module, not a `package` block, so there is no walker to add a
    # message. Nim's own `undeclared field` is the diagnostic, and the
    # naming refusals are the DSL's job -- measured in
    # `t_dsl_lifted_service_reference_is_typed.nim`. What this asserts is
    # that the stub does not accidentally export something it should not.
    let probe = compileAgainstStub(
      WellFormedConsumer.replace("l3LiftProducer.sso",
        "l3LiftProducer.ssoo"), "bad-name")
    checkpoint(probe.output)
    check not probe.ok
    check probe.output.contains("ssoo")

  test "a misspelled handle member does not compile":
    let probe = compileAgainstStub(
      WellFormedConsumer.replace("sso.port", "sso.prot"), "bad-member")
    checkpoint(probe.output)
    check not probe.ok
    check probe.output.contains("prot")

suite "L3 — the stub's emitted surface matches the producer's own":

  test "the handle type the stub declares is the one the lift recorded":
    let text = stubText()
    for act in producerArtifact().projectInterface.publicActivities:
      checkpoint("activity " & act.name)
      check text.contains("  " & act.handleType & "* = object")
      check text.contains("proc " & act.name & "*(pkg: " &
        "L3LiftProducerPackage): " & act.handleType)

  test "every `config:` key is a field of the stub's handle type":
    let text = stubText()
    for act in producerArtifact().projectInterface.publicActivities:
      for key in act.config:
        checkpoint(act.name & "." & key.name)
        check text.contains("    " & key.name & "*: " & key.nimType)

  test "every service is a field of the stub's handle type":
    let text = stubText()
    for act in producerArtifact().projectInterface.publicActivities:
      for svcName in act.services:
        checkpoint(act.name & "." & svcName)
        check text.contains("    " & svcName & "*: LiftedServiceHandle")

  test "a package-level service gets its own accessor, not a handle field":
    let text = stubText()
    check text.contains("    standalone*: LiftedServiceHandle")
    check text.contains("proc standalone*(pkg: L3LiftProducerPackage): " &
      "LiftedServiceHandle")

  test "the exports object carries exactly the exported names":
    # The reflection surface the DSL's `liftedExportRefusal` reads to
    # name what is available. If it drifted from the accessor set, the
    # refusal would name the wrong list.
    let text = stubText()
    check text.contains("  L3LiftProducerPackageExports* = object")
    check text.contains("    sso*: L3LiftProducerPackageSsoHandle")
    check text.contains("    edge*: L3LiftProducerPackageEdgeHandle")
    check text.contains("    standalone*: LiftedServiceHandle")
    # The bare `activity "default"` is not an export: it declares a name
    # and nothing else. Asserting its absence is what keeps the four
    # assertions above from passing on an emitter that exports
    # everything it can see.
    check not text.contains("    default*:")

  test "a producer with no services or activities emits no stub surface":
    # The control for the whole emitter: it must add nothing at all to a
    # stub for a package that exports neither, rather than an empty
    # `type` section that would not parse.
    var bare: ProjectInterface
    bare.projectName = "bareproducer"
    bare.packageName = "bareproducer"
    let dir = repoRoot() / "build" /
      ("l3-stub-bare-" & $getCurrentProcessId())
    createDir(dir)
    defer:
      try: removeDir(dir)
      except CatchableError: discard
    let path = dir / "bare_stub.nim"
    writeNimInterfaceStub(path, artifactFor(bare))
    let text = readFile(path)
    check not text.contains("Exports* = object")
    check not text.contains("liftedExports")
