struct rl_dest {
  char name[64];
  char host[64];   /* real destination, in the host namespace */
  int port;
  char inner[64];  /* the address the child dials, inside its namespace */
  int inner_port;
  int listen_fd;   /* received from the child */
};

struct rl_list { char **items; int n, cap; };

struct rl_cfg {
  int cleanup;          /* mode=cleanup: remove lease_dir as the lease user */
  char *lease_id, *lease_root, *lease_dir, *cwd;
  char *status_path, *report_path, *stdout_path, *stderr_path;
  char *cgroup;         /* a cgroup directory the lease is placed in, or NULL */
  char *stage;          /* where the namespace layer builds the new root */
  char *argv[RL_MAX_ARGS + 1]; int argc;
  char *envp[RL_MAX_ENV + 1]; int envc;
  struct rl_list read_roots, exec_roots, write_roots, hide, closure;
  struct rl_list inputs;  /* materialized input artifacts: read-only, executable */
  struct rl_dest dests[RL_MAX_DEST]; int n_dest;
  int layer_ns, layer_landlock, layer_floor;
  int memfd_noexec;     /* hardened: memfd_create must carry MFD_NOEXEC_SEAL */
  long uid, gid, subuid, subgid;
  char *newuidmap, *newgidmap;
  long timeout_ms;
  long nproc_limit, fsize_limit;
};

static struct rl_cfg cfg;
static int report_fd = -1;

