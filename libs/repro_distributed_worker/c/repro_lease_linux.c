/*
 * repro_lease_linux.c — the Linux execution-lease launcher of
 * Distributed-Execution M7 (deployment-security-architecture.md CONF-1,
 * CONF-2, CONF-3, CONF-5, FLOW-3, DET-1, DET-2).
 *
 * A remote goal never runs in the daemon's own process, user or home. This
 * file forks a SUPERVISOR, which forks the confined child. The child is
 * built up from three independently switchable layers, so a test can remove
 * each one alone and observe the breach it exists to stop
 * (tests/integration/t_execution_lease_confinement.nim):
 *
 *   NAMESPACE  fresh user + mount + net + pid + ipc + uts namespaces and a
 *              NEW ROOT, built the way the Nix sandbox builds one: a tmpfs
 *              holding only the approved read roots and the executable
 *              closure (read-only bind mounts), the child's own lease
 *              (read-write), a private /tmp, a fresh /proc and a minimal
 *              /dev — then pivot_root into it. Nothing else exists for the
 *              child: not another lease, not the daemon's state, not any
 *              home directory. EVERY WRITABLE MOUNT IS NOEXEC (the lease,
 *              /tmp, /dev/shm): a binary written during the goal cannot be
 *              executed or mapped executable by the kernel (noexec covers
 *              execve and file-backed PROT_EXEC mappings, so the
 *              `ld.so <file>` launch of a written file fails too). Without
 *              it: the child reads its neighbour's worktree.
 *   LANDLOCK   writes only beneath the child's own lease; reads beneath the
 *              declared read roots and the lease root; execution only
 *              beneath the declared closure and output directories.
 *              Without it: the child writes outside its lease.
 *   FLOOR      the CONF-1 floor applied to the child: a DIFFERENT host user
 *              (a subordinate uid from /etc/subuid, via newuidmap — the
 *              daemon's files and sockets are not its own); a seccomp
 *              ALLOW-LIST derived per CONF-3 (`repro_lease_floor_syscalls.h`,
 *              generated by scripts/derive_lease_floor_syscalls.py from
 *              systemd's @system-service set and the profiled lease
 *              workload, minus namespace construction and the kernel
 *              surfaces no build needs — threat model G30); socket families
 *              other than AF_INET, AF_INET6 and AF_UNIX (the
 *              RestrictAddressFamilies analogue); a connect / send to any
 *              unix socket that EXISTS in the lease's view (G38, below);
 *              clone() namespace flags; resource limits (G31). Without it:
 *              the child connects to the daemon's control socket.
 *
 * EVERY DENIAL IS REPORTED (DET-2, threat model G20). The lease runs under
 * ONE seccomp filter (the kernel allows a single listener per filter chain)
 * whose notifications the supervisor answers, writing a report line for
 * each denial before it answers:
 *
 *   * the floor's part routes every syscall outside the allow-list (and
 *     every non-IP socket, every namespace clone) to the supervisor, which
 *     reports `syscall-denied` and answers EPERM (EAFNOSUPPORT for a socket
 *     family; ENOSYS for clone3, whose flags live in memory a filter cannot
 *     read — glibc then falls back to clone(), whose flags it can);
 *   * AF_UNIX (threat model G38, coordinator decision 2026-10-20): creating
 *     a unix socket grants nothing by itself (socketpair always was
 *     allowed), so the floor allows socket(AF_UNIX). What it refuses is
 *     REACHING one: a connect / sendto / sendmsg / sendmmsg naming a unix
 *     socket that exists in the lease's view is refused and reported
 *     (`egress-denied`, `unix:<path>`) — the daemon's control socket under
 *     a visible root is exactly that. An attempt that CANNOT reach anything
 *     — a PATHNAME that does not exist in the lease's new root (the C
 *     library's nscd probe of /var/run/nscd/socket, ~4 per compile), or
 *     names something that is not a socket — is not a breach and is not
 *     reported: the supervisor answers it with the error the kernel would
 *     give (ENOENT, ENOTDIR, ECONNREFUSED) and NEVER lets it continue, so
 *     no argument the child rewrites after the check can turn it into a
 *     connection (the CONTINUE TOCTOU below does not apply). Reachability
 *     is judged by opening the name inside the child's root
 *     (`unix_dest_reachable`: openat2 RESOLVE_IN_ROOT from /proc/<pid>/root,
 *     RESOLVE_BENEATH from its cwd for a relative name); anything the
 *     supervisor cannot decide — an ABSTRACT name, an unnamed address, a
 *     relative name that leaves the cwd, a permission error, a kernel
 *     without openat2 — counts as reachable: refused and reported as
 *     before. (Abstract names are scoped by the lease's own network
 *     namespace, so the host's are not reachable; but whether one exists in
 *     that namespace is not checked, and no measured workload uses them.)
 *   * the always-on detection part routes connect / sendto / sendmsg /
 *     sendmmsg (EGRESS, FLOW-3), execve / execveat (EXEC, DET-1) and the
 *     path-based file syscalls Landlock governs (FILESYSTEM) to the
 *     supervisor. Egress to anything but a forwarder, and an execve /
 *     execveat of a file outside the closure, is refused and reported
 *     (`egress-denied`, `exec-outside-closure`). A file access Landlock
 *     will refuse is reported (`fs-denied`) and left to Landlock, which
 *     enforces it;
 *   * executable MAPPINGS are not intercepted (operator decision,
 *     2026-10-20): code loaded without an execve of its own from a file the
 *     goal wrote is stopped by the noexec writable mounts of the namespace
 *     layer, and by visibility — only the closure is mounted executable.
 *     Anonymous executable memory (a JIT) and memfds are outside both, as
 *     in every surveyed build sandbox; the hardened profile's answer is
 *     `vm.memfd_noexec` and a VM-grade boundary (threat model §3a);
 *   * a notification whose arguments the supervisor cannot read is refused
 *     (egress, exec) and reported — never passed on unexamined.
 *
 * The listener reaches the supervisor without a sendmsg from the filtered
 * child: the child writes its descriptor NUMBER on the control socket and
 * the supervisor takes it with pidfd_getfd(2). So no sendmsg is ever exempt
 * from inspection (an action used to be able to dup2 any socket onto the
 * control socket's number and send unchecked). The filter is installed
 * last, after Landlock, so nothing but the hand-over, chdir and execve runs
 * under it before the action.
 *
 * The notification path reads syscall arguments from the child's memory
 * and checks SECCOMP_IOCTL_NOTIF_ID_VALID before answering. A multi-threaded
 * child can still change an argument between the check and the kernel's use
 * of it when the supervisor lets the call CONTINUE (the documented
 * seccomp_unotify TOCTOU, accepted as threat-model G2): the network
 * namespace — which has no route anywhere — and Landlock are the
 * enforcement for egress and files; the notification is the detector.
 * Denials (no CONTINUE) are not subject to it.
 *
 * Reports are written as they happen and the daemon forwards them while the
 * lease runs (G21). Each report kind has a budget (`RL_REPORTS_PER_SEC`); a
 * flood of one kind is summarized (`reports-suppressed`, with the count)
 * and cannot crowd out another kind.
 *
 * Interface: repro_lease_spawn() parses a key/value buffer (see the Nim
 * caller, lease.nim) BEFORE forking and returns the supervisor's pid. The
 * supervisor writes `status` (exit=…, signal=…, timedout=…, error=…) and
 * appends JSON lines to `report`, then _exit()s with the child's status.
 */
