static void bring_loopback_up(int ctl) {
  int s = socket(AF_INET, SOCK_DGRAM, 0);
  if (s < 0) child_fail(ctl, "socket(lo)");
  struct ifreq ifr; memset(&ifr, 0, sizeof ifr);
  snprintf(ifr.ifr_name, IFNAMSIZ, "lo");
  if (ioctl(s, SIOCGIFFLAGS, &ifr) != 0) child_fail(ctl, "SIOCGIFFLAGS lo");
  ifr.ifr_flags |= IFF_UP | IFF_RUNNING;
  if (ioctl(s, SIOCSIFFLAGS, &ifr) != 0) child_fail(ctl, "SIOCSIFFLAGS lo");
  close(s);
}

/* Hands a listener to the supervisor by NUMBER (no sendmsg once a filter
   is in place; the supervisor takes it with pidfd_getfd) and waits until
   the supervisor confirms it holds it. */
static void hand_over_listener(int ctl, int fd, char tag) {
  char msg[32];
  int n = snprintf(msg, sizeof msg, "%c%d", tag, fd);
  write_all(ctl, msg, (size_t)n);
  char ack = 0;
  if (read(ctl, &ack, 1) != 1 || ack != 'K') _exit(127);
  close(fd);
}

static void set_limit(int resource, long value) {
  if (value <= 0) return;
  struct rlimit rl = { .rlim_cur = (rlim_t)value, .rlim_max = (rlim_t)value };
  setrlimit(resource, &rl);
}

static void confined_child(int ctl) {
  if (prctl(PR_SET_PDEATHSIG, SIGKILL) != 0) child_fail(ctl, "pdeathsig");
  if (mount(NULL, "/", NULL, MS_REC | MS_PRIVATE, NULL) != 0) child_fail(ctl, "make-rprivate");
  if (cfg.cleanup) {
    if (nftw(cfg.lease_dir, rm_cb, 32, FTW_DEPTH | FTW_PHYS) != 0) child_fail(ctl, "remove lease");
    write_all(ctl, "X", 1);
    _exit(0);
  }
  /* NAMESPACE layer: a new root holding only the approved roots, the
     closure and this lease (writable mounts noexec), then pivot_root. */
  if (cfg.layer_ns) {
    build_new_root(ctl);
  } else if (mount("proc", "/proc", "proc", MS_NOSUID | MS_NODEV | MS_NOEXEC, NULL) != 0) {
    child_fail(ctl, "mount proc");
  }
  bring_loopback_up(ctl);
  /* Egress forwarders: listeners inside, handed to the supervisor outside
     (before any filter exists, so SCM_RIGHTS is fine here). */
  for (int i = 0; i < cfg.n_dest; i++) {
    int s = socket(AF_INET, SOCK_STREAM, 0);
    if (s < 0) child_fail(ctl, "forwarder socket");
    int one = 1; setsockopt(s, SOL_SOCKET, SO_REUSEADDR, &one, sizeof one);
    struct sockaddr_in a; memset(&a, 0, sizeof a);
    a.sin_family = AF_INET; a.sin_port = htons((uint16_t)cfg.dests[i].inner_port);
    if (inet_pton(AF_INET, cfg.dests[i].inner, &a.sin_addr) != 1) child_fail(ctl, "forwarder address");
    if (bind(s, (struct sockaddr *)&a, sizeof a) != 0) child_fail(ctl, "forwarder bind");
    if (listen(s, 64) != 0) child_fail(ctl, "forwarder listen");
    if (send_fd(ctl, s, 'D' + 0) != 0) child_fail(ctl, "send forwarder");
    close(s);
  }
  /* FLOOR, part 1: become the lease's own (subordinate) user, with limits
     (G31: a lease cannot fork without bound, write one file without bound
     or dump core into its worktree). */
  if (cfg.layer_floor) {
    lchown_uid = 1000; lchown_gid = 1000;
    if (nftw(cfg.lease_dir, chown_cb, 32, FTW_PHYS) != 0) child_fail(ctl, "chown lease");
    if (setgroups(0, NULL) != 0) child_fail(ctl, "setgroups");
    if (setresgid(1000, 1000, 1000) != 0) child_fail(ctl, "setresgid");
    if (setresuid(1000, 1000, 1000) != 0) child_fail(ctl, "setresuid");
    /* A credential change clears the parent-death signal; restore it so a
       killed supervisor still takes the whole lease down. */
    if (prctl(PR_SET_PDEATHSIG, SIGKILL) != 0) child_fail(ctl, "pdeathsig");
    set_limit(RLIMIT_NPROC, cfg.nproc_limit);
    set_limit(RLIMIT_FSIZE, cfg.fsize_limit);
    set_limit(RLIMIT_CORE, 0);
  }
  /* The supervisor takes the listener with pidfd_getfd(2), which needs
     this process to be dumpable (a credential change cleared it). It is
     dumpable again after its execve anyway. */
  if (prctl(PR_SET_DUMPABLE, 1, 0, 0, 0) != 0) child_fail(ctl, "dumpable");
  if (prctl(PR_SET_NO_NEW_PRIVS, 1, 0, 0, 0) != 0) child_fail(ctl, "no_new_privs");
  if (cfg.layer_landlock && apply_landlock() != 0) child_fail(ctl, "landlock");
  /* Last, so nothing above runs under it: the seccomp filter (detection,
     and FLOOR part 2 — the derived allow-list). From here on only
     read/write on the control socket, chdir and execve remain. */
  int listener = install_lease_filter(cfg.layer_floor);
  if (listener < 0) child_fail(ctl, "seccomp filter");
  hand_over_listener(ctl, listener, 'N');
  if (chdir(cfg.cwd) != 0) child_fail(ctl, "chdir");
  write_all(ctl, "X", 1);   /* "about to exec": the supervisor stops expecting fds */
  /* The RAW system call, not libc's execve(3). A lease's environment is
     exactly what its descriptor names, and never LD_PRELOAD or LD_AUDIT
     (Distributed-Execution.md, `GraphCacheDescriptor`; the threat model's
     "a lease's environment is exactly what the descriptor names"). Through
     libc, a library preloaded into the WORKER can interpose execve and
     rewrite envp. The build monitor's shim does exactly that to follow its
     children (io-mon `ct_linux_preload_env_with_exec_gen` adds
     `LD_PRELOAD=<shim>`), so a worker run under a monitored build handed its
     shim to every lease. The lease's confinement then refused to open it,
     and every goal was disqualified (`fs-denied …/librepro_monitor_shim.so`).
     A system call cannot be interposed. The seccomp supervisor still judges
     it: the filter matches SYS_execve however it is made. */
  syscall(SYS_execve, cfg.argv[0], cfg.argv, cfg.envp);
  _exit(126);
}

