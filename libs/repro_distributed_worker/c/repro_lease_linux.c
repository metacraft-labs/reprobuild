static void write_all(int fd, const char *s, size_t n) {
  while (n > 0) {
    ssize_t w = write(fd, s, n);
    if (w < 0) { if (errno == EINTR) continue; return; }
    s += w; n -= (size_t)w;
  }
}

static void json_escape(char *out, size_t cap, const char *in) {
  size_t o = 0;
  for (; *in && o + 7 < cap; in++) {
    unsigned char c = (unsigned char)*in;
    if (c == '"' || c == '\\') { out[o++] = '\\'; out[o++] = (char)c; }
    else if (c < 0x20) { o += (size_t)snprintf(out + o, cap - o, "\\u%04x", c); }
    else out[o++] = (char)c;
  }
  out[o] = 0;
}

static long now_ms(void) {
  struct timespec ts; clock_gettime(CLOCK_MONOTONIC, &ts);
  return ts.tv_sec * 1000L + ts.tv_nsec / 1000000L;
}

/* Per-kind report budgets (G21). */
static double rk_tokens[RK_COUNT];
static long rk_last[RK_COUNT];
static long rk_suppressed[RK_COUNT];
static long rk_last_summary[RK_COUNT];

static void emit_line(const char *line, int n) {
  if (report_fd >= 0 && n > 0) write_all(report_fd, line, (size_t)n);
}

static void flush_suppressed(int kind, long now) {
  if (rk_suppressed[kind] == 0) return;
  char line[256];
  int n = snprintf(line, sizeof line,
    "{\"kind\":\"reports-suppressed\",\"detail\":\"%s\",\"count\":%ld,\"syscall\":\"\",\"pid\":0}\n",
    rk_names[kind], rk_suppressed[kind]);
  emit_line(line, n);
  rk_suppressed[kind] = 0;
  rk_last_summary[kind] = now;
}

static void report(int kind, const char *field, const char *value,
                   const char *syscall_name, pid_t pid) {
  if (report_fd < 0) return;
  long now = now_ms();
  if (rk_last[kind] == 0) { rk_tokens[kind] = RL_REPORTS_BURST; rk_last[kind] = now; }
  rk_tokens[kind] += (double)(now - rk_last[kind]) * RL_REPORTS_PER_SEC / 1000.0;
  if (rk_tokens[kind] > RL_REPORTS_BURST) rk_tokens[kind] = RL_REPORTS_BURST;
  rk_last[kind] = now;
  if (rk_tokens[kind] < 1.0) {
    rk_suppressed[kind]++;
    if (now - rk_last_summary[kind] >= 1000) flush_suppressed(kind, now);
    return;
  }
  rk_tokens[kind] -= 1.0;
  char esc[1200], line[1600];
  json_escape(esc, sizeof esc, value);
  int n = snprintf(line, sizeof line,
    "{\"kind\":\"%s\",\"%s\":\"%s\",\"syscall\":\"%s\",\"pid\":%d}\n",
    rk_names[kind], field, esc, syscall_name, (int)pid);
  emit_line(line, n);
}

static void child_fail(int ctl, const char *what) {
  char msg[512];
  int n = snprintf(msg, sizeof msg, "E%s: %s", what, strerror(errno));
  if (n > 0) write_all(ctl, msg, (size_t)n);
  _exit(127);
}

static int send_fd(int sock, int fd, int tag) {
  char data = (char)tag;
  struct iovec iov = { .iov_base = &data, .iov_len = 1 };
  char cbuf[CMSG_SPACE(sizeof(int))];
  memset(cbuf, 0, sizeof cbuf);
  struct msghdr m = { .msg_iov = &iov, .msg_iovlen = 1, .msg_control = cbuf, .msg_controllen = sizeof cbuf };
  struct cmsghdr *c = CMSG_FIRSTHDR(&m);
  c->cmsg_level = SOL_SOCKET; c->cmsg_type = SCM_RIGHTS; c->cmsg_len = CMSG_LEN(sizeof(int));
  memcpy(CMSG_DATA(c), &fd, sizeof(int));
  return sendmsg(sock, &m, 0) == 1 ? 0 : -1;
}

static int recv_msg(int sock, char *buf, size_t cap, int *fd_out) {
  struct iovec iov = { .iov_base = buf, .iov_len = cap };
  char cbuf[CMSG_SPACE(sizeof(int))];
  struct msghdr m = { .msg_iov = &iov, .msg_iovlen = 1, .msg_control = cbuf, .msg_controllen = sizeof cbuf };
  ssize_t n = recvmsg(sock, &m, 0);
  *fd_out = -1;
  if (n <= 0) return (int)n;
  for (struct cmsghdr *c = CMSG_FIRSTHDR(&m); c; c = CMSG_NXTHDR(&m, c))
    if (c->cmsg_level == SOL_SOCKET && c->cmsg_type == SCM_RIGHTS)
      memcpy(fd_out, CMSG_DATA(c), sizeof(int));
  return (int)n;
}

static int mkdir_p(const char *path, mode_t mode) {
  char tmp[PATH_MAX];
  snprintf(tmp, sizeof tmp, "%s", path);
  for (char *p = tmp + 1; *p; p++) {
    if (*p == '/') { *p = 0; if (mkdir(tmp, mode) != 0 && errno != EEXIST) return -1; *p = '/'; }
  }
  if (mkdir(tmp, mode) != 0 && errno != EEXIST) return -1;
  return 0;
}

static long lchown_uid, lchown_gid;
static int chown_cb(const char *p, const struct stat *sb, int f, struct FTW *ftw) {
  (void)sb; (void)f; (void)ftw;
  /* EROFS: a materialized input artifact, bound read-only on purpose; it
     stays the daemon's (mapped to the namespace's root), mode 0755, so the
     lease user reads and executes it and cannot change it. */
  if (lchown(p, (uid_t)lchown_uid, (gid_t)lchown_gid) != 0 && errno != EROFS) return -1;
  return 0;
}
static int rm_cb(const char *p, const struct stat *sb, int f, struct FTW *ftw) {
  (void)sb; (void)ftw;
  if (f == FTW_DP) return rmdir(p) == 0 || errno == ENOENT ? 0 : -1;
  return unlink(p) == 0 || errno == ENOENT ? 0 : -1;
}

