/* The flags a bind-mount remount must keep: inside a user namespace the
   kernel refuses to clear nosuid/nodev/noexec/atime flags the original
   mount carries ("locked" flags). */
static unsigned long locked_flags_of(const char *path) {
  struct statvfs sv;
  if (statvfs(path, &sv) != 0) return 0;
  unsigned long f = 0;
  if (sv.f_flag & ST_NOSUID) f |= MS_NOSUID;
  if (sv.f_flag & ST_NODEV) f |= MS_NODEV;
  if (sv.f_flag & ST_NOEXEC) f |= MS_NOEXEC;
  if (sv.f_flag & ST_RDONLY) f |= MS_RDONLY;
#ifdef ST_NOATIME
  if (sv.f_flag & ST_NOATIME) f |= MS_NOATIME;
#endif
#ifdef ST_NODIRATIME
  if (sv.f_flag & ST_NODIRATIME) f |= MS_NODIRATIME;
#endif
#ifdef ST_RELATIME
  if (sv.f_flag & ST_RELATIME) f |= MS_RELATIME;
#endif
  return f;
}

/* Creates the directories of `rel` (an absolute path) beneath `stage`,
   NEVER through a symlink: a component that already exists in the new root
   as a symlink (a replicated `/lib -> usr/lib`, or an absolute link into
   the store) would otherwise lead mkdir out of the new root and onto the
   host. Returns 1 when `rel` sits beneath such a symlink (the caller skips
   it: it is reachable through the link), 0 on success, -1 on error.
   `last` says whether the final component is created too. */
static int stage_dirs(const char *stage, const char *rel, int last) {
  char path[PATH_MAX * 2];
  size_t sl = strlen(stage);
  snprintf(path, sizeof path, "%s%s", stage, rel);
  size_t end = strlen(path);
  if (!last) {
    char *slash = strrchr(path + sl, '/');
    end = slash ? (size_t)(slash - path) : sl;
  }
  for (size_t i = sl + 1; i <= end; i++) {
    if (path[i] != '/' && i != end) continue;
    char save = path[i]; path[i] = 0;
    struct stat st;
    if (lstat(path, &st) == 0) {
      if (S_ISLNK(st.st_mode)) { path[i] = save; return 1; }
      if (!S_ISDIR(st.st_mode)) { path[i] = save; errno = ENOTDIR; return -1; }
    } else if (mkdir(path, 0755) != 0 && errno != EEXIST) {
      path[i] = save; return -1;
    }
    path[i] = save;
  }
  return 0;
}

/* Binds host path `src` at the same path inside the new root. `rw`: the
   mount stays writable and is made NOEXEC (every writable mount is). A
   symlink is replicated as a symlink, so the link resolves inside the new
   root — to nothing unless its target is mounted too. */
static int bind_into_root(const char *src, int rw, int dev) {
  struct stat st;
  if (lstat(src, &st) != 0) return errno == ENOENT ? 0 : -1;
  char dst[PATH_MAX * 2];
  snprintf(dst, sizeof dst, "%s%s", cfg.stage, src);
  int below_link = stage_dirs(cfg.stage, src, 0);
  if (below_link != 0) return below_link > 0 ? 0 : -1;
  struct stat dt;
  if (lstat(dst, &dt) == 0) {
    /* Already present (a parent bind brought it in): nothing to add for
       a read-only root, which inherits its parent's mount. */
    if (!rw && !dev) return 0;
  }
  if (S_ISLNK(st.st_mode)) {
    char tgt[PATH_MAX];
    ssize_t n = readlink(src, tgt, sizeof tgt - 1);
    if (n < 0) return -1;
    tgt[n] = 0;
    if (symlink(tgt, dst) != 0 && errno != EEXIST) return -1;
    return 0;
  }
  if (S_ISDIR(st.st_mode)) {
    if (mkdir(dst, 0755) != 0 && errno != EEXIST) return -1;
  } else {
    int fd = open(dst, O_WRONLY | O_CREAT | O_CLOEXEC | O_NOFOLLOW, 0644);
    if (fd < 0 && errno != EEXIST) return -1;
    if (fd >= 0) close(fd);
  }
  if (mount(src, dst, NULL, MS_BIND | MS_REC, NULL) != 0) return -1;
  unsigned long fl = MS_REMOUNT | MS_BIND | locked_flags_of(dst) | MS_NOSUID;
  if (!dev) fl |= MS_NODEV;
  if (rw) { fl &= ~(unsigned long)MS_RDONLY; fl |= MS_NOEXEC; }
  else fl |= MS_RDONLY;
  return mount(NULL, dst, NULL, fl, NULL);
}

struct root_entry { const char *path; int exec; };
static int cmp_root(const void *a, const void *b) {
  return strcmp(((const struct root_entry *)a)->path, ((const struct root_entry *)b)->path);
}

static int under_dir(const char *path, const char *dir) {
  size_t l = strlen(dir);
  return !strncmp(path, dir, l) && (path[l] == 0 || path[l] == '/');
}

/* Binds a materialized input artifact directory (inside the lease) over
   itself READ-ONLY and WITHOUT noexec: the content-addressed outputs of a
   declared input node, which the goal may run (a test runs what an earlier
   node built) but never change. The writable lease around it stays
   noexec. */
static int bind_input_ro_exec(const char *src) {
  char dst[PATH_MAX * 2];
  snprintf(dst, sizeof dst, "%s%s", cfg.stage, src);
  struct stat st;
  if (lstat(src, &st) != 0 || !S_ISDIR(st.st_mode)) { errno = ENOTDIR; return -1; }
  if (lstat(dst, &st) != 0 || !S_ISDIR(st.st_mode)) { errno = ENOENT; return -1; }
  if (mount(src, dst, NULL, MS_BIND | MS_REC, NULL) != 0) return -1;
  unsigned long fl = MS_REMOUNT | MS_BIND | MS_RDONLY | MS_NOSUID | MS_NODEV |
    locked_flags_of(dst);
  return mount(NULL, dst, NULL, fl, NULL);
}

static void build_new_root(int ctl) {
  if (mkdir_p(cfg.stage, 0700) != 0) child_fail(ctl, "stage directory");
  /* The new root's own tmpfs is NOEXEC, and read-only once it is entered
     (below): nothing written at the top level of the new root can run,
     with or without the floor's different uid. */
  if (mount("tmpfs", cfg.stage, "tmpfs", MS_NOSUID | MS_NODEV | MS_NOEXEC, "mode=0755") != 0)
    child_fail(ctl, "stage tmpfs");
  /* A private /tmp FIRST: the roots and the lease may live beneath /tmp,
     and their binds must land on top of it, not under it. */
  char p[PATH_MAX * 2];
  snprintf(p, sizeof p, "%s/tmp", cfg.stage);
  if (mkdir(p, 01777) != 0 && errno != EEXIST) child_fail(ctl, "mkdir /tmp");
  if (mount("tmpfs", p, "tmpfs", MS_NOSUID | MS_NODEV | MS_NOEXEC, "mode=1777") != 0)
    child_fail(ctl, "private /tmp");
  /* The approved read roots and the executable closure, read-only, in
     path order so a parent is mounted before what lies beneath it. */
  int n = cfg.read_roots.n + cfg.exec_roots.n;
  struct root_entry *roots = calloc((size_t)(n > 0 ? n : 1), sizeof *roots);
  if (!roots) child_fail(ctl, "root list");
  int k = 0;
  for (int i = 0; i < cfg.read_roots.n; i++) roots[k++] = (struct root_entry){ cfg.read_roots.items[i], 0 };
  for (int i = 0; i < cfg.exec_roots.n; i++) {
    /* Declared output directories live inside the lease, which is bound
       on its own below — writable, and therefore noexec. */
    if (under_dir(cfg.exec_roots.items[i], cfg.lease_dir)) continue;
    roots[k++] = (struct root_entry){ cfg.exec_roots.items[i], 1 };
  }
  qsort(roots, (size_t)k, sizeof *roots, cmp_root);
  for (int i = 0; i < k; i++) {
    if (i > 0 && !strcmp(roots[i].path, roots[i - 1].path)) continue;
    if (bind_into_root(roots[i].path, 0, 0) != 0) {
      char what[PATH_MAX + 32];
      snprintf(what, sizeof what, "bind %s", roots[i].path);
      child_fail(ctl, what);
    }
  }
  free(roots);
  /* Anything that must never be seen and still lies beneath a read root
     (the daemon's state, say, under an approved tree) is covered — BEFORE
     the lease is bound, because the lease root usually lives inside the
     daemon's state, and the lease must land on top of the cover. */
  for (int i = 0; i < cfg.hide.n; i++) {
    struct stat st;
    snprintf(p, sizeof p, "%s%s", cfg.stage, cfg.hide.items[i]);
    if (lstat(p, &st) == 0 && S_ISDIR(st.st_mode) &&
        mount("tmpfs", p, "tmpfs", MS_NOSUID | MS_NODEV | MS_NOEXEC, "mode=0755,size=1m") != 0)
      child_fail(ctl, "hide path");
  }
  /* The lease itself, and any extra writable root a test declared: the
     writable trees, NOEXEC. */
  if (bind_into_root(cfg.lease_dir, 1, 0) != 0) child_fail(ctl, "bind own lease");
  for (int i = 0; i < cfg.write_roots.n; i++) {
    if (!strcmp(cfg.write_roots.items[i], cfg.lease_dir)) continue;
    if (bind_into_root(cfg.write_roots.items[i], 1, 0) != 0)
      child_fail(ctl, "bind writable root");
  }
  /* Materialized input artifacts, on top of the (noexec) lease: read-only
     and executable. */
  for (int i = 0; i < cfg.inputs.n; i++) {
    if (!under_dir(cfg.inputs.items[i], cfg.lease_dir)) child_fail(ctl, "input outside the lease");
    if (bind_input_ro_exec(cfg.inputs.items[i]) != 0) child_fail(ctl, "bind input artifacts");
  }
  /* A fresh /proc. */
  snprintf(p, sizeof p, "%s/proc", cfg.stage);
  if (mkdir(p, 0555) != 0 && errno != EEXIST) child_fail(ctl, "mkdir /proc");
  if (mount("proc", p, "proc", MS_NOSUID | MS_NODEV | MS_NOEXEC, NULL) != 0)
    child_fail(ctl, "mount proc");
  /* A minimal /dev: the character devices tools expect, bound from the
     host (no mknod in a user namespace), and a noexec /dev/shm. */
  snprintf(p, sizeof p, "%s/dev", cfg.stage);
  if (mkdir(p, 0755) != 0 && errno != EEXIST) child_fail(ctl, "mkdir /dev");
  if (mount("tmpfs", p, "tmpfs", MS_NOSUID | MS_NOEXEC, "mode=0755") != 0)
    child_fail(ctl, "/dev tmpfs");
  static const char *const devs[] = { "/dev/null", "/dev/zero", "/dev/full",
                                      "/dev/random", "/dev/urandom", "/dev/tty" };
  for (size_t i = 0; i < sizeof devs / sizeof devs[0]; i++)
    if (bind_into_root(devs[i], 1, 1) != 0) child_fail(ctl, "bind device");
  static const char *const links[][2] = { { "/proc/self/fd", "fd" },
    { "/proc/self/fd/0", "stdin" }, { "/proc/self/fd/1", "stdout" },
    { "/proc/self/fd/2", "stderr" } };
  for (size_t i = 0; i < sizeof links / sizeof links[0]; i++) {
    snprintf(p, sizeof p, "%s/dev/%s", cfg.stage, links[i][1]);
    if (symlink(links[i][0], p) != 0 && errno != EEXIST) child_fail(ctl, "dev link");
  }
  snprintf(p, sizeof p, "%s/dev/shm", cfg.stage);
  if (mkdir(p, 01777) != 0 && errno != EEXIST) child_fail(ctl, "mkdir /dev/shm");
  if (mount("tmpfs", p, "tmpfs", MS_NOSUID | MS_NODEV | MS_NOEXEC, "mode=1777") != 0)
    child_fail(ctl, "/dev/shm");
  /* Enter it; the old root is detached and gone. */
  if (chdir(cfg.stage) != 0) child_fail(ctl, "chdir stage");
  if (syscall(SYS_pivot_root, ".", ".") != 0) child_fail(ctl, "pivot_root");
  if (umount2(".", MNT_DETACH) != 0) child_fail(ctl, "detach old root");
  if (chdir("/") != 0) child_fail(ctl, "chdir /");
  /* The top level of the new root is set up: read-only from here on (the
     mounts below it keep their own flags — the lease, /tmp, /dev/shm stay
     writable and noexec). */
  if (mount(NULL, "/", NULL, MS_REMOUNT | MS_BIND | MS_RDONLY | MS_NOSUID |
            MS_NODEV | MS_NOEXEC, NULL) != 0)
    child_fail(ctl, "read-only new root");
}

