static int ll_add(int ruleset, const char *path, uint64_t access, uint64_t handled) {
  int fd = open(path, O_PATH | O_CLOEXEC);
  if (fd < 0) return errno == ENOENT ? 0 : -1;  /* an absent root grants nothing */
  struct stat st;
  if (fstat(fd, &st) == 0 && !S_ISDIR(st.st_mode))
    access &= (LL_EXECUTE | LL_WRITE_FILE | LL_READ_FILE | LL_TRUNCATE | LL_IOCTL_DEV);
  struct rl_path_beneath_attr a = { .allowed_access = access & handled, .parent_fd = fd };
  int rc = (int)syscall(SYS_landlock_add_rule, ruleset, RL_LL_RULE_PATH_BENEATH, &a, 0);
  close(fd);
  return rc;
}

static int apply_landlock(void) {
  int abi = (int)syscall(SYS_landlock_create_ruleset, NULL, 0, RL_LL_CREATE_RULESET_VERSION);
  if (abi < 1) return -1;
  uint64_t handled = LL_EXECUTE | LL_WRITE_FILE | LL_READ_FILE | LL_READ_DIR |
    LL_REMOVE_DIR | LL_REMOVE_FILE | LL_MAKE_CHAR | LL_MAKE_DIR | LL_MAKE_REG |
    LL_MAKE_SOCK | LL_MAKE_FIFO | LL_MAKE_BLOCK | LL_MAKE_SYM;
  if (abi >= 2) handled |= LL_REFER;
  if (abi >= 3) handled |= LL_TRUNCATE;
  if (abi >= 5) handled |= LL_IOCTL_DEV;
  struct rl_ruleset_attr attr = { .handled_access_fs = handled };
  int rs = (int)syscall(SYS_landlock_create_ruleset, &attr, sizeof attr.handled_access_fs, 0);
  if (rs < 0) return -1;
  const uint64_t rd = LL_READ_FILE | LL_READ_DIR;
  const uint64_t wr = rd | LL_WRITE_FILE | LL_REMOVE_DIR | LL_REMOVE_FILE |
    LL_MAKE_DIR | LL_MAKE_REG | LL_MAKE_SYM | LL_MAKE_FIFO | LL_MAKE_SOCK |
    LL_REFER | LL_TRUNCATE;
  int rc = 0;
  for (int i = 0; i < cfg.read_roots.n && rc == 0; i++) rc = ll_add(rs, cfg.read_roots.items[i], rd, handled);
  if (rc == 0) rc = ll_add(rs, cfg.lease_root, rd, handled);
  for (int i = 0; i < cfg.write_roots.n && rc == 0; i++) rc = ll_add(rs, cfg.write_roots.items[i], wr, handled);
  for (int i = 0; i < cfg.exec_roots.n && rc == 0; i++) rc = ll_add(rs, cfg.exec_roots.items[i], rd | LL_EXECUTE, handled);
  /* Character devices every tool expects. */
  if (rc == 0) rc = ll_add(rs, "/dev/null", LL_READ_FILE | LL_WRITE_FILE | LL_TRUNCATE, handled);
  if (rc == 0) rc = ll_add(rs, "/dev/tty", LL_READ_FILE | LL_WRITE_FILE, handled);
  if (rc == 0) rc = ll_add(rs, "/dev/full", LL_READ_FILE | LL_WRITE_FILE, handled);
  if (rc == 0) rc = ll_add(rs, "/dev/zero", LL_READ_FILE, handled);
  if (rc == 0) rc = ll_add(rs, "/dev/urandom", LL_READ_FILE, handled);
  if (rc == 0) rc = ll_add(rs, "/dev/random", LL_READ_FILE, handled);
  if (rc == 0) rc = ll_add(rs, "/proc", rd, handled);
  if (rc != 0) { close(rs); return -1; }
  rc = (int)syscall(SYS_landlock_restrict_self, rs, 0);
  close(rs);
  return rc;
}


