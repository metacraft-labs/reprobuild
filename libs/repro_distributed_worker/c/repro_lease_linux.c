static int list_add(struct rl_list *l, char *v) {
  if (l->n >= RL_MAX_ROOTS) return -1;
  if (l->n == l->cap) {
    int cap = l->cap ? l->cap * 2 : 64;
    char **items = realloc(l->items, (size_t)cap * sizeof *items);
    if (!items) return -1;
    l->items = items; l->cap = cap;
  }
  l->items[l->n++] = v;
  return 0;
}

static int parse_dest(char *v) {
  /* name|host|port|inner|innerport */
  if (cfg.n_dest >= RL_MAX_DEST) return -1;
  struct rl_dest *d = &cfg.dests[cfg.n_dest];
  memset(d, 0, sizeof *d);
  char *f[5]; int i = 0; char *save = NULL;
  for (char *t = strtok_r(v, "|", &save); t && i < 5; t = strtok_r(NULL, "|", &save)) f[i++] = t;
  if (i != 5) return -1;
  snprintf(d->name, sizeof d->name, "%s", f[0]);
  snprintf(d->host, sizeof d->host, "%s", f[1]);
  d->port = atoi(f[2]);
  snprintf(d->inner, sizeof d->inner, "%s", f[3]);
  d->inner_port = atoi(f[4]);
  d->listen_fd = -1;
  cfg.n_dest++;
  return 0;
}

static int cmp_str(const void *a, const void *b) {
  return strcmp(*(char *const *)a, *(char *const *)b);
}

static int parse_cfg(char *buf, size_t len) {
  memset(&cfg, 0, sizeof cfg);
  cfg.newuidmap = "/usr/bin/newuidmap";
  cfg.newgidmap = "/usr/bin/newgidmap";
  size_t pos = 0;
  while (pos < len) {
    char *k = buf + pos; pos += strlen(k) + 1;
    if (pos >= len) return -1;
    char *v = buf + pos; pos += strlen(v) + 1;
    int rc = 0;
    if (!strcmp(k, "mode")) cfg.cleanup = !strcmp(v, "cleanup");
    else if (!strcmp(k, "lease_id")) cfg.lease_id = v;
    else if (!strcmp(k, "lease_root")) cfg.lease_root = v;
    else if (!strcmp(k, "lease_dir")) cfg.lease_dir = v;
    else if (!strcmp(k, "cwd")) cfg.cwd = v;
    else if (!strcmp(k, "status")) cfg.status_path = v;
    else if (!strcmp(k, "report")) cfg.report_path = v;
    else if (!strcmp(k, "stdout")) cfg.stdout_path = v;
    else if (!strcmp(k, "stderr")) cfg.stderr_path = v;
    else if (!strcmp(k, "cgroup")) cfg.cgroup = v;
    else if (!strcmp(k, "stage")) cfg.stage = v;
    else if (!strcmp(k, "arg")) { if (cfg.argc >= RL_MAX_ARGS) rc = -1; else cfg.argv[cfg.argc++] = v; }
    else if (!strcmp(k, "env")) { if (cfg.envc >= RL_MAX_ENV) rc = -1; else cfg.envp[cfg.envc++] = v; }
    else if (!strcmp(k, "read")) rc = list_add(&cfg.read_roots, v);
    else if (!strcmp(k, "exec")) rc = list_add(&cfg.exec_roots, v);
    else if (!strcmp(k, "write")) rc = list_add(&cfg.write_roots, v);
    else if (!strcmp(k, "hide")) rc = list_add(&cfg.hide, v);
    else if (!strcmp(k, "closure")) rc = list_add(&cfg.closure, v);
    else if (!strcmp(k, "input")) rc = list_add(&cfg.inputs, v);
    else if (!strcmp(k, "memfd_noexec")) cfg.memfd_noexec = atoi(v);
    else if (!strcmp(k, "dest")) rc = parse_dest(v);
    else if (!strcmp(k, "layer_ns")) cfg.layer_ns = atoi(v);
    else if (!strcmp(k, "layer_landlock")) cfg.layer_landlock = atoi(v);
    else if (!strcmp(k, "layer_floor")) cfg.layer_floor = atoi(v);
    else if (!strcmp(k, "uid")) cfg.uid = atol(v);
    else if (!strcmp(k, "gid")) cfg.gid = atol(v);
    else if (!strcmp(k, "subuid")) cfg.subuid = atol(v);
    else if (!strcmp(k, "subgid")) cfg.subgid = atol(v);
    else if (!strcmp(k, "newuidmap")) cfg.newuidmap = v;
    else if (!strcmp(k, "newgidmap")) cfg.newgidmap = v;
    else if (!strcmp(k, "timeout_ms")) cfg.timeout_ms = atol(v);
    else if (!strcmp(k, "nproc_limit")) cfg.nproc_limit = atol(v);
    else if (!strcmp(k, "fsize_limit")) cfg.fsize_limit = atol(v);
    if (rc != 0) return -1;
  }
  cfg.argv[cfg.argc] = NULL;
  cfg.envp[cfg.envc] = NULL;
  if (!cfg.lease_dir || !cfg.lease_root || !cfg.status_path || !cfg.report_path) return -1;
  if (!cfg.cleanup && (cfg.argc == 0 || cfg.argv[0][0] != '/' || !cfg.cwd)) return -1;
  if (cfg.layer_floor && (cfg.subuid <= 0 || cfg.subgid <= 0)) return -1;
  if (!cfg.cleanup && cfg.layer_ns && (!cfg.stage || cfg.stage[0] != '/')) return -1;
  if (cfg.closure.n > 1) qsort(cfg.closure.items, (size_t)cfg.closure.n, sizeof(char *), cmp_str);
  return 0;
}

