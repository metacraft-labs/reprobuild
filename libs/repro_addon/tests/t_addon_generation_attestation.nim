## The signed generation attestation an add-on host puts in its evidence
## records (spec §10.5, threat model G23).
##
## It must verify only against the host's enrolled key and only over the
## exact statement; it must say what it covers and what it does not, and it
## must never present itself as host attestation. The producer-side digests
## it names must be the ones the off-host check derives from the manifest.
##
## Falsifying builds (``scripts/run_addon_unit_mutation.sh``):
## ``attestation-unsigned`` (the signature covers other bytes: the
## verification step goes red) and ``attestation-claims-host`` (the scope
## says host attestation: the "never host attestation" step goes red).
##
## Mocks: none. Real P-256 keys generated by the deploy agent's own key
## generation, a real state directory laid out as the switch lays it out,
## and real signed manifests.

import std/[os, strutils, times, unittest]

import repro_infra
import repro_deploy_agent/manifest
import repro_peer_cache/auth as peerAuth

import repro_addon/agent_record
import repro_addon/attestation
import repro_addon/fingerprint

let root = getTempDir() / ("addon-attestation-" & $getCurrentProcessId())
removeDir(root)
createDir(root)
let stateDir = root / "state"
let keyPath = root / "agent" / "attestation.key"

proc layGeneration(gen, ledger, profile: string; rec: AgentRecord) =
  ## A committed generation as the switch leaves it: its ledger, its
  ## profile, its agent record, and ``current`` pointing at it.
  let gd = generationDir(stateDir, gen)
  createDir(gd)
  writeFile(gd / GenerationLedgerName, ledger)
  writeFile(gd / GenerationUserProfileName, profile)
  if rec.present: writeFile(gd / AgentRecordName, render(rec))
  let cur = currentPath(stateDir)
  if symlinkExists(cur): removeFile(cur)
  createSymlink(gd, cur)

proc manifestFor(seqNo: uint64; text: string): DeployManifest =
  var m = DeployManifest(target: "h1", sequence: seqNo, deploymentId: "d" & $seqNo,
    profileText: text, issuedAt: uint64(getTime().toUnix()), maxAgeSeconds: 3600,
    closureDigests: @[ClosureDigest(actionId: "a", digest: "blake3:" & "1".repeat(64)),
                      ClosureDigest(actionId: "b", digest: "blake3:" & "2".repeat(64))])
  signManifest(peerAuth.generateKeypair(), m)
  m

suite "generation attestation":
  createDir(stateDir / "addon")
  writeFile(stateDir / "addon" / BootstrapEvidenceName,
    "{\"binarySha256\":\"" & "ab".repeat(32) & "\",\"generationId\":\"g0\"}\n")
  let m = manifestFor(7, "canonical profile text\n")
  layGeneration("g1", "ledger bytes\n", "canonical profile text\n",
    AgentRecord(deploymentId: m.deploymentId, sequence: m.sequence,
      profileDigest: manifestProfileDigestOf(m),
      closuresDigest: closureDigestsDigest(m.closureDigests)))
  let key = ensureAttestationKey(keyPath)

  test "the key is created 0400 and never replaced":
    check key.created
    check (getFilePermissions(keyPath) * {fpGroupRead, fpOthersRead}).len == 0
    check ensureAttestationKey(keyPath) == (key.publicKeyHex, false)

  test "the attestation names what the generation's files say":
    let a = currentAttestation(stateDir, "host-a")
    check a.generation == "g1"
    check a.ledgerDigest == "sha256:" & sha256Hex("ledger bytes\n")
    check a.profileDigest == "sha256:" & sha256Hex("canonical profile text\n")
    check a.sequence == 7'u64
    check a.deploymentId == "d7"
    check a.bootstrapDigest == "ab".repeat(32)
    # The producer side derives the same digests from the manifest.
    check a.manifestProfileDigest == "sha256:" & sha256Hex(m.profileText)
    check a.closuresDigest == closureDigestsDigest(@[m.closureDigests[1],
                                                     m.closureDigests[0]])

  test "it verifies against the enrolled key, and only over its statement":
    let s = signAttestation(currentAttestation(stateDir, "host-a"), keyPath)
    check verifyAttestation(s, key.publicKeyHex) == ""
    # Another key: refused, even when the record names that key itself.
    let other = peerAuth.generateKeypair()
    check verifyAttestation(s, peerAuth.publicKeyHex(other.publicKey)).len > 0
    var forged = s
    forged.statement = s.statement.replace("sequence=7", "sequence=8")
    check verifyAttestation(forged, key.publicKeyHex).len > 0
    check verifyAttestation(s, "").len > 0

  test "it is never presented as host attestation":
    let st = statement(currentAttestation(stateDir, "host-a"))
    check st.startsWith("scope=" & AttestationScope & "\n")
    check "host-attestation" notin st
    check ("notCovered=" & AttestationNotCovered) in st
    for part in ["kernel", "bootloader", "distribution-packages"]:
      check part in AttestationNotCovered
    check parseStatement(st).generation == "g1"
    expect AttestationError:
      discard parseStatement("scope=reprobuild.host-attestation.v1\nhost=x\n")

  test "a source profile's attestation names the compiled-profile pin":
    var src = manifestFor(9, "import repro\n")
    src.compiledProfile.digest = "sha256:" & "c".repeat(64)
    check manifestProfileDigestOf(src) == src.compiledProfile.digest
    check closureDigestsDigest(@[]) == ""

  test "an operator's generation carries no manifest digests":
    layGeneration("g2", "ledger 2\n", "operator text\n", AgentRecord())
    let a = currentAttestation(stateDir, "host-a")
    check a.generation == "g2"
    check a.sequence == 0'u64
    check a.manifestProfileDigest == ""
    check a.closuresDigest == ""

removeDir(root)
