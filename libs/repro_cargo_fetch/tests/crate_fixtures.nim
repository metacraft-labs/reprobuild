proc sha256Hex*(s: string): string = toLowerAscii($sha256.digest(s))

proc blake3Digest*(s: string): PrefixIdBytes =
  ## The key the store's `cas/` gives ``s``.
  PrefixIdBytes(blake3.digest(s.toOpenArrayByte(0, s.high)))

proc packCrate*(work, name, version: string;
                files: seq[(string, string)]): string =
  ## A real `.crate` of a library package ``name`` ``version`` holding
  ## ``files`` (relative path, content) beside its `Cargo.toml`, made by
  ## `cargo package`. Returns the archive's bytes.
  # The fixture tool that makes real crates, not something under test.
  let cargo = uncontrolledFindExe("cargo")
  doAssert cargo.len > 0, "cargo is not on PATH"
  let pkg = work / ("pkg-" & name & "-" & version)
  createDir(pkg)
  writeFile(pkg / "Cargo.toml", "[package]\nname = \"" & name &
    "\"\nversion = \"" & version & "\"\nedition = \"2021\"\n" &
    "description = \"fixture\"\nlicense = \"MIT\"\n\n[lib]\npath = " &
    "\"src/lib.rs\"\n")
  for (rel, content) in files:
    createDir(parentDir(pkg / rel))
    writeFile(pkg / rel, content)
  let env = newStringTable(modeCaseSensitive)
  for k, v in envPairs(): env[k] = v
  env["CARGO_HOME"] = work / "packager-cargo-home"
  env["CARGO_TARGET_DIR"] = work / "packager-target"
  let p = uncontrolledStartProcess(cargo, workingDir = pkg, args = ["package",
    "--no-verify", "--allow-dirty", "--offline", "--quiet"], env = env,
    options = {poStdErrToStdOut})
  let output = drainStream(p.outputStream)
  let code = p.waitForExit()
  p.close()
  doAssert code == 0, "cargo package failed:\n" & output
  readFile(work / "packager-target" / "package" / (name & "-" & version &
    ".crate"))

proc handCrate*(work: string; members: seq[TarMember]): string =
  ## A gzipped hand-made tar of ``members``, in order.
  gzipOf(work, tarOf(members))

proc lockText*(rows: seq[CrateRow];
               extra: seq[(string, string, string)] = @[]): string =
  ## A `Cargo.lock` (format v4) for a fixture project depending on
  ## ``rows``, each from crates.io, plus ``extra`` packages (name, version,
  ## source) with no checksum.
  result = "# This file is automatically @generated by Cargo.\n" &
    "# It is not intended for manual editing.\nversion = 4\n\n" &
    "[[package]]\nname = \"fixture-project\"\nversion = \"0.1.0\"\n" &
    "dependencies = [\n"
  for r in rows: result.add " \"" & r.name & "\",\n"
  result.add "]\n"
  for r in rows:
    result.add "\n[[package]]\nname = \"" & r.name & "\"\nversion = \"" &
      r.version & "\"\nsource = \"registry+https://github.com/rust-lang/" &
      "crates.io-index\"\nchecksum = \"" & r.cksum & "\"\n"
  for (n, v, s) in extra:
    result.add "\n[[package]]\nname = \"" & n & "\"\nversion = \"" & v &
      "\"\nsource = \"" & s & "\"\n"

type
  CrateFixture* = object
    f*: Fixture
    mirrorDir*: string   ## served at https://mirror.test:<port>/mirror/
    originDir*: string   ## served at https://forge.test:<port>/origin/

proc newCrateFixture*(prefix: string): CrateFixture =
  result.mirrorDir = createTempDir("cg4a-" & prefix & "-mirror-", "")
  result.originDir = createTempDir("cg4a-" & prefix & "-origin-", "")
  result.f = newFixture(prefix, @[
    Route(prefix: "/mirror/", serveDir: result.mirrorDir),
    Route(prefix: "/origin/", serveDir: result.originDir)])

proc httpsMirror*(cf: CrateFixture): Mirror =
  parseMirror("https://" & MirrorHost & ":" & $cf.f.port & "/mirror/")

proc originBase*(cf: CrateFixture): string =
  "https://" & ForgeHost & ":" & $cf.f.port & "/origin/"

proc putOnHttpsMirror*(cf: CrateFixture; cksum, bytes: string) =
  let p = cf.mirrorDir / crateObjectPath(cksum)
  createDir(parentDir(p))
  writeFile(p, bytes)

proc putAtOrigin*(cf: CrateFixture; name, version, bytes: string) =
  let p = cf.originDir / name / version / "download"
  createDir(parentDir(p))
  writeFile(p, bytes)

proc crateConfig*(cf: CrateFixture; stateDir, store: string;
                  mirrors: seq[Mirror]; withOrigin = true): CrateFetchConfig =
  CrateFetchConfig(stateDir: stateDir, storeRoot: store, mirrors: mirrors,
    mirrorAccess: cf.f.mirrorPolicy(),
    originBase: (if withOrigin: cf.originBase() else: ""),
    originPolicy: cf.f.testPolicy(), limits: DefaultExtractLimits)

proc requestsFor*(cf: CrateFixture; needle: string): int =
  cf.f.requestsMatching(needle)

proc cratePrefixDirs*(store, name: string): seq[string] =
  ## The prefix directories published for crate ``name``.
  let d = store / "prefixes" / name
  if dirExists(d):
    for kind, p in walkDir(d):
      if kind == pcDir: result.add p

proc stagingEntries*(store: string): seq[string] =
  ## What the store's staging area still holds.
  if dirExists(store / "tmp"):
    for kind, p in walkDir(store / "tmp"): result.add p

proc filesUnder*(dir: string): seq[string] =
  ## Every regular file and link under ``dir``, relative, sorted.
  if not dirExists(dir): return
  for p in walkDirRec(dir, yieldFilter = {pcFile, pcLinkToFile, pcLinkToDir},
                      relative = true):
    result.add p
  result = result.sorted()

proc removeTestTree*(dir: string) =
  ## Remove a test's directory, read-only store prefixes included.
  if dir.len == 0 or not dirExists(dir): return
  discard uncontrolledExecShellCmd("chmod -R u+w " & quoteShell(dir))
  removeDir(dir)

proc cleanup*(cf: CrateFixture) =
  ## Remove what the fixture served and logged.
  removeTestTree(cf.mirrorDir)
  removeTestTree(cf.originDir)
  removeTestTree(cf.f.dir)
