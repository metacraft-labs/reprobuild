## Test support (not a test): the registry crate fetch's tests.
##
## Nothing here contacts the internet. Mirrors and the origin are served by
## the Nimble fetch's HTTPS fixture (`fetch_fixtures`, on top of
## `generator_fixtures`): a TLS listener on 127.0.0.1 with a certificate
## minted for the test's host names. A mirror is a location the
## configuration names, so `mirror.test` resolves to 127.0.0.1 directly;
## the origin goes through the production origin egress policy, where the
## test's resolver answers the documentation address 203.0.113.10 for
## `forge.test` and the dialer maps that address alone to the listener.
## That is the only substitution, and it is the one the Nimble fetch's tests
## make: the policy still checks the address the resolver answered.
##
## Crates are real `.crate` files made by `cargo package` from a fixture
## package (GNU tar headers, a gzip stream of one member, one top directory
## `<name>-<version>/`, as crates.io serves them), or hand-made tar archives
## for the archives a registry must never serve (`../` names and the like).
## `cargo package` runs with a private, empty `CARGO_HOME`, never the
## user's, and offline.

