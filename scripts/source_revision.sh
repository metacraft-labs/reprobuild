#!/usr/bin/env bash
# The source revision a reprobuild image is built from -- the ONE place that
# derives it.
#
# `ReprobuildSourceRevision` (libs/repro_core/src/repro_core.nim) names the
# commit an image was built from, because the version string alone does not
# identify a build; `repro home export` records it as provenance. Two routes
# build the engine: `scripts/build_apps.sh` and the `reprobuild.apps.reprobuild`
# edge in `repro.nim`. They used to derive the value separately, and the graph
# route had no git fallback, so the engine `repro build` produced carried no
# revision at all. Both now ask this script (spec/Core-Invariants.md, "One
# Implementation Per Concern").
#
# The revision is, in order:
#
#   1. `$REPROBUILD_SOURCE_REVISION` when it is set and non-empty. The Nix
#      package sets it from the flake (its sandbox has no .git) and the release
#      workflow sets it to `github.sha`. It is read when THIS SCRIPT RUNS --
#      on the graph route that is action run time, never recipe evaluation,
#      whose snapshot would be served stale to later builds
#      (docs/user-guide/idiomatic-reprobuild.md §4.4).
#   2. Otherwise `git rev-parse HEAD` of the tree, with `-dirty` appended when
#      `git diff --quiet HEAD --` fails (tracked files differ from HEAD). The
#      tree must be the TOP LEVEL of its git work tree: a reprobuild source
#      copy that merely sits inside some other repository (an unpacked tarball
#      in a checkout, say) would otherwise report that repository's commit.
#   3. Otherwise empty: the image reports its revision as unknown.
#
# A revision is restricted to [A-Za-z0-9._+-]. Anything else is refused rather
# than escaped: no real revision needs it, and the value is spliced into a
# compiler define and into Nim source below.
#
# Usage:
#   source_revision.sh [--tree DIR]
#       Print the revision followed by a newline, or nothing when unknown.
#   source_revision.sh [--tree DIR] --nim-module PATH
#       Write PATH as a Nim module declaring
#         const reprobuildGeneratedSourceRevision* = "<revision>"
#       (`""` when unknown). This is what the graph edge compiles in; see the
#       `reprobuild.apps.source-revision` edge in repro.nim. The content is a
#       function of the revision alone, and a module that already holds it is
#       not rewritten: the engine edge that reads the file revalidates it by
#       timestamp, so only an untouched file keeps that edge a cache hit.
#
# DIR defaults to the repository this script lives in. Exit status: 0 on
# success (an unknown revision included), 2 on a usage error, 3 when the
# revision contains a refused character.
#
# Only bash builtins, `git` and (for --nim-module) `mkdir` run here: the graph
# edge declares exactly those tools, and under path-mode tool provisioning an
# undeclared tool is not on the action's PATH.
set -euo pipefail
export LC_ALL=C

script_dir="${BASH_SOURCE[0]%/*}"
[ "${script_dir}" = "${BASH_SOURCE[0]}" ] && script_dir="."
tree="${script_dir}/.."
nim_module=""

while [ "$#" -gt 0 ]; do
  case "$1" in
    --tree)
      [ "$#" -ge 2 ] || { echo "source_revision.sh: --tree needs a value" >&2; exit 2; }
      tree="$2"; shift 2 ;;
    --nim-module)
      [ "$#" -ge 2 ] || { echo "source_revision.sh: --nim-module needs a value" >&2; exit 2; }
      nim_module="$2"; shift 2 ;;
    *)
      echo "source_revision.sh: unknown argument: $1" >&2; exit 2 ;;
  esac
done

revision="${REPROBUILD_SOURCE_REVISION:-}"
# `--show-prefix` prints the tree's path below the work-tree top level, so it
# is empty exactly when DIR is the top level. Comparing prefixes rather than
# absolute paths keeps this correct on Windows, where git and bash spell the
# same directory differently (`C:/...` versus `/c/...`).
if [ -z "${revision}" ] && command -v git >/dev/null 2>&1 &&
   prefix="$(git -C "${tree}" rev-parse --show-prefix 2>/dev/null)" &&
   [ -z "${prefix}" ] &&
   revision="$(git -C "${tree}" rev-parse HEAD 2>/dev/null)"; then
  if ! git -C "${tree}" diff --quiet HEAD -- 2>/dev/null; then
    revision="${revision}-dirty"
  fi
fi

case "${revision}" in
  *[!A-Za-z0-9._+-]*)
    echo "source_revision.sh: refusing revision with characters outside" \
      "[A-Za-z0-9._+-]: '${revision}'" >&2
    exit 3 ;;
esac

if [ -z "${nim_module}" ]; then
  if [ -n "${revision}" ]; then
    printf '%s\n' "${revision}"
  fi
  exit 0
fi

module_dir="${nim_module%/*}"
if [ "${module_dir}" != "${nim_module}" ] && [ -n "${module_dir}" ]; then
  mkdir -p "${module_dir}"
fi
printf -v content '%s\n%s\n' \
  "# Generated by scripts/source_revision.sh -- do not edit." \
  "const reprobuildGeneratedSourceRevision* = \"${revision}\""
# Leave an up-to-date module ALONE. Identical bytes are not enough to keep the
# engine edge a cache hit: its recorded inputs are revalidated by timestamp
# metadata first (the default `ffpTimestamp` policy), so rewriting the same
# bytes gives the file a new mtime and the engine misses on
# "input metadata changed" on every build. This probe edge is uncacheable and
# runs on every build, so the module must change on disk exactly when the
# revision does. `read -d ''` reads the whole file through a builtin; it
# returns non-zero at end of file, which is expected here.
existing=""
if [ -f "${nim_module}" ]; then
  IFS= read -r -d '' existing < "${nim_module}" || true
fi
if [ "${existing}" != "${content}" ]; then
  printf '%s' "${content}" > "${nim_module}"
fi
