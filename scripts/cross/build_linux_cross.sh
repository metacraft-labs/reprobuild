#!/usr/bin/env bash
# build_linux_cross.sh — cross-compile an installable reprobuild prefix for
# another Linux architecture, against a sysroot taken from the target.
#
# Usage (from the reprobuild checkout root, INSIDE the dev shell):
#
#   nix develop --command scripts/cross/build_linux_cross.sh \
#       --sysroot build/cross/arm-linux-gnueabihf/sysroot
#
# One-command rebuild and reinstall on a reachable target (fetch sysroot,
# build, install under /usr/local/repro with links in /usr/local/bin):
#
#   nix develop --command scripts/cross/build_linux_cross.sh \
#       --fetch-sysroot-from <ssh-destination> [--ssh <ssh-program>] --install
#
# Options:
#   --sysroot DIR        sysroot to link against (scripts/cross/fetch_target_sysroot.sh)
#   --fetch-sysroot-from DEST
#                        (re)fetch the sysroot from DEST first ("" with --ssh
#                        for a wrapper that already names the host)
#   --ssh PROGRAM        ssh program for --fetch-sysroot-from
#   --triple TRIPLE      GNU multiarch triple (default: arm-linux-gnueabihf)
#   --out DIR            output root (default: build/cross/<triple>)
#   --entrypoints LIST   space-separated apps/entrypoints.txt names to build
#                        (default: the set an installed host needs, below)
#   --skip-nim           do not cross-build the Nim compiler
#   --install            install the result on the --fetch-sysroot-from host
#                        (passwordless sudo there): the prefix is unpacked
#                        beside --install-prefix and swapped in by rename, and
#                        repro, reprobuild and nim are linked into --bin-links
#   --install-prefix DIR install prefix on the target (default /usr/local/repro)
#   --bin-links DIR      directory for the PATH links (default /usr/local/bin)
#
# Environment:
#   REPROBUILD_BUILD_MODE  debug (default, as scripts/build_apps.sh) | release
#   REPRO_CROSS_ARCH_FLAGS target code-generation flags; the default for the
#                          armhf triple is Debian's armhf baseline (ARMv7-A,
#                          VFPv3-D16, hard float), which every Raspberry Pi
#                          from the Pi 2 on executes
#   REPRO_CROSS_CLANG / REPRO_CROSS_LLD
#                          an unwrapped clang / an lld bin dir; resolved from
#                          this flake's nixpkgs when unset
#
# OUTPUT. `<out>/prefix/` is an installed layout (Distribution-And-Packaging
# §5, the one `repro_core/source_root` resolves from the running image):
#
#   bin/reprobuild, bin/repro, bin/<providers>   the engine and its siblings
#   bin/reprobuild-sandbox-launcher
#   bin/nim -> ../nim/bin/nim                     the fork compiler, cross-built
#   lib/librepro_monitor_shim.so                  io-mon's interpose shim
#   lib/librepro_project_dsl_runtime.so           the Tier-1 DSL runtime
#   nim/{bin,lib,config,dist}                     the Nim installation tree
#   share/repro/source, share/repro/src           the sources post-install
#                                                 compiles build against
#
# and `<out>/reprobuild-<version>-linux-<arch>.tar.gz` is that prefix packed.
# Installing is `tar -C <prefix> --strip-components=1 -xzf <tarball>`.
#
# WHY CROSS-COMPILE, AND WHY THIS WAY. The first target is a Raspberry Pi 2
# (4 x Cortex-A7 @ 900 MHz, 1 GB RAM). A native build of the engine there
# takes hours and does not fit in memory without swap; the same C compiled on
# a workstation takes minutes. The C is generated by the same `nim` that
# builds the native images, with `--cpu`/`--os` naming the target, and with
# the per-entrypoint flags read from `apps/entrypoints.txt` -- the table
# `scripts/build_apps.sh` reads -- so a cross image and a native image of the
# same revision differ only in the target. The C compiler is an UNWRAPPED
# clang (any clang is a cross compiler) linking with lld against the target's
# own sysroot, so the binaries reference only the target's glibc and
# libraries and need no relocation on the target.
#
# The nixpkgs clang is built not to pass `-dynamic-linker` itself (its cc
# wrapper supplies the loader), so the wrapper below names the target's
# loader for every executable link. Without it lld emits a PIE with no
# PT_INTERP, which the kernel starts as a static PIE and which dies at its
# first relocation (SIGSEGV before main, nothing from LD_DEBUG).
set -euo pipefail

usage() { sed -n '2,40p' "$0" >&2; exit 64; }

sysroot=""
fetch_from=""
fetch_requested=0
ssh_program=""
triple="arm-linux-gnueabihf"
out=""
entrypoints=""
skip_nim=0
install=0
install_prefix=/usr/local/repro
bin_links=/usr/local/bin
while [ "$#" -gt 0 ]; do
  case "$1" in
    --sysroot) sysroot="$2"; shift 2 ;;
    --sysroot=*) sysroot="${1#--sysroot=}"; shift ;;
    --fetch-sysroot-from) fetch_from="$2"; fetch_requested=1; shift 2 ;;
    --fetch-sysroot-from=*) fetch_from="${1#--fetch-sysroot-from=}"; fetch_requested=1; shift ;;
    --ssh) ssh_program="$2"; shift 2 ;;
    --ssh=*) ssh_program="${1#--ssh=}"; shift ;;
    --triple) triple="$2"; shift 2 ;;
    --triple=*) triple="${1#--triple=}"; shift ;;
    --out) out="$2"; shift 2 ;;
    --out=*) out="${1#--out=}"; shift ;;
    --entrypoints) entrypoints="$2"; shift 2 ;;
    --entrypoints=*) entrypoints="${1#--entrypoints=}"; shift ;;
    --skip-nim) skip_nim=1; shift ;;
    --install) install=1; shift ;;
    --install-prefix) install_prefix="$2"; shift 2 ;;
    --install-prefix=*) install_prefix="${1#--install-prefix=}"; shift ;;
    --bin-links) bin_links="$2"; shift 2 ;;
    --bin-links=*) bin_links="${1#--bin-links=}"; shift ;;
    -h|--help) usage ;;
    *) echo "build_linux_cross: unknown argument: $1" >&2; usage ;;
  esac
done

[ -f libs/repro_project_dsl/src/repro_project_dsl.nim ] || {
  echo "build_linux_cross: run from the reprobuild checkout root" >&2; exit 64; }
command -v nim >/dev/null 2>&1 || {
  echo "build_linux_cross: no nim on PATH -- run inside the dev shell (nix develop)" >&2; exit 64; }

repo_root="$(pwd)"
out="${out:-build/cross/${triple}}"
mkdir -p "${out}"
out="$(cd "${out}" && pwd)"
sysroot="${sysroot:-${out}/sysroot}"

# ---------------------------------------------------------------------------
# Target table. One row per supported triple: Nim's --cpu, the code-generation
# baseline, the loader path and the architecture suffix of the archive name.
# ---------------------------------------------------------------------------
case "${triple}" in
  arm-linux-gnueabihf)
    nim_cpu=arm
    default_arch_flags="-march=armv7-a -mfpu=vfpv3-d16 -mfloat-abi=hard"
    dynamic_linker=/lib/ld-linux-armhf.so.3
    archive_arch=armv7l
    ;;
  aarch64-linux-gnu)
    nim_cpu=arm64
    default_arch_flags=""
    dynamic_linker=/lib/ld-linux-aarch64.so.1
    archive_arch=aarch64
    ;;
  *)
    echo "build_linux_cross: unsupported triple '${triple}' (add a row to the target table)" >&2
    exit 64
    ;;
esac
arch_flags="${REPRO_CROSS_ARCH_FLAGS-${default_arch_flags}}"

if [ "${fetch_requested}" = 1 ]; then
  fetch_args=(--triple "${triple}")
  [ -n "${ssh_program}" ] && fetch_args+=(--ssh "${ssh_program}")
  bash scripts/cross/fetch_target_sysroot.sh "${fetch_args[@]}" "${fetch_from}" "${sysroot}"
fi
[ -f "${sysroot}/.sysroot-info" ] || {
  echo "build_linux_cross: ${sysroot} is not a fetched sysroot (no .sysroot-info);" >&2
  echo "  run scripts/cross/fetch_target_sysroot.sh or pass --fetch-sysroot-from" >&2
  exit 1; }
sysroot="$(cd "${sysroot}" && pwd)"

started_at=$(date +%s)

# ---------------------------------------------------------------------------
# Toolchain: an unwrapped clang + lld from this flake's nixpkgs, behind a
# wrapper that fixes the target, the sysroot and the loader.
# ---------------------------------------------------------------------------
resolve_nixpkgs_out() {
  nix build --no-link --print-out-paths --inputs-from "${repo_root}" "nixpkgs#$1" |
    grep -v -- '-man$\|-dev$\|-lib$' | head -n1
}
clang_bin="${REPRO_CROSS_CLANG:-$(resolve_nixpkgs_out llvmPackages.clang-unwrapped)/bin/clang}"
lld_bin_dir="${REPRO_CROSS_LLD:-$(resolve_nixpkgs_out llvmPackages.lld)/bin}"
[ -x "${clang_bin}" ] || { echo "build_linux_cross: no clang at ${clang_bin}" >&2; exit 1; }
[ -x "${lld_bin_dir}/ld.lld" ] || { echo "build_linux_cross: no ld.lld in ${lld_bin_dir}" >&2; exit 1; }

toolchain_dir="${out}/toolchain"
mkdir -p "${toolchain_dir}"
cc_wrapper="${toolchain_dir}/${triple}-cc"
cat > "${cc_wrapper}" <<EOF
#!/usr/bin/env bash
# Generated by scripts/cross/build_linux_cross.sh -- clang for ${triple}
# against ${sysroot}.
link_executable=1
for arg in "\$@"; do
  case "\$arg" in
    -c|-S|-E|-shared|-static|-static-pie|-r|-M|-MM) link_executable=0 ;;
  esac
done
extra=()
if [ "\$link_executable" = 1 ]; then
  extra+=("-Wl,-dynamic-linker,${dynamic_linker}")
fi
exec "${clang_bin}" --target=${triple} ${arch_flags} --sysroot="${sysroot}" \\
  -fuse-ld=lld --ld-path="${lld_bin_dir}/ld.lld" \\
  -Wno-unused-command-line-argument \\
  "\${extra[@]}" "\$@"
EOF
chmod +x "${cc_wrapper}"

# The flags that turn a `nim c` of this tree into a cross compile. Everything
# else a `nim c` here receives is what scripts/build_apps.sh passes.
nim_cross_flags=(
  "--cpu:${nim_cpu}"
  "--os:linux"
  "--cc:clang"
  "--clang.exe:${cc_wrapper}"
  "--clang.linkerexe:${cc_wrapper}"
)

# The dev shell describes the BUILD host's libraries: x86-64 store prefixes in
# NIX_LDFLAGS and in the *_PREFIX / *_LIBDIR variables config.nims consults
# for blake3, xxhash, sqlite and OpenSSL. Every one of them would put a
# build-host library on the target's link line (or into its RPATH), so they
# are withheld from every cross `nim c`; the target's own copies are found in
# the sysroot by the linker's default search. The vendored blake3 / xxhash
# sources are compiled in instead of the host's libraries.
cross_env=(
  env
  -u NIX_LDFLAGS -u NIX_CFLAGS_COMPILE -u NIX_CFLAGS_LINK -u NIX_CC
  -u LD_LIBRARY_PATH -u LIBRARY_PATH -u CPATH -u C_INCLUDE_PATH
  -u OPENSSL_LIBDIR -u OPENSSL_PREFIX -u SQLITE_LIBDIR -u SQLITE_PREFIX
  -u BLAKE3_PREFIX -u XXHASH_PREFIX -u CLINGO_PREFIX -u ZSTD_PREFIX
  REPROBUILD_USE_SYSTEM_HASH_LIBS=0
)

nim_mode_flags=(--parallelBuild:"${NIX_BUILD_CORES:-0}")
source_revision="$(bash scripts/source_revision.sh --tree .)"
if [ -n "${source_revision}" ]; then
  nim_mode_flags+=("-d:ReprobuildSourceRevision=${source_revision}")
fi
case "${REPROBUILD_BUILD_MODE:-debug}" in
  debug) ;;
  release) nim_mode_flags+=("-d:release") ;;
  *) echo "unsupported REPROBUILD_BUILD_MODE=${REPROBUILD_BUILD_MODE}" >&2; exit 2 ;;
esac

stage="${out}/stage"
nimcache="${out}/nimcache"
rm -rf "${stage}"
mkdir -p "${stage}/bin" "${stage}/lib" "${nimcache}"

failures=()
record_failure() { failures+=("$1"); echo "build_linux_cross: FAILED: $1" >&2; }

# The ELF machine every produced image must carry; a build-host image that
# slipped through would otherwise be found only on the target.
expected_machine="$(case "${nim_cpu}" in arm) echo ARM ;; arm64) echo AArch64 ;; esac)"
check_target_elf() {
  local path="$1" machine
  # e_machine, little-endian, at offset 18 (both targets are little-endian).
  machine="$(od -An -tx1 -j18 -N2 "${path}" 2>/dev/null | tr -d ' \n')"
  case "${machine}" in
    2800) machine=ARM ;;
    b700) machine=AArch64 ;;
  esac
  if [ "${machine}" != "${expected_machine}" ]; then
    record_failure "${path}: ELF machine is '${machine}', expected '${expected_machine}'"
    return 1
  fi
}

# ---------------------------------------------------------------------------
# 1. io-mon's monitor shim, through io-mon's own builder (it appends our
#    arguments to its `nim c`). Every monitored edge needs it: without it
#    `repro internal io monitor` refuses to run, and the profile compile is
#    one such edge.
# ---------------------------------------------------------------------------
io_mon_src="${IO_MON_SRC:-../io-mon}"
io_mon_src="${io_mon_src%/src}"
shm_queue_src="$(source scripts/source_paths.sh && resolve_shm_queue_src)"
echo "build_linux_cross: [1/5] io-mon monitor shim"
if "${cross_env[@]}" \
    IO_MON_SHIM_OUT_DIR="${stage}/lib" \
    IO_MON_SHIM_NIMCACHE_DIR="${nimcache}/io-mon-shim" \
    IO_MON_BUILD_MODE="${REPROBUILD_BUILD_MODE:-debug}" \
    SHM_QUEUE_SRC="${shm_queue_src}" \
    bash "${io_mon_src}/scripts/build_shim.sh" "${nim_cross_flags[@]}"; then
  check_target_elf "${stage}/lib/librepro_monitor_shim.so" || true
else
  record_failure "io-mon monitor shim"
fi

# ---------------------------------------------------------------------------
# 2. Entry points, with exactly the per-entrypoint flags of
#    apps/entrypoints.txt.
# ---------------------------------------------------------------------------
# The default set is what an installed host runs: the engine, the thin client
# on PATH, and the two provider images the engine resolves as its siblings
# (`siblingStandardProviderPath` / `siblingTryCompileProviderPath`).
entrypoints="${entrypoints:-reprobuild repro repro-standard-provider repro-cmake-trycompile-provider}"
echo "build_linux_cross: [2/5] entry points: ${entrypoints}"
for wanted in ${entrypoints}; do
  row="$(awk -v n="${wanted}" '$1 == n { print; exit }' apps/entrypoints.txt)"
  if [ -z "${row}" ]; then
    record_failure "${wanted}: not listed in apps/entrypoints.txt"
    continue
  fi
  read -r name path extra_flags <<< "${row}"
  # shellcheck disable=SC2206
  extra_flag_array=(${extra_flags})
  ssl_flags=()
  for f in ${extra_flag_array[@]+"${extra_flag_array[@]}"}; do
    case "$f" in
      --define:ssl|-d:ssl) ssl_flags=("--passL:-lssl" "--passL:-lcrypto") ;;
    esac
  done
  echo "build_linux_cross:   ${name} <- ${path}"
  if "${cross_env[@]}" nim c \
      "${nim_mode_flags[@]}" \
      "${nim_cross_flags[@]}" \
      ${extra_flag_array[@]+"${extra_flag_array[@]}"} \
      ${ssl_flags[@]+"${ssl_flags[@]}"} \
      --nimcache:"${nimcache}/${name}" \
      --out:"${stage}/bin/${name}" \
      "${path}"; then
    check_target_elf "${stage}/bin/${name}" || true
  else
    record_failure "${name}: nim c ${path}"
  fi
done

# ---------------------------------------------------------------------------
# 3. The shared DSL runtime library (as scripts/build_apps.sh builds it).
# ---------------------------------------------------------------------------
echo "build_linux_cross: [3/5] DSL runtime library"
if "${cross_env[@]}" nim c \
    "${nim_mode_flags[@]}" \
    "${nim_cross_flags[@]}" \
    --app:lib --threads:on --mm:orc \
    --define:reproProviderMode --define:reproProviderRuntimeDll \
    --nimcache:"${nimcache}/repro-project-dsl-runtime-dll" \
    --out:"${stage}/lib/librepro_project_dsl_runtime.so" \
    libs/repro_project_dsl_runtime_dll/src/repro_project_dsl_runtime_entry.nim; then
  check_target_elf "${stage}/lib/librepro_project_dsl_runtime.so" || true
else
  record_failure "librepro_project_dsl_runtime"
fi

# ---------------------------------------------------------------------------
# 4. The sandbox launcher (plain C, its own build script).
# ---------------------------------------------------------------------------
echo "build_linux_cross: [4/5] reprobuild-sandbox-launcher"
if CC="${cc_wrapper}" bash apps/reprobuild-sandbox-launcher/build.sh \
    --out "${stage}/bin/reprobuild-sandbox-launcher"; then
  check_target_elf "${stage}/bin/reprobuild-sandbox-launcher" || true
else
  record_failure "reprobuild-sandbox-launcher"
fi

# ---------------------------------------------------------------------------
# 5. The Nim compiler: the same fork, at the same revision, that the dev shell
#    builds reprobuild with (`nix/pkgs/by-name/re/reprobuild/nim-fork.nix`), so
#    the host compiles recipes and profiles with the compiler its engine was
#    built by. The installation tree (lib/, config/, dist/) is target-neutral
#    and is copied from the dev shell's build of that derivation; only
#    `bin/nim` is cross-compiled, from the derivation's own source inputs and
#    with its own flags.
# ---------------------------------------------------------------------------
if [ "${skip_nim}" = 0 ]; then
  echo "build_linux_cross: [5/5] Nim compiler"
  host_system="$(nix eval --raw --impure --expr builtins.currentSystem)"
  nim_attr=".#packages.${host_system}.nim-fork"
  nim_tree="$(nix eval --raw "${nim_attr}.outPath")"
  if [ "$(command -v nim)" != "${nim_tree}/bin/nim" ]; then
    echo "build_linux_cross: note: the nim on PATH ($(command -v nim)) is not ${nim_tree}/bin/nim" >&2
  fi
  nim_src_dir="${out}/nim-src"
  rm -rf "${nim_src_dir}"
  cp -r "$(nix eval --raw "${nim_attr}.passthru.sources.forkSrc.outPath")" "${nim_src_dir}"
  chmod -R u+w "${nim_src_dir}"
  mkdir -p "${nim_src_dir}/dist"
  for pair in traceFormatSrc:codetracer-trace-format-nim stewSrc:nim-stew \
              resultsSrc:nim-results checksumsSrc:checksums nimonySrc:nimony; do
    cp -r "$(nix eval --raw "${nim_attr}.passthru.sources.${pair%%:*}.outPath")" \
      "${nim_src_dir}/dist/${pair#*:}"
  done
  chmod -R u+w "${nim_src_dir}/dist"
  mkdir -p "${stage}/nim/bin"
  if (cd "${nim_src_dir}" && "${cross_env[@]}" nim c \
      --parallelBuild:"${NIX_BUILD_CORES:-0}" -d:release -d:nimKochBootstrap \
      --skipUserCfg --skipParentCfg --noNimblePath \
      --warning:BareExcept:off --warning:UnusedImport:off \
      "${nim_cross_flags[@]}" \
      --nimcache:"${nimcache}/nim-compiler" \
      -o:"${stage}/nim/bin/nim" compiler/nim.nim); then
    check_target_elf "${stage}/nim/bin/nim" || true
    cp -r "${nim_tree}/lib" "${nim_tree}/config" "${nim_tree}/dist" "${stage}/nim/"
    chmod -R u+w "${stage}/nim"
    find "${stage}/nim" -xtype l -delete
    ln -sfn ../nim/bin/nim "${stage}/bin/nim"
  else
    record_failure "nim compiler"
  fi
fi

if [ "${#failures[@]}" -gt 0 ]; then
  echo "" >&2
  echo "build_linux_cross: ${#failures[@]} step(s) failed:" >&2
  printf '  - %s\n' "${failures[@]}" >&2
  exit 1
fi

# ---------------------------------------------------------------------------
# Assemble the prefix and the archive.
# ---------------------------------------------------------------------------
bash scripts/release/stage_release_sources.sh "${stage}"
version="$(sed -nE 's/^version[[:space:]]*=[[:space:]]*"([^"]+)".*/\1/p' reprobuild.nimble)"
pkg_name="reprobuild-${version}-linux-${archive_arch}"
{
  echo "source_revision=${source_revision:-unknown}"
  echo "triple=${triple}"
  echo "arch_flags=${arch_flags}"
  echo "build_mode=${REPROBUILD_BUILD_MODE:-debug}"
  cat "${sysroot}/.sysroot-info"
} > "${stage}/share/repro/cross-build-info"
rm -rf "${out}/prefix"
mv "${stage}" "${out}/prefix"
rm -f "${out}/${pkg_name}.tar.gz"
tar -C "${out}" --transform "s|^prefix|${pkg_name}|" -czf "${out}/${pkg_name}.tar.gz" prefix
elapsed=$(( $(date +%s) - started_at ))
echo "build_linux_cross: OK (${elapsed}s) -- ${out}/prefix and ${out}/${pkg_name}.tar.gz"
echo "build_linux_cross: source revision ${source_revision:-unknown}"

# ---------------------------------------------------------------------------
# Optional: install on the host the sysroot came from.
# ---------------------------------------------------------------------------
if [ "${install}" = 1 ]; then
  if [ "${fetch_requested}" != 1 ]; then
    echo "build_linux_cross: --install needs --fetch-sysroot-from (the host to install on)" >&2
    exit 64
  fi
  remote_cmd=(ssh)
  [ -n "${ssh_program}" ] && remote_cmd=("${ssh_program}")
  [ -n "${fetch_from}" ] && remote_cmd+=("${fetch_from}")
  # Unpacked beside the live prefix and swapped in by rename, so a running
  # `repro` never sees a half-written tree and a failed unpack leaves the
  # previous install in place.
  "${remote_cmd[@]}" "set -e
    sudo rm -rf '${install_prefix}.new' '${install_prefix}.old'
    sudo mkdir -p '${install_prefix}.new'
    sudo tar -C '${install_prefix}.new' --strip-components=1 --no-same-owner -xzf -
    if [ -e '${install_prefix}' ]; then sudo mv '${install_prefix}' '${install_prefix}.old'; fi
    sudo mv '${install_prefix}.new' '${install_prefix}'
    sudo rm -rf '${install_prefix}.old'
    sudo mkdir -p '${bin_links}'
    for name in repro reprobuild nim; do
      sudo ln -sfn '${install_prefix}'/bin/\$name '${bin_links}'/\$name
    done
    '${bin_links}'/repro --version" < "${out}/${pkg_name}.tar.gz"
  echo "build_linux_cross: installed at ${install_prefix} on the target"
fi
