#!/usr/bin/env python3
"""Generate the ``reprobuild/dsl/<module>`` re-export modules.

The canonical recipe import surface is the ``reprobuild`` module tree in
``libs/reprobuild/src`` (see that library's README). Its domain and package
modules -- ``import reprobuild/dsl/fs``, ``reprobuild/dsl/packages/nim``,
``reprobuild/dsl/packaging`` and so on -- are one-to-one re-exports of the
modules of ``libs/repro_dsl_stdlib/src/repro_dsl_stdlib``. Each canonical
module holds exactly::

    import repro_dsl_stdlib/<module> as impl
    export impl

so both names denote the SAME symbols: a recipe that mixes old and new imports
sees no ambiguity, and ``nimsuggest`` ``def`` on a symbol imported through
either name lands on the one definition.

There are several hundred such modules and the stdlib gains packages often, so
they are derived from the stdlib tree rather than maintained by hand. Run this
script after adding, moving or deleting a stdlib module; the integration test
``t_ux_m1_reprobuild_module_hierarchy_and_lsp`` fails, naming this script, when
the two trees disagree.

Rules:

* every ``repro_dsl_stdlib/<path>.nim`` gets ``reprobuild/dsl/<path>.nim``;
* a one-release "moved package" stub -- a module whose body is a top-level
  ``{.error: ...}`` naming the package's new home -- gets NO canonical name:
  the package never existed under ``reprobuild/dsl``, so there is nothing to
  keep importable there;
* the hand-written modules ``reprobuild.nim``, ``reprobuild/dsl.nim``,
  ``reprobuild/home.nim`` and ``reprobuild/system.nim`` are not generated and
  are never touched;
* a generated module whose stdlib source disappeared is deleted, so the
  canonical tree never names a module the stdlib no longer has.

Usage::

    python3 scripts/generate_reprobuild_dsl_modules.py          # write
    python3 scripts/generate_reprobuild_dsl_modules.py --check  # exit 1 on drift
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
STDLIB_ROOT = REPO_ROOT / "libs" / "repro_dsl_stdlib" / "src" / "repro_dsl_stdlib"
CANONICAL_DSL_ROOT = REPO_ROOT / "libs" / "reprobuild" / "src" / "reprobuild" / "dsl"

# The first line of every generated module. It is how this script recognises
# a file it owns (and may rewrite or delete) and how a reader learns not to
# edit it.
GENERATED_MARKER = "## GENERATED by scripts/generate_reprobuild_dsl_modules.py"


def is_moved_package_stub(source: Path) -> bool:
    """True for a one-release stub left behind by a package that moved out.

    The stub's whole body is a column-0 ``{.error: ...}`` pragma (see
    ``MovedPackageImportStubs`` in ``repro_project_dsl``). An ``{.error:}``
    nested inside a macro or ``when`` branch is indented and does not count.
    """
    for line in source.read_text(encoding="utf-8").splitlines():
        if line.startswith("{.error:"):
            return True
    return False


def module_path(relative: Path) -> str:
    """``packages/nim.nim`` -> ``packages/nim`` with ``/`` on every host."""
    return relative.with_suffix("").as_posix()


def render(stdlib_module: str) -> str:
    """The exact text of the canonical module for ``stdlib_module``."""
    return (
        f"{GENERATED_MARKER} -- do not edit.\n"
        f"## Canonical name of ``repro_dsl_stdlib/{stdlib_module}``: "
        "``import reprobuild/dsl/"
        f"{stdlib_module}`` and the legacy import denote the same symbols.\n"
        "\n"
        f"import repro_dsl_stdlib/{stdlib_module} as impl\n"
        "export impl\n"
    )


def expected_modules() -> dict[Path, str]:
    """Map each canonical module path to the text it must contain."""
    result: dict[Path, str] = {}
    for source in sorted(STDLIB_ROOT.rglob("*.nim")):
        if is_moved_package_stub(source):
            continue
        relative = source.relative_to(STDLIB_ROOT)
        result[CANONICAL_DSL_ROOT / relative] = render(module_path(relative))
    return result


def existing_generated_modules() -> set[Path]:
    """Every file under the canonical ``dsl/`` tree that this script owns."""
    owned: set[Path] = set()
    if not CANONICAL_DSL_ROOT.is_dir():
        return owned
    for path in CANONICAL_DSL_ROOT.rglob("*.nim"):
        with path.open(encoding="utf-8") as handle:
            if handle.readline().startswith(GENERATED_MARKER):
                owned.add(path)
    return owned


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="report drift and exit 1 instead of rewriting the tree",
    )
    args = parser.parse_args()

    if not STDLIB_ROOT.is_dir():
        print(f"error: stdlib tree not found at {STDLIB_ROOT}", file=sys.stderr)
        return 2

    expected = expected_modules()
    stale = existing_generated_modules() - set(expected)
    drift: list[str] = []

    for path, text in sorted(expected.items()):
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if current is not None and not current.startswith(GENERATED_MARKER):
            # A hand-written file sits where a generated one belongs. Refuse
            # rather than overwrite work this script does not own.
            print(
                f"error: {path.relative_to(REPO_ROOT)} exists and was not "
                "generated by this script; move it before regenerating",
                file=sys.stderr,
            )
            return 2
        drift.append(f"{'update' if current else 'create'} {path.relative_to(REPO_ROOT)}")
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")

    for path in sorted(stale):
        drift.append(f"delete {path.relative_to(REPO_ROOT)}")
        if not args.check:
            path.unlink()

    if args.check:
        for line in drift:
            print(line)
        if drift:
            print(
                f"{len(drift)} canonical reprobuild/dsl module(s) out of date; "
                "run: python3 scripts/generate_reprobuild_dsl_modules.py",
                file=sys.stderr,
            )
            return 1
        print(f"reprobuild/dsl: {len(expected)} modules up to date")
        return 0

    print(f"reprobuild/dsl: {len(expected)} modules, {len(drift)} change(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
