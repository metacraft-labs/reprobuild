#!/usr/bin/env python3
"""Exercise canonical installed wrappers with the real daemon spawn boundary.

The fixture's leaf payload only forwards argv; its wrapper is generated by the
actual package.nix postFixup, not copied or emulated here. A real regression
binary invokes production startAutoRunQuotaIfNeeded and a real daemon on a real
socket. The deliberately older ambient daemon is a positive selector control.
Every process is killed/reaped in finally, and stdout startup waits are bounded.
"""
import argparse
import ctypes
import os
from pathlib import Path
import selectors
import signal
import subprocess
import tempfile
import time


def identity(pid):
    try:
        fields = Path(f"/proc/{pid}/stat").read_text().rsplit(")", 1)[1].split()
        return None if fields[0] in ("Z", "X") else fields[19]
    except (FileNotFoundError, ProcessLookupError):
        return None


def run_case(args, override):
    daemon_pid = None
    daemon_identity = None
    child = None
    with tempfile.TemporaryDirectory(prefix="repro-packaged-runquota-") as scratch:
        env = dict(os.environ)
        env.pop("RUNQUOTAD_BIN", None)
        env.pop("RUNQUOTA_BIN", None)
        env.pop("RUNQUOTA_SOCKET", None)
        env["PATH"] = str(Path(args.ambient_daemon).parent) + os.pathsep + env.get("PATH", "")
        env["REPRO_TEST_AUTO_RUNQUOTA_CHILD_SCRATCH"] = scratch
        expected_daemon = args.pinned_daemon
        expected_client = args.pinned_client
        if override:
            expected_daemon = args.ambient_daemon
            expected_client = args.override_client
            env["RUNQUOTAD_BIN"] = expected_daemon
            env["RUNQUOTA_BIN"] = expected_client
        try:
            child = subprocess.Popen([args.wrapper, args.probe], env=env,
                                     stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
            selector = selectors.DefaultSelector()
            selector.register(child.stdout, selectors.EVENT_READ)
            output = b""
            deadline = time.monotonic() + 60
            try:
                while time.monotonic() < deadline and daemon_pid is None:
                    if not selector.select(max(0, deadline - time.monotonic())):
                        break
                    chunk = os.read(child.stdout.fileno(), 4096)
                    if not chunk:
                        break
                    output += chunk
                    for line in output.splitlines():
                        if line.startswith(b"auto-runquota-daemon-pid="):
                            daemon_pid = int(line.split(b"=", 1)[1])
                            break
            finally:
                selector.close()
            assert daemon_pid is not None, f"no daemon pid before deadline: {output!r}"
            daemon_identity = identity(daemon_pid)
            assert daemon_identity is not None, "daemon exited before selector observation"
            actual_daemon = Path(f"/proc/{daemon_pid}/exe").resolve()
            values = dict(item.split(b"=", 1) for item in
                          Path(f"/proc/{child.pid}/environ").read_bytes().split(b"\0")
                          if b"=" in item)
            print(f"observed {'override' if override else 'default'}: daemon {actual_daemon}; "
                  f"RUNQUOTAD_BIN={values.get(b'RUNQUOTAD_BIN')!r}; "
                  f"RUNQUOTA_BIN={values.get(b'RUNQUOTA_BIN')!r}", flush=True)
            assert values.get(b"RUNQUOTAD_BIN", b"").decode() == expected_daemon, values.get(b"RUNQUOTAD_BIN")
            assert values.get(b"RUNQUOTA_BIN", b"").decode() == expected_client, values.get(b"RUNQUOTA_BIN")
            assert actual_daemon == Path(expected_daemon).resolve(), (actual_daemon, expected_daemon)
            print(f"{'override' if override else 'default'}: real daemon {actual_daemon}; client {expected_client}")
        finally:
            # Even an unfixed daemon is our fixture to reclaim. Identity-check
            # before signalling so a reused PID can never receive the kill.
            owned = {}
            if daemon_pid:
                owned[daemon_pid] = daemon_identity
            if child is not None and daemon_pid is None:
                try:
                    children = Path(f"/proc/{child.pid}/task/{child.pid}/children").read_text()
                    owned.update((int(pid), identity(int(pid))) for pid in children.split())
                except FileNotFoundError:
                    pass
            for pid, start in owned.items():
                if start and identity(pid) == start:
                    try:
                        os.kill(pid, signal.SIGKILL)
                    except ProcessLookupError:
                        pass
            if child is not None:
                if child.poll() is None:
                    child.kill()
                child.wait(timeout=10)
                child.stdout.close()
            # This checker is a subreaper, so killing the invocation adopts
            # its daemon even when the daemon is unfixed. Reap rather than
            # leaving zombies to the host's init or test runner.
            for pid in owned:
                deadline = time.monotonic() + 10
                while True:
                    try:
                        got, _ = os.waitpid(pid, os.WNOHANG)
                    except ChildProcessError:
                        break  # The invocation already reaped it.
                    if got == pid:
                        break
                    if time.monotonic() >= deadline:
                        raise TimeoutError(f"fixture daemon {pid} could not be reaped")
                    time.sleep(0.02)


def main():
    parser = argparse.ArgumentParser()
    for argument in ("wrapper", "probe", "pinned-daemon", "pinned-client",
                     "ambient-daemon", "override-client"):
        parser.add_argument("--" + argument, required=True)
    args = parser.parse_args()
    # Linux fixture: adoption makes cleanup an observable waitpid boundary,
    # not merely a signal sent to a process that might become an orphan.
    libc = ctypes.CDLL(None, use_errno=True)
    if libc.prctl(36, 1, 0, 0, 0) != 0:  # PR_SET_CHILD_SUBREAPER
        raise OSError(ctypes.get_errno(), "cannot become fixture subreaper")
    assert Path(args.pinned_daemon).resolve() != Path(args.ambient_daemon).resolve(), "selector control must differ"
    run_case(args, False)
    run_case(args, True)


if __name__ == "__main__":
    main()
