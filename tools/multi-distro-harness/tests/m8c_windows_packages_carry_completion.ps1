<#
test_cs_m8c_windows_packages_carry_completion, the Windows part: the MSI,
built with WiX v3 on Windows, installs repro's PowerShell completion script at
%ProgramFiles%\Reprobuild\share\repro\completions\repro.ps1 with the custom
actions that register it; and the Scoop manifest's hooks, run the way Scoop
runs them, leave a fresh Windows PowerShell 5.1 and PowerShell 7 session
completing `repro`, registered once, and take it away again. The host-neutral
part (the .wxs, an MSI built with msitools, the manifest's text) is
tests/unit/test_release_native_packages.py.

  powershell -NoProfile -ExecutionPolicy Bypass -File tools\multi-distro-harness\tests\m8c_windows_packages_carry_completion.ps1 -FetchWix

Run it from a reprobuild checkout as an ordinary user, after a build
(bash ./scripts/build_apps.sh in the Windows environment, . .\env.ps1). It
needs no administrator rights and writes only under one scratch directory
(-Work, default a new directory under %TEMP%).

  * The MSI is built by scripts/release/repro-build-packages.sh --ecosystem msi
    (the code path a release would use) from an archive of the release's shape
    (made from -BuildDir as m8c_install_completion_windows.ps1 makes it, or
    -Archive), with WiX v3: -Wix3Bin names the directory holding candle.exe
    and light.exe, or -FetchWix downloads wix314-binaries.zip from the WiX
    project's GitHub release into the scratch directory and checks it against
    the SHA-256 the reprobuild package catalogue pins
    (libs/repro_dsl_stdlib/src/repro_dsl_stdlib/packages/wix3.nim). It is read
    back through the Windows Installer database API, and its files are
    extracted with an administrative installation (msiexec /a, which writes
    only the target directory and registers nothing). It is NOT installed: an
    installation writes Program Files, the machine PATH and the all-users
    PowerShell profiles. A negative control rebuilds the same authoring
    without the completion script's component and checks that the assertion
    rejects it.
  * The MSI's two deferred custom actions are run as the installed package
    runs them, the administrative image's bin\repro.exe with each action's
    own arguments, plus repro's internal --system-root, which re-roots every
    system path (each PowerShell's $PSHOME included) under the scratch
    directory, and with a PATH that reaches only scratch PowerShell
    installations (pwsh.exe beside System.Management.Automation.dll, and
    powershell.exe in a WindowsPowerShell\v1.0 directory; never started).
    The ensure action must register (the script under the re-rooted
    installation prefix and one block in each re-rooted $PSHOME\Profile.ps1,
    still one after a second run, as on a repair), and the remove action
    must take the blocks away again. The check refuses to run when that
    PATH reaches a real PowerShell.
  * The Scoop manifest is generated by scripts/release/repro-publish-repos.sh
    --ecosystem scoop for that archive. Scoop itself is not run: installing
    Scoop writes the user's environment (the user PATH and SCOOP variables in
    HKCU), which this check must not touch. Its hooks are run as Scoop runs
    them (the hook's lines joined into one script block and invoked with
    $dir naming the app's directory), in a PowerShell whose USERPROFILE is
    the scratch home, with the archive extracted as the app's directory.

Exit status: 0 when every check passed and nothing was NOT RUN, 1 on a failed
check (or a refusal), 3 when all checks passed but a leg was NOT RUN.
#>
[CmdletBinding()]
param(
  [string]$Work = '',
  [string]$BuildDir = '',
  [string]$Archive = '',
  [string]$Wix3Bin = '',
  [switch]$FetchWix
)

$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'm8c_common.ps1')

$RepoRoot = (Resolve-Path -LiteralPath (Join-Path $PSScriptRoot '../../..')).Path
# The version of this checkout's build, the name of the archive made from
# it; a real release archive names its own version.
$Version = Get-ReproVersion -RepoRoot $RepoRoot
$Arch = 'x86_64'
if ($Archive) {
  $m = [regex]::Match((Split-Path -Leaf $Archive), '^reprobuild-(.+)-windows-(x86_64|aarch64)\.zip$')
  if (-not $m.Success) { throw "-Archive must be a reprobuild-<version>-windows-<arch>.zip, not $Archive" }
  $Version = $m.Groups[1].Value
  $Arch = $m.Groups[2].Value
}
$Top = "reprobuild-$Version-windows-$Arch"
$CompletionPath = 'ProgramFiles64Folder/Reprobuild/share/repro/completions/repro.ps1'
$ReproPath = 'ProgramFiles64Folder/Reprobuild/bin/repro.exe'
$CustomActions = @{
  'ReproCompletionEnsure' = 'hooks ensure --shell-autocomplete --system'
  'ReproCompletionRemove' = 'hooks uninstall --shell-autocomplete --system'
}
# WiX v3.14.1, as the package catalogue pins it.
$WixUrl = 'https://github.com/wixtoolset/wix3/releases/download/wix3141rtm/wix314-binaries.zip'
$WixSha256 = '6ac824e1642d6f7277d0ed7ea09411a508f6116ba6fae0aa5f2c7daa2ff43d31'

if (-not $script:M8cOnWindows) { Write-Host 'm8c_windows_packages_carry_completion: this runs on Windows only'; exit 1 }
if (-not $Work) { $Work = Join-Path ([IO.Path]::GetTempPath()) ('m8c-packages-' + [guid]::NewGuid().ToString('N').Substring(0, 8)) }
New-Item -ItemType Directory -Force -Path $Work | Out-Null
$Work = (Resolve-Path -LiteralPath $Work).Path
Set-Location -LiteralPath $RepoRoot
$H = Join-Path $Work 'home'
$Tmp = Join-Path $Work 'tmp'
$Neutral = Join-Path $Work 'cwd'
New-Item -ItemType Directory -Force -Path $Tmp, $Neutral | Out-Null

# The rows of one table of an MSI database, each a string array.
function Get-MsiRows {
  param([string]$Msi, [string]$Table)
  $installer = New-Object -ComObject WindowsInstaller.Installer
  $db = $installer.GetType().InvokeMember('OpenDatabase', 'InvokeMethod', $null, $installer, @($Msi, 0))
  $view = $db.GetType().InvokeMember('OpenView', 'InvokeMethod', $null, $db, @("SELECT * FROM ``$Table``"))
  $view.GetType().InvokeMember('Execute', 'InvokeMethod', $null, $view, $null) | Out-Null
  $cols = $view.GetType().InvokeMember('ColumnInfo', 'GetProperty', $null, $view, @(0))
  $n = $cols.GetType().InvokeMember('FieldCount', 'GetProperty', $null, $cols, $null)
  $rows = @()
  while ($true) {
    $rec = $view.GetType().InvokeMember('Fetch', 'InvokeMethod', $null, $view, $null)
    if ($null -eq $rec) { break }
    $row = @(foreach ($k in 1..$n) { $rec.GetType().InvokeMember('StringData', 'GetProperty', $null, $rec, @($k)) })
    $rows += , $row
  }
  $view.GetType().InvokeMember('Close', 'InvokeMethod', $null, $view, $null) | Out-Null
  return , $rows
}

# {install path: extracted file} for every file of the package, its custom
# actions and its sequence, from the database and an administrative image.
function Get-MsiContents {
  param([string]$Msi, [string]$Tag)
  $parent = @{}; $name = @{}
  foreach ($r in (Get-MsiRows $Msi 'Directory')) { $parent[$r[0]] = $r[1]; $name[$r[0]] = $r[2] }
  function LongName([string]$s) { $s = $s.Split(':')[0]; return $s.Split('|')[-1] }
  function DirPath([string]$d) {
    if ($d -eq 'TARGETDIR' -or $d -eq 'ProgramFiles64Folder' -or -not $parent.ContainsKey($d)) { return $d }
    return (DirPath $parent[$d]) + '/' + (LongName $name[$d])
  }
  $cdir = @{}
  foreach ($r in (Get-MsiRows $Msi 'Component')) { $cdir[$r[0]] = $r[2] }
  $image = Join-Path $Work "admin-$Tag"
  $log = Join-Path $Work "admin-$Tag.log"
  $p = Start-Process -FilePath (Join-Path $env:SystemRoot 'System32\msiexec.exe') -Wait -PassThru `
    -ArgumentList @('/a', "`"$Msi`"", '/qn', "TARGETDIR=`"$image`"", '/l*v', "`"$log`"")
  if ($p.ExitCode -ne 0) { throw "msiexec /a exited $($p.ExitCode); log: $log" }
  $files = @{}
  foreach ($r in (Get-MsiRows $Msi 'File')) {
    $path = (DirPath $cdir[$r[1]]) + '/' + (LongName $r[2])
    # The administrative image keeps the directory tree under TARGETDIR,
    # the standard folder by its name (ProgramFiles64Folder becomes
    # "Program Files 64" or similar); find the file by its path below it.
    $files[$path] = $path
  }
  $actions = @{}
  foreach ($r in (Get-MsiRows $Msi 'CustomAction')) { $actions[$r[0]] = @([int]$r[1], $r[2], $r[3]) }
  $sequence = @{}
  foreach ($r in (Get-MsiRows $Msi 'InstallExecuteSequence')) { $sequence[$r[0]] = $r[1] }
  $script = Get-ChildItem -LiteralPath $image -Recurse -File -Filter 'repro.ps1' |
    Where-Object { $_.FullName -match '[\\/]Reprobuild[\\/]share[\\/]repro[\\/]completions[\\/]repro\.ps1$' } | Select-Object -First 1
  return [pscustomobject]@{ Files = $files; Actions = $actions; Sequence = $sequence; Script = $script }
}

# Throws when the package does not carry the completion as specified.
function Assert-MsiCompletion {
  param($Contents, [byte[]]$ArchiveScript)
  if (-not $Contents.Files.ContainsKey($CompletionPath)) { throw "the package installs no $CompletionPath" }
  if (-not $Contents.Files.ContainsKey($ReproPath)) { throw "the package installs no $ReproPath" }
  if ($null -eq $Contents.Script) { throw 'the administrative image holds no Reprobuild\share\repro\completions\repro.ps1' }
  $bytes = [IO.File]::ReadAllBytes($Contents.Script.FullName)
  if ([Convert]::ToBase64String($bytes) -ne [Convert]::ToBase64String($ArchiveScript)) { throw 'the installed repro.ps1 differs from the archive''s' }
  foreach ($a in $CustomActions.Keys) {
    if (-not $Contents.Actions.ContainsKey($a)) { throw "no custom action $a" }
    $row = $Contents.Actions[$a]
    if ($row[0] -ne 3154 -or $row[1] -ne 'fil_repro_exe' -or $row[2] -ne $CustomActions[$a]) { throw "custom action $a is $($row -join ' | ')" }
    if (-not $Contents.Sequence.ContainsKey($a)) { throw "custom action $a is not sequenced" }
  }
}

# Runs the MSI's deferred custom actions as the installed package runs them
# (the administrative image's repro.exe, each action's own arguments), under
# --system-root and against scratch PowerShell installations, so that they
# write under the scratch directory only. Records PASS/FAIL lines.
function Test-MsiActionsRegister {
  param([string]$Image)
  $exe = Get-ChildItem -LiteralPath $Image -Recurse -File -Filter 'repro.exe' |
    Where-Object { $_.FullName -match '[\\/]Reprobuild[\\/]bin[\\/]repro\.exe$' } | Select-Object -First 1
  if ($null -eq $exe) { throw 'the administrative image holds no Reprobuild\bin\repro.exe' }
  $fps = Join-Path $Work 'msi-fps'
  $pwshHome = [IO.Path]::Combine($fps, 'PowerShell', '7')
  $winHome = [IO.Path]::Combine($fps, 'WindowsPowerShell', 'v1.0')
  New-Item -ItemType Directory -Force -Path $pwshHome, $winHome | Out-Null
  foreach ($f in @((Join-Path $pwshHome 'pwsh.exe'), (Join-Path $pwshHome 'System.Management.Automation.dll'),
      (Join-Path $winHome 'powershell.exe'))) { [IO.File]::WriteAllBytes($f, [byte[]]@()) }
  $root = Join-Path $Work 'msi-root'
  New-Item -ItemType Directory -Force -Path $root | Out-Null
  # A path re-rooted as --system-root re-roots it: its drive dropped.
  function Get-UnderRoot([string]$Path) { return Join-Path $root $Path.Substring([IO.Path]::GetPathRoot($Path).Length) }
  $profiles = @((Join-Path (Get-UnderRoot $pwshHome) 'Profile.ps1'), (Join-Path (Get-UnderRoot $winHome) 'Profile.ps1'))
  $prefix = Split-Path -Parent (Split-Path -Parent $exe.FullName)
  $script = [IO.Path]::Combine((Get-UnderRoot $prefix), 'share', 'repro', 'completions', 'repro.ps1')
  $actionEnv = New-IsolatedEnvironment -HomeDir (Join-Path $Work 'msi-home') -TempDir $Tmp -PathDirs @($exe.DirectoryName, $pwshHome, $winHome)
  foreach ($d in ($actionEnv['PATH'] -split ';')) {
    foreach ($n in @('pwsh.exe', 'powershell.exe')) {
      $c = Join-Path $d $n
      if ((Test-Path -LiteralPath $c) -and -not $c.StartsWith($Work, [StringComparison]::OrdinalIgnoreCase)) {
        throw "refused: the actions' PATH reaches the real PowerShell $c"
      }
    }
  }
  $ensure = @($CustomActions['ReproCompletionEnsure'] -split ' ') + "--system-root=$root"
  $remove = @($CustomActions['ReproCompletionRemove'] -split ' ') + "--system-root=$root"
  foreach ($run in 1, 2) {
    $r = Invoke-Isolated -FilePath $exe.FullName -Arguments $ensure -Environment $actionEnv -WorkingDirectory $Neutral -TimeoutSeconds 300
    Write-Host $r.Output
    Assert-Equal $r.Code 0 "MSI ensure action, run ${run}: exited 0"
    Assert-True (Test-Path -LiteralPath $script) "MSI ensure action, run ${run}: the script under the re-rooted prefix"
    foreach ($p in $profiles) { Assert-Equal (Get-CompletionBlockCount $p) 1 "MSI ensure action, run ${run}: blocks in $p" }
  }
  foreach ($h in @($pwshHome, $winHome)) {
    Assert-True (-not (Test-Path -LiteralPath (Join-Path $h 'Profile.ps1'))) "MSI ensure action: nothing written in the scratch PowerShell itself ($h)"
  }
  $r = Invoke-Isolated -FilePath $exe.FullName -Arguments $remove -Environment $actionEnv -WorkingDirectory $Neutral -TimeoutSeconds 300
  Write-Host $r.Output
  Assert-Equal $r.Code 0 'MSI remove action: exited 0'
  foreach ($p in $profiles) { Assert-Equal (Get-CompletionBlockCount $p) 0 "MSI remove action: blocks in $p" }
}

$exit = 1
try {
  Write-Step 'preconditions'
  $bash = Get-ScriptBash -RepoRoot $RepoRoot
  if (-not $bash) { throw 'no Git for Windows bash for the repository scripts' }
  $powershells = Get-TestPowerShells
  foreach ($ps in $powershells) { Write-Host "$($ps[0]): $($ps[1])" }
  if (-not ($powershells | Where-Object { $_[0] -eq 'PowerShell 7' })) { NotRun 'PowerShell 7 (pwsh is not on PATH)' }
  $realBefore = Get-RealProfileState
  foreach ($l in $realBefore) { Write-Host "real-profile: before $l" }

  if ($Archive) {
    $zip = $Archive
  } else {
    if (-not $BuildDir) { $BuildDir = Join-Path $RepoRoot 'build' }
    $zip = New-TestArchive -RepoRoot $RepoRoot -BuildDir $BuildDir -Version $Version -Arch $Arch -OutDir $Work -Bash $bash
  }
  Add-Type -AssemblyName System.IO.Compression.FileSystem
  $appDir = Join-Path $Work 'scoop-app'
  [System.IO.Compression.ZipFile]::ExtractToDirectory($zip, $appDir)
  $archiveScript = [IO.File]::ReadAllBytes([IO.Path]::Combine($appDir, $Top, 'share', 'repro', 'completions', 'repro.ps1'))
  Pass "archive $zip"

  # ===================================================================
  Write-Step 'MSI: built with WiX v3, read back'
  # ===================================================================
  if (-not $Wix3Bin -and $FetchWix) {
    $wixZip = Join-Path $Work 'wix314-binaries.zip'
    Invoke-WebRequest -Uri $WixUrl -OutFile $wixZip -UseBasicParsing
    $got = (Get-FileHash -Algorithm SHA256 -LiteralPath $wixZip).Hash.ToLowerInvariant()
    if ($got -ne $WixSha256) { throw "wix314-binaries.zip has SHA-256 $got, not the pinned $WixSha256" }
    $Wix3Bin = Join-Path $Work 'wix3'
    [System.IO.Compression.ZipFile]::ExtractToDirectory($wixZip, $Wix3Bin)
    Pass "WiX v3.14.1 fetched and checked against the pinned SHA-256"
  }
  if (-not $Wix3Bin -or -not (Test-Path -LiteralPath (Join-Path $Wix3Bin 'candle.exe'))) {
    NotRun 'MSI: no WiX v3 (pass -Wix3Bin <dir with candle.exe and light.exe>, or -FetchWix)'
  } else {
    $out = Join-Path $Work 'msi-out'
    $env:REPRO_MSI_TOOLSET = 'wix3'
    $env:REPRO_WIX3_BIN = ConvertTo-ScriptPath $Wix3Bin
    try {
      $code = (Invoke-NativeCommand -FilePath $bash -ArgumentList @('./scripts/release/repro-build-packages.sh', '--version', $Version,
          '--tarball', (ConvertTo-ScriptPath $zip), '--out', (ConvertTo-ScriptPath $out), '--ecosystem', 'msi',
          '--platform', 'windows', '--asset-arch', $Arch)).Code
    } finally {
      Remove-Item Env:\REPRO_MSI_TOOLSET, Env:\REPRO_WIX3_BIN -ErrorAction SilentlyContinue
    }
    Assert-Equal $code 0 'MSI: repro-build-packages.sh --ecosystem msi (WiX v3) exited 0'
    $msi = Join-Path $out "$Top.msi"
    if (Test-Path -LiteralPath $msi) {
      try {
        Assert-MsiCompletion (Get-MsiContents -Msi $msi -Tag 'good') $archiveScript
        Pass "MSI: installs $CompletionPath byte-identical to the archive's, repro.exe, and both custom actions (type 3154, sequenced)"
      } catch { Fail "MSI: $($_.Exception.Message)" }
      try { Test-MsiActionsRegister -Image (Join-Path $Work 'admin-good') } catch { Fail "MSI actions: $($_.Exception.Message)" }
      # Negative control: the authoring without the completion script's
      # component, built with the same WiX, is rejected.
      $wxs = Get-Content -Raw -LiteralPath (Join-Path $out "$Top.wxs")
      $mutant = [regex]::Replace($wxs, '\s*<Component Id="cmp_completion_ps1".*?</Component>', '', 'Singleline')
      $mutant = $mutant.Replace('      <ComponentRef Id="cmp_completion_ps1" />' + "`n", '')
      if ($mutant -match 'fil_completion_ps1') {
        Fail 'MSI control: could not remove the completion component from the authoring'
      } else {
        $mw = Join-Path $Work 'mutant.wxs'
        [IO.File]::WriteAllText($mw, $mutant)
        $src = Join-Path $Work 'msi-src'
        [System.IO.Compression.ZipFile]::ExtractToDirectory($zip, $src)
        $candle = Invoke-NativeCommand -FilePath (Join-Path $Wix3Bin 'candle.exe') -ArgumentList @('-nologo', '-arch', 'x64', "-dSourceDir=$src", '-out', (Join-Path $Work 'mutant.wixobj'), $mw)
        $light = if ($candle.Code -eq 0) { Invoke-NativeCommand -FilePath (Join-Path $Wix3Bin 'light.exe') -ArgumentList @('-nologo', '-sval', '-out', (Join-Path $Work 'mutant.msi'), (Join-Path $Work 'mutant.wixobj')) } else { $null }
        if ($candle.Code -ne 0 -or $light.Code -ne 0) {
          # A control package that was never built would be "rejected" for
          # the wrong reason.
          Fail "MSI control: the package without the completion entry did not build (candle exit $($candle.Code), light exit $(if ($light) { $light.Code } else { 'not run' }))"
        } else {
          $rejected = $false
          try { Assert-MsiCompletion (Get-MsiContents -Msi (Join-Path $Work 'mutant.msi') -Tag 'mutant') $archiveScript } catch { $rejected = $true; Write-Host "control rejected: $($_.Exception.Message)" }
          Assert-True $rejected 'MSI control: the package without the completion entry fails the assertion'
        }
      }
    } else {
      Fail "MSI: no $msi"
    }
  }

  # ===================================================================
  Write-Step 'Scoop: the manifest''s hooks, run as Scoop runs them'
  # ===================================================================
  $pk = Join-Path $Work 'scoop-assets'
  New-Item -ItemType Directory -Force -Path $pk | Out-Null
  Copy-Item -LiteralPath $zip -Destination (Join-Path $pk "$Top.zip")
  $r = Invoke-NativeCommand -FilePath $bash -ArgumentList @('./scripts/release/repro-publish-repos.sh', '--version', $Version,
      '--packages', (ConvertTo-ScriptPath $pk), '--ecosystem', 'scoop', '--repo-root', (ConvertTo-ScriptPath (Join-Path $Work 'bucket')),
      '--target', 'none', '--scoop-downloads-base', 'https://downloads.example')
  Assert-Equal $r.Code 0 'Scoop: repro-publish-repos.sh --ecosystem scoop exited 0'
  $manifestPath = [IO.Path]::Combine($Work, 'bucket', 'scoop', 'bucket', 'reprobuild.json')
  $manifest = Get-Content -Raw -LiteralPath $manifestPath | ConvertFrom-Json
  Assert-Equal $manifest.extract_dir $Top 'Scoop: extract_dir is the archive''s top directory'
  $dir = Join-Path $appDir $Top
  Assert-True (Test-Path -LiteralPath ([IO.Path]::Combine($dir, 'share', 'repro', 'completions', 'repro.ps1'))) 'Scoop: the app directory holds share\repro\completions\repro.ps1'

  $isoPath = @((Join-Path $dir 'bin'), (Join-Path $env:SystemRoot 'System32'), $env:SystemRoot, (Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0'))
  $pw = $powershells | Where-Object { $_[0] -eq 'PowerShell 7' } | Select-Object -First 1
  if ($pw) { $isoPath += (Split-Path -Parent $pw[1]) }
  $isoEnv = New-IsolatedEnvironment -HomeDir $H -TempDir $Tmp -PathDirs $isoPath
  New-Item -ItemType Directory -Force -Path $H, ([IO.Path]::Combine($H, 'AppData', 'Local')), ([IO.Path]::Combine($H, 'AppData', 'Roaming')), ([IO.Path]::Combine($H, 'Documents')) | Out-Null
  if (-not (Assert-DocumentsInScratch -PowerShells $powershells -Environment $isoEnv -Scratch $Work -WorkingDirectory $Neutral)) {
    throw 'refused: Documents resolves outside the scratch directory (see above)'
  }
  $docs = Get-IsolatedDocuments -PowerShell $powershells[0][1] -Environment $isoEnv -WorkingDirectory $Neutral
  $loc = Get-UserCompletionPaths -HomeDir $H -Documents $docs
  function Get-RegistrationCount {
    $n = 0
    if (Test-Path -LiteralPath $loc.Script) { $n++ }
    foreach ($p in $loc.Profiles) { $n += (Get-CompletionBlockCount $p) }
    return $n
  }
  # Scoop runs a hook in the PowerShell that runs Scoop, with $dir (and
  # $global, $manifest, ...) in scope:
  # Invoke-Command ([scriptblock]::Create($hook -join "`r`n")).
  function Invoke-ScoopHook {
    param([string]$Hook, [hashtable]$Environment = $isoEnv)
    $runner = "`$dir = '$($dir.Replace("'", "''"))'; `$global = `$false; " +
      "`$manifest = Get-Content -Raw -LiteralPath '$($manifestPath.Replace("'", "''"))' | ConvertFrom-Json; " +
      "Invoke-Command ([scriptblock]::Create((@(`$manifest.$Hook) -join `"``r``n`"))); exit `$LASTEXITCODE"
    $r = Invoke-Isolated -FilePath $powershells[0][1] -Arguments @('-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass',
        '-EncodedCommand', (Get-EncodedCommand $runner)) -Environment $Environment -WorkingDirectory $Neutral -TimeoutSeconds 300
    Write-Host $r.Output
    return $r
  }
  $registered = 1 + $loc.Profiles.Count
  Assert-Equal (Get-RegistrationCount) 0 'Scoop: no completion before post_install'
  $null = Invoke-ScoopHook 'post_install'
  Assert-Equal (Get-RegistrationCount) $registered 'Scoop: post_install wrote the script and one block per profile'
  Assert-Completes -PowerShells $powershells -Environment $isoEnv -WorkingDirectory $Neutral -Want $true -Tag 'Scoop post_install'
  $null = Invoke-ScoopHook 'post_install'
  Assert-Equal (Get-RegistrationCount) $registered 'Scoop: a second post_install (an update) registers nothing twice'
  $null = Invoke-ScoopHook 'pre_uninstall'
  Assert-Equal (Get-RegistrationCount) 0 'Scoop: pre_uninstall removed the script and every block'
  Assert-Completes -PowerShells $powershells -Environment $isoEnv -WorkingDirectory $Neutral -Want $false -Tag 'Scoop after pre_uninstall'
  $optOut = $isoEnv.Clone()
  $optOut['REPRO_NO_COMPLETION'] = '1'
  $null = Invoke-ScoopHook -Hook 'post_install' -Environment $optOut
  Assert-Equal (Get-RegistrationCount) 0 'Scoop: post_install with REPRO_NO_COMPLETION=1 registers nothing'

  Write-Step 'the invoking user''s real profiles are unchanged'
  $realAfter = Get-RealProfileState
  foreach ($l in $realAfter) { Write-Host "real-profile: after $l" }
  Assert-True ((Compare-Object $realBefore $realAfter | Measure-Object).Count -eq 0) 'the real profiles and per-user completion script are byte-identical before and after'

  $exit = Complete-Run -Name 'm8c_windows_packages_carry_completion' -Work $Work
} catch {
  Write-Host "HARNESS DIED: $($_.Exception.Message)"
  Write-Host $_.ScriptStackTrace
  $exit = 1
}
exit $exit
