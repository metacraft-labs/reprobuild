<#
e2e_cs_m8c_install_script_sets_up_completion: on Windows, the install
script's archive method leaves a fresh Windows PowerShell 5.1 session and a
fresh PowerShell 7 session completing `repro`, registered exactly once, and
-Uninstall takes it away again. The Windows counterpart of
m8b_install_completion_macos.sh.

  powershell -NoProfile -ExecutionPolicy Bypass -File tools\multi-distro-harness\tests\m8c_install_completion_windows.ps1

Run it from a reprobuild checkout as an ordinary user, after a build
(bash ./scripts/build_apps.sh in the Windows environment, . .\env.ps1). It
never needs administrator rights and writes only under one scratch directory
(-Work, default a new directory under %TEMP%): the installer runs with a
prefix of its own and a scratch home (USERPROFILE, LOCALAPPDATA, APPDATA), so
the profiles it writes are under the scratch home's Documents folder. It
refuses to run when Documents would resolve outside the scratch directory
(m8c_common.ps1 explains why), and it compares the invoking user's real
profiles before and after. Under pwsh on Linux the same legs run for
PowerShell 7 (profiles under the scratch XDG_CONFIG_HOME); Windows
PowerShell 5.1 exists only on Windows.

What it needs:
  * a build tree (-BuildDir, default <checkout>\build) with repro.exe and
    reprobuild.exe: registering completion runs the installed `repro hooks
    ensure`, and completing runs the installed `repro __complete`, so a
    stand-in will not do. The script makes an archive of the release's shape
    from it (bin\, lib\, share\repro\completions\repro.ps1 generated by
    scripts/release/stage_release_completions.sh), or -Archive names a real
    reprobuild-<version>-windows-x86_64.zip.
  * Git for Windows' bash, with its gpg and sh: a throwaway key signs the
    archive (scripts/release-signing/make-test-key.sh and
    repro-sign-release.sh), and the installer verifies it with
    repro-verify-release.sh before extracting, as it does for a user. A local
    HTTP server (System.Net.HttpListener on localhost) stands in for the
    release host (REPRO_BASE_URL).
  * Windows PowerShell 5.1 and PowerShell 7 (pwsh on PATH). A missing one is
    reported NOT RUN.

Legs:
  1  The archive install: the archive's share\ is installed, the user's
     completion script and one block in each PowerShell's CurrentUserAllHosts
     profile exist, a fresh session of each completes `repro wor<Tab>` to
     `workspace`; a re-run leaves one script and one block per profile and
     still completes; -Uninstall removes script, blocks, record and tree, and
     the sessions no longer complete.
  2  -NoCompletion and REPRO_NO_COMPLETION=1: repro installed, no completion
     script or block anywhere, and the sessions do NOT complete. This is the
     control that shows the probe is not vacuous.
  3  A re-run with -NoCompletion after a completion install removes the
     registration (the opt-out always leaves none).

Exit status: 0 when every check passed and nothing was NOT RUN, 1 on a failed
check (or a refusal), 3 when all checks passed but a leg was NOT RUN.
#>
[CmdletBinding()]
param(
  [string]$Work = '',
  [string]$BuildDir = '',
  [string]$Archive = '',
  [int]$Port = 8743
)

$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'm8c_common.ps1')

$RepoRoot = (Resolve-Path -LiteralPath (Join-Path $PSScriptRoot '../../..')).Path
$InstallPs1 = [IO.Path]::Combine($RepoRoot, 'scripts', 'install', 'repro-install.ps1')
$SignDir = [IO.Path]::Combine($RepoRoot, 'scripts', 'release-signing')
$Version = '0.2.29'
$Arch = 'x86_64'
# A real release archive names its own version.
if ($Archive) {
  $m = [regex]::Match((Split-Path -Leaf $Archive), '^reprobuild-(.+)-windows-(x86_64|aarch64)\.zip$')
  if (-not $m.Success) { throw "-Archive must be a reprobuild-<version>-windows-<arch>.zip, not $Archive" }
  $Version = $m.Groups[1].Value
  $Arch = $m.Groups[2].Value
}
$Top = "reprobuild-$Version-windows-$Arch"
$Asset = "$Top.zip"
$KeyringFile = 'metacraft-labs-archive-keyring.asc'

if (-not $Work) { $Work = Join-Path ([IO.Path]::GetTempPath()) ('m8c-install-completion-' + [guid]::NewGuid().ToString('N').Substring(0, 8)) }
New-Item -ItemType Directory -Force -Path $Work | Out-Null
$Work = (Resolve-Path -LiteralPath $Work).Path
$H = Join-Path $Work 'home'
$Prefix = Join-Path $Work 'prefix'
$Tmp = Join-Path $Work 'tmp'
$Www = Join-Path $Work 'www'
$Neutral = Join-Path $Work 'cwd'
New-Item -ItemType Directory -Force -Path $Tmp, $Neutral | Out-Null

$server = $null
$bash = ''
$exit = 1
try {
  Write-Step 'preconditions'
  $bash = Get-ScriptBash -RepoRoot $RepoRoot
  if (-not $bash) { throw 'no bash for the repository scripts (Git for Windows bash on Windows)' }
  $shDir = Split-Path -Parent $bash
  $powershells = Get-TestPowerShells
  foreach ($ps in $powershells) { Write-Host "$($ps[0]): $($ps[1])" }
  if ($script:M8cOnWindows) {
    if (-not ($powershells | Where-Object { $_[0] -eq 'Windows PowerShell 5.1' })) { NotRun 'Windows PowerShell 5.1 (not found)' }
    if (-not ($powershells | Where-Object { $_[0] -eq 'PowerShell 7' })) { NotRun 'PowerShell 7 (pwsh is not on PATH)' }
    Write-Host 'Execution policies of this machine (the probes pass -ExecutionPolicy Bypass for their own process):'
    Get-ExecutionPolicy -List | Format-Table -AutoSize | Out-String | Write-Host
  }
  if ($powershells.Count -eq 0) { throw 'no PowerShell to test' }
  # The PowerShell the installer runs under: Windows PowerShell 5.1 on
  # Windows (what `irm | iex` gets on a stock machine), pwsh elsewhere.
  $installerPs = $powershells[0][1]

  $realBefore = Get-RealProfileState
  foreach ($l in $realBefore) { Write-Host "real-profile: before $l" }

  # The PATH of every isolated process: the scratch prefix's bin, the system
  # directories, and the directory of bash (sh, gpg, and on Linux the rest of
  # the userland).
  $sys = @()
  if ($script:M8cOnWindows) {
    $sys = @((Join-Path $env:SystemRoot 'System32'), $env:SystemRoot, (Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0'))
    $pw = $powershells | Where-Object { $_[0] -eq 'PowerShell 7' } | Select-Object -First 1
    if ($pw) { $sys += (Split-Path -Parent $pw[1]) }
  } else {
    # This host's PATH without any directory that holds a `repro`, so the
    # only repro a probe can reach is the one under test.
    $sys = @($env:PATH -split ':' | Where-Object { $_ -and -not (Test-Path -LiteralPath (Join-Path $_ 'repro')) })
  }
  # On Linux, `repro` on PATH for the completion script: a link to the
  # installed bin/repro.exe (the client finds its engine beside the link's
  # target).
  $shim = Join-Path $Work 'shim'
  if (-not $script:M8cOnWindows) {
    New-Item -ItemType Directory -Force -Path $shim | Out-Null
    & ln -sf (Join-Path $Prefix 'bin/repro.exe') (Join-Path $shim 'repro')
  }
  $isoPath = @((Join-Path $Prefix 'bin'), $shim) + $sys + @($shDir)
  $isoEnv = New-IsolatedEnvironment -HomeDir $H -TempDir $Tmp -PathDirs $isoPath

  Write-Step 'the release archive, signed with a throwaway key, served over local HTTP'
  $dl = [IO.Path]::Combine($Www, 'downloads', "v$Version")
  New-Item -ItemType Directory -Force -Path $dl, (Join-Path $Www 'keys') | Out-Null
  if ($Archive) {
    if ((Split-Path -Leaf $Archive) -ne $Asset) { throw "the archive must be named $Asset, the name the installer asks for" }
    Copy-Item -LiteralPath $Archive -Destination (Join-Path $dl $Asset)
  } else {
    if (-not $BuildDir) { $BuildDir = Join-Path $RepoRoot 'build' }
    $zip = New-TestArchive -RepoRoot $RepoRoot -BuildDir $BuildDir -Version $Version -Arch $Arch -OutDir $Work -Bash $bash
    Copy-Item -LiteralPath $zip -Destination (Join-Path $dl $Asset)
  }
  $gnupg = Join-Path $Work 'gnupg'
  $fpr = (& $bash (ConvertTo-ScriptPath (Join-Path $SignDir 'make-test-key.sh')) --home (ConvertTo-ScriptPath $gnupg) | Select-Object -Last 1)
  if (-not $fpr) { throw 'make-test-key.sh printed no fingerprint' }
  $env:GNUPGHOME = ConvertTo-ScriptPath $gnupg
  $env:REPRO_SIGNING_ALLOW_TEST_KEY = '1'
  try {
    & $bash (ConvertTo-ScriptPath (Join-Path $SignDir 'repro-sign-release.sh')) --dir (ConvertTo-ScriptPath $dl) --key $fpr | Out-Host
    if ($LASTEXITCODE -ne 0) { throw "repro-sign-release.sh failed (exit $LASTEXITCODE)" }
    & $bash -c "gpg --homedir '$(ConvertTo-ScriptPath $gnupg)' --armor --export '$fpr' > '$(ConvertTo-ScriptPath (Join-Path (Join-Path $Www 'keys') $KeyringFile))'"
    if ($LASTEXITCODE -ne 0) { throw 'gpg --export failed' }
  } finally {
    Remove-Item Env:\GNUPGHOME, Env:\REPRO_SIGNING_ALLOW_TEST_KEY -ErrorAction SilentlyContinue
  }
  $anchorSha = (Get-FileHash -Algorithm SHA256 -LiteralPath (Join-Path (Join-Path $Www 'keys') $KeyringFile)).Hash.ToLowerInvariant()
  Pass "archive $Asset and its signatures are under $dl"
  $base = "http://localhost:$Port"
  if (Wait-Url -Url "$base/" -Seconds 1) { throw "$base answers before this run started its server" }
  $server = Start-FileServer -Root $Www -Port $Port -Work $Work
  if (-not (Wait-Url -Url "$base/downloads/v$Version/SHA256SUMS")) { throw "the HTTP server did not come up: $(Get-Content -Raw -LiteralPath (Join-Path $Work 'serve.err') -ErrorAction SilentlyContinue)" }
  Pass "HTTP server pid $($server.Id) serves $base"

  $installEnv = $isoEnv.Clone()
  $installEnv['REPRO_BASE_URL'] = $base
  $installEnv['REPRO_KEYRING_SHA256'] = $anchorSha
  $installEnv['REPRO_KEYRING_FILE'] = $KeyringFile
  $installEnv['REPRO_ALLOW_TEST_KEY'] = '1'
  $installEnv['REPRO_VERIFY_SCRIPT'] = Join-Path $SignDir 'repro-verify-release.sh'

  function Invoke-Installer {
    param([string[]]$Extra, [hashtable]$Environment = $installEnv)
    $a = @('-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-File', $InstallPs1) + $Extra
    $r = Invoke-Isolated -FilePath $installerPs -Arguments $a -Environment $Environment -WorkingDirectory $Neutral -TimeoutSeconds 900
    Write-Host (($r.Output -split "`r?`n" | Select-Object -First 60) -join "`n")
    return $r
  }
  function Reset-Home {
    foreach ($d in @($H, $Prefix)) { if (Test-Path -LiteralPath $d) { Remove-Item -LiteralPath $d -Recurse -Force } }
    New-Item -ItemType Directory -Force -Path $H, ([IO.Path]::Combine($H, 'AppData', 'Local')), ([IO.Path]::Combine($H, 'AppData', 'Roaming')), ([IO.Path]::Combine($H, 'Documents')) | Out-Null
  }

  Reset-Home
  if (-not (Assert-DocumentsInScratch -PowerShells $powershells -Environment $isoEnv -Scratch $Work -WorkingDirectory $Neutral)) {
    throw 'refused: Documents resolves outside the scratch directory (see above); nothing was installed'
  }
  $docs = if ($script:M8cOnWindows) { Get-IsolatedDocuments -PowerShell $powershells[0][1] -Environment $isoEnv -WorkingDirectory $Neutral } else { '' }
  $loc = Get-UserCompletionPaths -HomeDir $H -Documents $docs
  $record = [IO.Path]::Combine($Prefix, '.reprobuild', 'completion')
  function Get-RegistrationCount {
    $n = 0
    if (Test-Path -LiteralPath $loc.Script) { $n++ }
    foreach ($p in $loc.Profiles) { $n += (Get-CompletionBlockCount $p) }
    return $n
  }
  # One script, one block per profile.
  $registered = 1 + $loc.Profiles.Count

  # ===================================================================
  Write-Step 'leg 1: the archive install registers completion for this user'
  # ===================================================================
  Assert-Equal (Get-RegistrationCount) 0 'leg 1: no repro completion before the install'
  $r = Invoke-Installer @('-Method', 'tarball', '-Version', $Version, '-Prefix', $Prefix)
  Assert-Equal $r.Code 0 'leg 1: the archive install exited 0'
  Assert-True (Test-Path -LiteralPath ([IO.Path]::Combine($Prefix, 'share', 'repro', 'completions', 'repro.ps1'))) 'leg 1: the archive share\ was installed'
  Assert-True (Test-Path -LiteralPath $loc.Script) "leg 1: the user's completion script: $($loc.Script)"
  foreach ($p in $loc.Profiles) { Assert-Equal (Get-CompletionBlockCount $p) 1 "leg 1: one completion block in $p" }
  Assert-True (Test-Path -LiteralPath $record) 'leg 1: the completion record'
  Assert-Completes -PowerShells $powershells -Environment $isoEnv -WorkingDirectory $Neutral -Want $true -Tag 'leg 1'
  $r = Invoke-Installer @('-Method', 'tarball', '-Version', $Version, '-Prefix', $Prefix)
  Assert-Equal $r.Code 0 'leg 1: a re-run exited 0'
  Assert-Equal (Get-RegistrationCount) $registered 'leg 1: still one script and one block per profile after a re-run'
  foreach ($p in $loc.Profiles) { Assert-Equal (Get-CompletionBlockCount $p) 1 "leg 1: still one completion block in $p" }
  Assert-Completes -PowerShells $powershells -Environment $isoEnv -WorkingDirectory $Neutral -Want $true -Tag 'leg 1 after a re-run'
  $r = Invoke-Installer @('-Method', 'tarball', '-Prefix', $Prefix, '-Uninstall')
  Assert-Equal $r.Code 0 'leg 1: -Uninstall exited 0'
  Assert-Equal (Get-RegistrationCount) 0 'leg 1: -Uninstall removed the script and every block'
  Assert-True (-not (Test-Path -LiteralPath $record)) 'leg 1: -Uninstall removed the completion record'
  Assert-True (-not (Test-Path -LiteralPath (Join-Path $Prefix 'bin'))) 'leg 1: -Uninstall removed the installed tree'
  Assert-Completes -PowerShells $powershells -Environment $isoEnv -WorkingDirectory $Neutral -Want $false -Tag 'leg 1 after -Uninstall'

  # ===================================================================
  Write-Step 'leg 2: -NoCompletion and REPRO_NO_COMPLETION=1'
  # ===================================================================
  Reset-Home
  $r = Invoke-Installer @('-Method', 'tarball', '-Version', $Version, '-Prefix', $Prefix, '-NoCompletion')
  Assert-Equal $r.Code 0 'leg 2: the -NoCompletion install exited 0'
  Assert-True (Test-Path -LiteralPath (Join-Path (Join-Path $Prefix 'bin') 'repro.exe')) 'leg 2: repro is installed'
  Assert-Equal (Get-RegistrationCount) 0 'leg 2: -NoCompletion registered nothing'
  Assert-True (-not (Test-Path -LiteralPath $record)) 'leg 2: no completion record'
  # The control for the probe: repro installed and on PATH, nothing
  # registered, so no session may complete `repro wor`.
  Assert-Completes -PowerShells $powershells -Environment $isoEnv -WorkingDirectory $Neutral -Want $false -Tag 'leg 2'
  $r = Invoke-Installer @('-Method', 'tarball', '-Prefix', $Prefix, '-Uninstall')
  Reset-Home
  $optOut = $installEnv.Clone()
  $optOut['REPRO_NO_COMPLETION'] = '1'
  $r = Invoke-Installer -Extra @('-Method', 'tarball', '-Version', $Version, '-Prefix', $Prefix) -Environment $optOut
  Assert-Equal $r.Code 0 'leg 2: the REPRO_NO_COMPLETION=1 install exited 0'
  Assert-Equal (Get-RegistrationCount) 0 'leg 2: REPRO_NO_COMPLETION=1 registered nothing'
  $r = Invoke-Installer @('-Method', 'tarball', '-Prefix', $Prefix, '-Uninstall')

  # ===================================================================
  Write-Step 'leg 3: a re-run with -NoCompletion removes an earlier registration'
  # ===================================================================
  Reset-Home
  $r = Invoke-Installer @('-Method', 'tarball', '-Version', $Version, '-Prefix', $Prefix)
  Assert-Equal (Get-RegistrationCount) $registered 'leg 3: the first install registered completion'
  $r = Invoke-Installer @('-Method', 'tarball', '-Version', $Version, '-Prefix', $Prefix, '-NoCompletion')
  Assert-Equal $r.Code 0 'leg 3: the -NoCompletion re-run exited 0'
  Assert-Equal (Get-RegistrationCount) 0 'leg 3: the -NoCompletion re-run removed the registration'
  Assert-True (-not (Test-Path -LiteralPath $record)) 'leg 3: and its record'
  $r = Invoke-Installer @('-Method', 'tarball', '-Prefix', $Prefix, '-Uninstall')

  Write-Step 'the invoking user''s real profiles are unchanged'
  $realAfter = Get-RealProfileState
  foreach ($l in $realAfter) { Write-Host "real-profile: after $l" }
  Assert-True ((Compare-Object $realBefore $realAfter | Measure-Object).Count -eq 0) 'the real profiles and per-user completion script are byte-identical before and after'

  $exit = Complete-Run -Name 'm8c_install_completion_windows' -Work $Work
} catch {
  Write-Host "HARNESS DIED: $($_.Exception.Message)"
  Write-Host $_.ScriptStackTrace
  $exit = 1
} finally {
  Stop-FileServer $server
  # The gpg-agent the throwaway key's home started, by that home only.
  if ($bash -and (Test-Path -LiteralPath (Join-Path $Work 'gnupg'))) {
    & $bash -c "gpgconf --homedir '$(ConvertTo-ScriptPath (Join-Path $Work 'gnupg'))' --kill all" 2>$null
  }
}
exit $exit
