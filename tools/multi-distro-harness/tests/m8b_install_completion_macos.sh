#!/bin/sh
# e2e_cs_m8b_install_script_sets_up_completion: on macOS, the installer's tarball
# method leaves Zsh, Bash and Fish completing `repro`, registered exactly once,
# and --uninstall takes it away again.
#
#   sh tools/multi-distro-harness/tests/m8b_install_completion_macos.sh
#
# Run it as an ordinary user on a Mac. It never uses sudo and writes only under
# one scratch directory (REPRO_M8B_WORK, default a mktemp -d under $TMPDIR): the
# installer is run as that user with a prefix, a state directory and a trust
# anchor of its own, and a scratch HOME and ZDOTDIR, so the machine's own
# /usr/local, home directory and shells' configuration are not touched. The
# script checks that, by comparing the files it would have written on the real
# machine before and after.
#
# What it needs:
#   * a built reprobuild tree, for a real `repro`: completing `repro wor` runs
#     the installed `repro __complete`, and registering completion runs the
#     installed `repro hooks ensure`, so a stand-in script will not do. Build
#     with `bash scripts/build_apps.sh`; REPRO_M8B_BUILD_DIR names its build/
#     directory (default <checkout>/build). The script turns it into an archive
#     of the release's shape (bin/, lib/, share/repro/completions/ generated by
#     scripts/release/stage_release_completions.sh), or REPRO_M8B_ARCHIVE names
#     a real macOS release archive, reprobuild-<version>-darwin-aarch64.tar.gz.
#   * curl, gpg, python3, /bin/zsh and /bin/bash; and fish, or its legs are
#     reported NOT RUN. A throwaway signing key signs the archive; a local HTTP
#     server stands in for the release host (REPRO_BASE_URL).
#   * optionally REPRO_M8B_BASH_COMPLETION (a bash_completion script) and
#     REPRO_M8B_BASH5 (a bash 4.2 or newer): macOS's own bash is 3.2 and has no
#     bash-completion, so the leg that runs the package's Bash file under a
#     real bash-completion is reported NOT RUN without them. For example, from
#     Nix: nix build --no-link --print-out-paths nixpkgs#bash-completion, and
#     REPRO_M8B_BASH_COMPLETION=<that path>/share/bash-completion/bash_completion.
#
# Legs:
#   1  The tarball install, as an ordinary user with a prefix of their own:
#      the archive's share/ is installed, the user's files and rc blocks
#      exist and are the user's, nothing is written on the real machine, the
#      three shells complete `repro wor<Tab>` to `workspace` (macOS's bash 3.2
#      through a block in ~/.bashrc, since it has no bash-completion), a re-run
#      leaves one registration per shell, and --uninstall removes everything.
#   2  --no-completion and REPRO_NO_COMPLETION=1: no completion anywhere, and
#      the shells do NOT complete. This is the control that shows the probe is
#      not vacuous.
#   3  A prefix the user cannot write is refused before anything is fetched,
#      and nothing is written.
#   4  The .pkg's and the Homebrew formula's file layout under a real
#      bash-completion and fish (relocated into the scratch directory with
#      XDG_DATA_DIRS, since /usr/local cannot be written): the Bash file at
#      share/bash-completion/completions/repro and the Fish file at
#      share/fish/vendor_completions.d/repro.fish complete.
#
# How completion is observed: each shell is started interactively on a
# pseudo-terminal, from an empty directory, and is typed `repro wor` and a Tab.
# Completion has worked when the terminal then shows the rest of the word
# (`kspace`), which the typed text does not contain. The probe kills only the
# shell it started.
#
# Exit status: 0 when every check passed and no leg was NOT RUN, 1 on a failed
# check, 3 when all checks passed but a leg was NOT RUN (set
# REPRO_M8B_ALLOW_NOT_RUN=1 to make that 0, for a machine known to lack the
# optional tools).

set -eu

REPO_ROOT="${REPRO_REPO_ROOT:-$(CDPATH='' cd -- "$(dirname -- "$0")/../../.." && pwd)}"
SIGN_DIR="$REPO_ROOT/scripts/release-signing"
INSTALL_SH="$REPO_ROOT/scripts/install/repro-install.sh"
STAGE_COMPLETIONS="$REPO_ROOT/scripts/release/stage_release_completions.sh"

fails=0
checks=0
notrun=''
step() { printf '\n=== %s ===\n' "$*"; }
ok()   { checks=$((checks + 1)); printf 'PASS  %s\n' "$*"; }
bad()  { checks=$((checks + 1)); fails=$((fails + 1)); printf 'FAIL  %s\n' "$*"; }
not_run() { notrun="$notrun
  $*"; printf 'NOT RUN  %s\n' "$*"; }
assert_eq() { if [ "$1" = "$2" ]; then ok "$3 (= $1)"; else bad "$3: expected '$2', got '$1'"; fi; }
assert_file() { if [ -e "$1" ]; then ok "$2: $1"; else bad "$2 missing: $1"; fi; }
assert_absent() { if [ ! -e "$1" ]; then ok "$2 absent: $1"; else bad "$2 still present: $1"; fi; }

# ---------------------------------------------------------------------
step 'preconditions'
# ---------------------------------------------------------------------
[ "$(uname -s)" = Darwin ] || { echo 'm8b_install_completion_macos: this runs on macOS only' >&2; exit 1; }
[ "$(id -u)" -ne 0 ] || { echo 'm8b_install_completion_macos: run it as an ordinary user, not root' >&2; exit 1; }
for f in "$INSTALL_SH" "$STAGE_COMPLETIONS" "$SIGN_DIR/make-test-key.sh" "$SIGN_DIR/repro-sign-release.sh" "$SIGN_DIR/repro-verify-release.sh"; do
  [ -f "$f" ] || { echo "missing required script: $f" >&2; exit 1; }
done
for t in curl gpg python3 shasum; do
  command -v "$t" >/dev/null 2>&1 || { echo "missing required tool: $t" >&2; exit 1; }
done
[ -x /bin/zsh ] && [ -x /bin/bash ] || { echo 'missing /bin/zsh or /bin/bash' >&2; exit 1; }
FISH="$(command -v fish 2>/dev/null || true)"

REAL_HOME="$HOME"
WORK="${REPRO_M8B_WORK:-$(mktemp -d "${TMPDIR:-/tmp}/m8b-install-completion.XXXXXX")}"
mkdir -p "$WORK"
WORK="$(CDPATH='' cd -- "$WORK" && pwd -P)"
H="$WORK/home"
ZD="$WORK/zdotdir"
PREFIX="$WORK/prefix"
STATE="$WORK/state"
KEYRING_DEST="$WORK/keyring/anchor.asc"
WWW="$WORK/www"
PORT="${REPRO_M8B_PORT:-8742}"
BASE="http://127.0.0.1:$PORT"
V='0.2.29'
TOP="reprobuild-$V-darwin-aarch64"
ASSET="$TOP.tar.gz"
KEYRING_FILE='metacraft-labs-archive-keyring.asc'

# The installer's userland is macOS's own: /usr/bin and /bin first, and a
# directory holding links to the few tools it needs from elsewhere (curl,
# gpg and fish may come from Nix). In particular there is no sha256sum.
TOOLS="$WORK/tools"
mkdir -p "$TOOLS" "$H" "$ZD" "$WORK/tmp"
for t in curl gpg gpgv python3 fish; do
  _p="$(command -v "$t" 2>/dev/null || true)"
  [ -z "$_p" ] || ln -sf "$_p" "$TOOLS/$t"
done
BASEPATH="$TOOLS:/usr/bin:/bin:/usr/sbin:/sbin"

# What this machine's shells actually read, printed rather than assumed.
echo "macOS $(sw_vers -productVersion 2>/dev/null || echo '?') on $(uname -m)"
echo "bash: $(/bin/bash --version | head -n 1)"
echo "zsh:  $(/bin/zsh --version)"
echo "fish: ${FISH:-none} ${FISH:+$("$FISH" --version)}"
echo 'zsh default fpath (/bin/zsh -f):'; /bin/zsh -f -c 'print -rl -- $fpath' | sed 's/^/  /'
if [ -n "$FISH" ]; then
  echo 'fish_complete_path, XDG_DATA_DIRS unset:'
  env -i HOME="$H" PATH="$BASEPATH" __fish_nix_darwin_general_config_sourced=1 "$FISH" -c 'string join \n $fish_complete_path' | sed 's/^/  /'
fi

# The places the installer must not touch on the real machine: the real home's
# rc files and completion locations, and the system completion directories.
REAL_PATHS="$REAL_HOME/.zshrc $REAL_HOME/.bashrc $REAL_HOME/.bash_profile $REAL_HOME/.profile \
$REAL_HOME/.config/fish/completions/repro.fish \
$REAL_HOME/.local/share/bash-completion/completions/repro \
$REAL_HOME/.local/share/zsh/site-functions/_repro \
/usr/local/share/bash-completion/completions/repro /usr/local/share/zsh/site-functions/_repro \
/usr/local/share/fish/vendor_completions.d/repro.fish /usr/local/etc/bash_completion.d/repro \
/etc/fish/completions/repro.fish"
real_state() {
  for _p in $REAL_PATHS; do
    if [ -e "$_p" ]; then printf '%s %s\n' "$_p" "$(shasum -a 256 "$_p" | awk '{print $1}')"
    else printf '%s absent\n' "$_p"; fi
  done
}
real_state > "$WORK/real-before.txt"

# User locations of the scratch home, and the places a script could be
# registered from; "registered once" means exactly one script per shell.
USR_BASH="$H/.local/share/bash-completion/completions/repro"
USR_ZSH="$H/.local/share/zsh/site-functions/_repro"
USR_FISH="$H/.config/fish/completions/repro.fish"
ALL_LOCATIONS="$USR_BASH $USR_ZSH $USR_FISH"
count_present() {
  _n=0
  for _p in "$@"; do [ -e "$_p" ] && _n=$((_n + 1)); done
  echo "$_n"
}

HTTP_PID=''
cleanup() {
  set +e
  [ -z "$HTTP_PID" ] || kill "$HTTP_PID" 2>/dev/null
}
trap cleanup EXIT INT TERM

# ---------------------------------------------------------------------
step 'the release archive, signed with a throwaway key, served over local HTTP'
# ---------------------------------------------------------------------
DL="$WWW/downloads/v$V"
mkdir -p "$DL" "$WWW/keys"
if [ -n "${REPRO_M8B_ARCHIVE:-}" ]; then
  [ -f "$REPRO_M8B_ARCHIVE" ] || { echo "no archive at $REPRO_M8B_ARCHIVE" >&2; exit 1; }
  _an="$(basename "$REPRO_M8B_ARCHIVE")"
  [ "$_an" = "$ASSET" ] || { echo "the archive must be named $ASSET (the installer asks for that name), not $_an" >&2; exit 1; }
  cp "$REPRO_M8B_ARCHIVE" "$DL/$ASSET"
else
  BUILD="${REPRO_M8B_BUILD_DIR:-$REPO_ROOT/build}"
  [ -x "$BUILD/bin/repro" ] || { echo "no $BUILD/bin/repro; build first (bash scripts/build_apps.sh) or set REPRO_M8B_ARCHIVE" >&2; exit 1; }
  A="$WORK/archive-src/$TOP"
  mkdir -p "$A/bin" "$A/lib"
  for f in "$BUILD"/bin/*; do
    [ -f "$f" ] && [ -x "$f" ] || continue
    case "$f" in *.stale|*.old) continue ;; esac
    cp "$f" "$A/bin/"
  done
  for f in "$BUILD"/lib/*; do
    [ -f "$f" ] || continue
    case "$f" in *.stale|*.old) continue ;; esac
    cp "$f" "$A/lib/"
  done
  ( cd "$REPO_ROOT" && REPRO_COMPLETION_BIN="$BUILD/bin/repro" bash "$STAGE_COMPLETIONS" "$A" ) \
    || { echo 'stage_release_completions.sh failed' >&2; exit 1; }
  tar -czf "$DL/$ASSET" -C "$WORK/archive-src" "$TOP"
fi
GOOD_HOME="$WORK/gnupg-good"
GOOD_FPR="$(sh "$SIGN_DIR/make-test-key.sh" --home "$GOOD_HOME")"
[ -n "$GOOD_FPR" ] || { echo 'no signing key' >&2; exit 1; }
( cd "$DL" && shasum -a 256 "$ASSET" > SHA256SUMS )
env GNUPGHOME="$GOOD_HOME" REPRO_SIGNING_ALLOW_TEST_KEY=1 \
  sh "$SIGN_DIR/repro-sign-release.sh" --dir "$DL" --key "$GOOD_FPR" > "$WORK/sign.log" 2>&1 \
  || { cat "$WORK/sign.log"; echo 'repro-sign-release.sh failed' >&2; exit 1; }
gpg --homedir "$GOOD_HOME" --armor --export "$GOOD_FPR" > "$WWW/keys/$KEYRING_FILE" 2>/dev/null
ANCHOR_SHA="$(shasum -a 256 "$WWW/keys/$KEYRING_FILE" | awk '{print $1}')"
ok "archive $ASSET and its signatures are under $DL"

if curl -fsS -o /dev/null "$BASE/" 2>/dev/null; then
  echo "FATAL: $BASE answers before this run started its server" >&2; exit 1
fi
( cd "$WWW" && exec python3 -m http.server "$PORT" --bind 127.0.0.1 ) > "$WORK/http.log" 2>&1 &
HTTP_PID=$!
_i=0
until curl -fsS -o /dev/null "$BASE/downloads/v$V/SHA256SUMS" 2>/dev/null; do
  _i=$((_i + 1))
  if [ "$_i" -ge 50 ] || ! kill -0 "$HTTP_PID" 2>/dev/null; then cat "$WORK/http.log"; echo 'the HTTP server did not come up' >&2; exit 1; fi
  sleep 0.2
done
ok "HTTP server pid $HTTP_PID serves $BASE"

# The installer, run as this user from the scratch directory, with its own
# prefix, state directory and trust anchor, a clean environment and macOS's
# own userland. `sh` is /bin/sh, macOS's bash 3.2 in POSIX mode.
installer() {
  ( cd "$WORK" && env -i HOME="$H" USER="$(id -un)" LOGNAME="$(id -un)" PATH="$BASEPATH" \
      TMPDIR="$WORK/tmp" ZDOTDIR="$ZD" \
      REPRO_BASE_URL="$BASE" REPRO_KEYRING_SHA256="$ANCHOR_SHA" REPRO_KEYRING_FILE="$KEYRING_FILE" \
      REPRO_KEYRING_DEST="$KEYRING_DEST" REPRO_ALLOW_TEST_KEY=1 \
      REPRO_VERIFY_SCRIPT="$SIGN_DIR/repro-verify-release.sh" \
      REPRO_TARBALL_MANIFEST="$STATE/installed-files.txt" REPRO_REPO_USERS_DIR="$STATE/users" \
      "$@" )
}

# The pty probe. It starts ONE shell on a pseudo-terminal, answers the terminal
# queries a shell may wait on, types `repro wor` and a Tab, and reports whether
# the rest of the word appeared. For Bash it also reports how many `complete`
# registrations `repro` has. It kills only the process it started.
cat > "$WORK/pty_complete.py" <<'PY'
import os, pty, re, select, signal, sys, time

transcript_path = sys.argv[1]
is_bash = sys.argv[2] == "bash"
argv = sys.argv[3:]
pid, fd = pty.fork()
if pid == 0:
    os.execv(argv[0], argv)

buf = bytearray()

def pump(seconds, until=None):
    end = time.time() + seconds
    while time.time() < end:
        r, _, _ = select.select([fd], [], [], 0.1)
        if r:
            try:
                data = os.read(fd, 65536)
            except OSError:
                return False
            if not data:
                return False
            buf.extend(data)
            if b"\x1b[c" in data or b"\x1b[0c" in data:
                os.write(fd, b"\x1b[?62;22c")
            if b"\x1b[6n" in data:
                os.write(fd, b"\x1b[1;1R")
        if until is not None and until(bytes(buf)):
            return True
    return False

def plain(b):
    return re.sub(rb"\x1b\[[0-9;?]*[ -/]*[@-~]|\x1b[\]P][^\x07\x1b]*(\x07|\x1b\\)|\x1b[()][0-9A-Za-z]|\x1b[=>]|\r", b"", b)

try:
    pump(3)
    os.write(fd, b"echo M8B''READY\r")
    ready = pump(20, lambda b: b"M8BREADY" in plain(b).replace(b"M8B''READY", b""))
    mark = len(buf)
    os.write(fd, b"repro wor\t")
    completed = pump(15, lambda b: b"kspace" in plain(b[mark:]))
    registrations = "-"
    if is_bash:
        os.write(fd, b"\x15echo M8BCOUNT=$(complete -p repro 2>/dev/null | wc -l | tr -d ' ')\r")
        pump(10, lambda b: re.search(rb"M8BCOUNT=\d", plain(b[mark:])) is not None)
        m = re.search(rb"M8BCOUNT=(\d+)", plain(bytes(buf[mark:])))
        registrations = m.group(1).decode() if m else "?"
    print(f"ready={'yes' if ready else 'no'} completed={'yes' if completed else 'no'} registrations={registrations}")
finally:
    try:
        os.write(fd, b"\x15exit\r")
        pump(2)
    except OSError:
        pass
    try:
        os.kill(pid, signal.SIGKILL)
    except ProcessLookupError:
        pass
    try:
        os.waitpid(pid, 0)
    except ChildProcessError:
        pass
    with open(transcript_path, "wb") as f:
        f.write(plain(bytes(buf)))
PY

# probe <tag> <bash|zsh|fish> <shell argv...> [env NAME=VALUE ...]: run the pty
# probe from an empty directory in a clean environment (the scratch home and
# ZDOTDIR; `repro` on PATH from the scratch prefix); print its one-line result.
# Extra environment goes in PROBE_ENV (a list of NAME=VALUE words).
PROBE_ENV=''
# A machine whose /etc/zshenv and /etc/fish/config.fish are generated by
# nix-darwin resets PATH and fpath from there, which would hide the scratch
# prefix from the probe. Those files skip themselves when these variables are
# set, so the shells run as they do on a stock macOS: macOS's own /etc files
# do not touch PATH or completion. (Harmless names on a machine without them.)
SHELL_GUARDS='__ETC_ZSHENV_SOURCED=1 __ETC_ZPROFILE_SOURCED=1 __ETC_ZSHRC_SOURCED=1 __fish_nix_darwin_general_config_sourced=1 __fish_nix_darwin_login_config_sourced=1 __NIX_DARWIN_SET_ENVIRONMENT_DONE=1'
probe() {
  _tag="$1"; _kind="$2"; shift 2
  _d="$(mktemp -d "$WORK/tmp/probe.XXXXXX")"
  # shellcheck disable=SC2086
  ( cd "$_d" && env -i HOME="$H" USER="$(id -un)" LOGNAME="$(id -un)" ZDOTDIR="$ZD" \
      TERM=xterm LANG=en_US.UTF-8 PATH="$PREFIX/bin:$BASEPATH" $SHELL_GUARDS $PROBE_ENV \
      python3 "$WORK/pty_complete.py" "$_d/.transcript" "$_kind" "$@" ) 2>&1 | tail -n 1
  cp "$_d/.transcript" "$WORK/transcript-$(printf %s "$_tag" | tr ' /' --)-$_kind.txt" 2>/dev/null || true
  rm -rf "$_d"
}

# assert_probe <tag> <yes|no> <bash|zsh|fish> <shell argv...>
assert_probe() {
  _tag="$1"; _want="$2"; _kind="$3"; shift 3
  _r="$(probe "$_tag" "$_kind" "$@")"
  _t="$WORK/transcript-$(printf %s "$_tag" | tr ' /' --)-$_kind.txt"
  case "$_r" in *'ready=yes'*) ;; *) bad "$_tag: the $_kind probe never got a prompt ($_r; transcript $_t)"; return 0 ;; esac
  case "$_r" in
    *"completed=$_want"*) ok "$_tag: $_kind completes 'repro wor<Tab>' -> workspace: $_want ($_r)" ;;
    *) bad "$_tag: $_kind: expected completed=$_want, got: $_r (transcript $_t)"; sed -n '1,30p' "$_t" ;;
  esac
  if [ "$_kind" = bash ] && [ "$_want" = yes ]; then
    case "$_r" in
      *'registrations=1'*) ok "$_tag: bash has exactly one 'complete' registration for repro" ;;
      *) bad "$_tag: bash registrations for repro: $_r" ;;
    esac
  fi
}

# The three shells as a user would start them: macOS's zsh and bash, and fish.
shells_probe() {
  _tag="$1"; _want="$2"
  assert_probe "$_tag" "$_want" zsh /bin/zsh -d -i
  assert_probe "$_tag" "$_want" bash /bin/bash -i
  if [ -n "$FISH" ]; then assert_probe "$_tag" "$_want" fish "$FISH" -i
  else not_run "$_tag: fish (no fish on PATH)"
  fi
}

new_home() {
  rm -rf "$H" "$ZD" "$PREFIX" "$STATE" "$WORK/keyring"
  mkdir -p "$H" "$ZD"
  printf 'autoload -U compinit; compinit\n' > "$ZD/.zshrc"
}

# =====================================================================
step 'leg 1: tarball install as an ordinary user, with a prefix of their own'
# =====================================================================
new_home
assert_eq "$(count_present $ALL_LOCATIONS)" '0' 'leg 1: no repro completion script before the install'
set +e
installer sh "$INSTALL_SH" --method tarball --version "$V" --prefix "$PREFIX" > "$WORK/leg1.log" 2>&1
_rc=$?
set -e
sed -n '1,60p' "$WORK/leg1.log"
assert_eq "$_rc" '0' 'leg 1: the tarball install exited 0'
assert_file "$PREFIX/lib/reprobuild/share/repro/completions/_repro" 'leg 1: the archive share/ was installed'
assert_file "$PREFIX/bin/repro" 'leg 1: the repro command'
assert_eq "$(find "$PREFIX/lib/reprobuild" -perm -020 ! -type l | wc -l | tr -d ' ')" '0' 'leg 1: no installed file is group-writable'
assert_eq "$(find "$PREFIX/lib/reprobuild" -perm -002 ! -type l | wc -l | tr -d ' ')" '0' 'leg 1: no installed file is world-writable'
assert_eq "$(find "$PREFIX/lib/reprobuild" ! -user "$(id -un)" | wc -l | tr -d ' ')" '0' 'leg 1: every installed file is the installing user'"'"'s'
for _p in $ALL_LOCATIONS "$ZD/.zshrc"; do assert_file "$_p" 'leg 1: completion file or rc file'; done
assert_eq "$(count_present $ALL_LOCATIONS)" '3' 'leg 1: one completion script per shell'
assert_eq "$(grep -c '>>> repro:home:repro-completion-zsh >>>' "$ZD/.zshrc" || true)" '1' 'leg 1: one zsh block in .zshrc'
assert_eq "$(grep -c 'repro:home:repro-completion' "$H/.bashrc" 2>/dev/null || echo 0)" '2' 'leg 1: the bash block in ~/.bashrc (marker lines; bash 3.2 has no bash-completion)'
assert_file "$STATE/completion" 'leg 1: the completion record'
shells_probe 'leg 1' yes
# A re-run: still one registration per shell.
set +e
installer sh "$INSTALL_SH" --method tarball --version "$V" --prefix "$PREFIX" > "$WORK/leg1-rerun.log" 2>&1
_rc=$?
set -e
assert_eq "$_rc" '0' 'leg 1: a re-run exited 0'
assert_eq "$(count_present $ALL_LOCATIONS)" '3' 'leg 1: still one script per shell after a re-run'
assert_eq "$(grep -c '>>> repro:home:repro-completion-zsh >>>' "$ZD/.zshrc" || true)" '1' 'leg 1: still one zsh block after a re-run'
assert_eq "$(grep -c 'repro:home:repro-completion' "$H/.bashrc" 2>/dev/null || echo 0)" '2' 'leg 1: still one bash block after a re-run'
shells_probe 'leg 1 after a re-run' yes
set +e
installer sh "$INSTALL_SH" --method tarball --prefix "$PREFIX" --uninstall > "$WORK/leg1-uninstall.log" 2>&1
_rc=$?
set -e
sed -n '1,30p' "$WORK/leg1-uninstall.log"
assert_eq "$_rc" '0' 'leg 1: --uninstall exited 0'
assert_eq "$(count_present $ALL_LOCATIONS)" '0' 'leg 1: --uninstall removed every completion script'
assert_eq "$(grep -c 'repro:home:repro-completion' "$ZD/.zshrc" || true)" '0' 'leg 1: --uninstall removed the zsh block'
assert_eq "$(grep -c 'repro:home:repro-completion' "$H/.bashrc" 2>/dev/null || echo 0)" '0' 'leg 1: --uninstall removed the bash block'
assert_absent "$STATE/completion" 'leg 1: the completion record'
assert_absent "$PREFIX/lib/reprobuild" 'leg 1: the tarball tree'
assert_absent "$PREFIX/bin/repro" 'leg 1: the repro command'

# =====================================================================
step 'leg 2: --no-completion and REPRO_NO_COMPLETION=1'
# =====================================================================
new_home
set +e
installer sh "$INSTALL_SH" --method tarball --version "$V" --prefix "$PREFIX" --no-completion > "$WORK/leg2.log" 2>&1
_rc=$?
set -e
sed -n '1,40p' "$WORK/leg2.log"
assert_eq "$_rc" '0' 'leg 2: the --no-completion install exited 0'
assert_file "$PREFIX/bin/repro" 'leg 2: repro is installed'
assert_eq "$(count_present $ALL_LOCATIONS)" '0' 'leg 2: --no-completion wrote no completion script'
assert_eq "$(grep -c 'repro:home:repro-completion' "$ZD/.zshrc" || true)" '0' 'leg 2: --no-completion wrote no zsh block'
assert_absent "$H/.bashrc" 'leg 2: a ~/.bashrc'
assert_absent "$STATE/completion" 'leg 2: a completion record'
# The control for the probe itself: repro installed, no completion registered,
# so no shell may complete `repro wor`.
shells_probe 'leg 2' no
set +e
installer env REPRO_NO_COMPLETION=1 sh "$INSTALL_SH" --method tarball --version "$V" --prefix "$PREFIX" > "$WORK/leg2b.log" 2>&1
_rc=$?
set -e
assert_eq "$_rc" '0' 'leg 2: the REPRO_NO_COMPLETION=1 install exited 0'
assert_eq "$(count_present $ALL_LOCATIONS)" '0' 'leg 2: REPRO_NO_COMPLETION=1 wrote no completion script'
installer sh "$INSTALL_SH" --method tarball --prefix "$PREFIX" --uninstall > "$WORK/leg2-uninstall.log" 2>&1 || true

# =====================================================================
step 'leg 3: a prefix this user cannot write is refused, with nothing written'
# =====================================================================
new_home
snapshot_dir() { find "$1" -exec /usr/bin/stat -f '%N %z %m' {} + 2>/dev/null | LC_ALL=C sort; }
snapshot_dir "$H" > "$WORK/home-before.txt"
set +e
installer sh "$INSTALL_SH" --method tarball --version "$V" --prefix /usr/lib/m8b-unwritable-prefix > "$WORK/leg3.log" 2>&1
_rc=$?
set -e
sed -n '1,10p' "$WORK/leg3.log"
if [ "$_rc" -ne 0 ]; then ok "leg 3: the install exited non-zero ($_rc)"; else bad 'leg 3: an unwritable prefix was accepted'; fi
if grep -q 'cannot write' "$WORK/leg3.log"; then ok 'leg 3: the refusal names the directory the user cannot write'; else bad 'leg 3: no refusal naming the directory'; fi
assert_absent /usr/lib/m8b-unwritable-prefix 'leg 3: the prefix'
assert_eq "$(count_present $ALL_LOCATIONS)" '0' 'leg 3: no completion script'
snapshot_dir "$H" > "$WORK/home-after.txt"
if cmp -s "$WORK/home-before.txt" "$WORK/home-after.txt"; then ok 'leg 3: nothing written under the scratch home'
else bad 'leg 3: the refused install wrote under the scratch home'; diff "$WORK/home-before.txt" "$WORK/home-after.txt" || true
fi

# =====================================================================
step "leg 4: the .pkg's and the formula's file layout under a real bash-completion and fish"
# =====================================================================
# The .pkg installs share/bash-completion/completions/repro and
# share/fish/vendor_completions.d/repro.fish under /usr/local (the formula, its
# own prefix). /usr/local cannot be written here, so the same layout is put in
# a scratch directory that XDG_DATA_DIRS names, which is how bash-completion
# and fish find /usr/local/share on a machine that names it.
new_home
SYS="$WORK/sys"
rm -rf "$SYS"
mkdir -p "$SYS/share/bash-completion/completions" "$SYS/share/fish/vendor_completions.d" "$SYS/bin"
installer sh "$INSTALL_SH" --method tarball --version "$V" --prefix "$PREFIX" --no-completion > "$WORK/leg4-install.log" 2>&1 \
  || { cat "$WORK/leg4-install.log"; bad 'leg 4: the --no-completion install failed'; }
cp "$PREFIX/lib/reprobuild/share/repro/completions/repro.bash" "$SYS/share/bash-completion/completions/repro"
cp "$PREFIX/lib/reprobuild/share/repro/completions/repro.fish" "$SYS/share/fish/vendor_completions.d/repro.fish"
if [ -n "${REPRO_M8B_BASH_COMPLETION:-}" ] && [ -n "${REPRO_M8B_BASH5:-}" ] \
   && [ -f "$REPRO_M8B_BASH_COMPLETION" ] && [ -x "$REPRO_M8B_BASH5" ]; then
  echo "bash: $("$REPRO_M8B_BASH5" --version | head -n 1); bash-completion: $REPRO_M8B_BASH_COMPLETION"
  printf '. "%s"\n' "$REPRO_M8B_BASH_COMPLETION" > "$WORK/bc-rc"
  PROBE_ENV="XDG_DATA_DIRS=$SYS/share"
  assert_probe 'leg 4 Bash file in share/bash-completion/completions' yes bash "$REPRO_M8B_BASH5" --rcfile "$WORK/bc-rc" -i
  # Without the directory on XDG_DATA_DIRS the same shell finds nothing: the
  # control that shows the file is what the completion comes from.
  PROBE_ENV="XDG_DATA_DIRS=$WORK/empty-share"
  assert_probe 'leg 4 control: directory not searched' no bash "$REPRO_M8B_BASH5" --rcfile "$WORK/bc-rc" -i
  PROBE_ENV=''
else
  not_run 'leg 4: Bash file under a real bash-completion (set REPRO_M8B_BASH_COMPLETION and REPRO_M8B_BASH5)'
fi
if [ -n "$FISH" ]; then
  PROBE_ENV="XDG_DATA_DIRS=$SYS/share"
  assert_probe 'leg 4 Fish file in share/fish/vendor_completions.d' yes fish "$FISH" -i
  PROBE_ENV="XDG_DATA_DIRS=$WORK/empty-share"
  assert_probe 'leg 4 control: directory not searched' no fish "$FISH" -i
  PROBE_ENV=''
else
  not_run 'leg 4: Fish file under vendor_completions.d (no fish on PATH)'
fi
installer sh "$INSTALL_SH" --method tarball --prefix "$PREFIX" --uninstall > "$WORK/leg4-uninstall.log" 2>&1 || true

