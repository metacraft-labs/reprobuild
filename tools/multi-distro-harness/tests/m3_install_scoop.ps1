<#
M3 HOSTING+REPOS+INSTALLER gate, Windows/Scoop arm.

  pwsh -NoProfile -File tools/multi-distro-harness/tests/m3_install_scoop.ps1

Proves, with Scoop's own actions, output and exit codes:

  S1  the installer registers a Scoop bucket and Scoop installs reprobuild
  S2  a SECOND installer run changes nothing (measured, not asserted)
  S3  publishing a newer manifest makes `scoop status` report an update
  S4  `scoop update reprobuild` MOVES the box to the newer release
  S5  a TAMPERED archive is REJECTED by Scoop's own hash check
  S6  -Uninstall leaves no app and no bucket

with the control that makes S1 and S5 mean anything:

  N0  a manifest whose hash does not match the artifact is REJECTED,
      and the GENUINE one with the same URL is ACCEPTED. Without the
      pair, S5 could be passing because the download failed.

## A REAL local bucket, not a placeholder

runquota's packaging leaves `@SCOOP_URL@` unsubstituted because no bucket
exists to publish to. A bucket is only a git repository containing
bucket/<app>.json, so one can be stood up locally -- and is, here. The
manifest is generated by the real release step
(scripts/release/repro-publish-repos.sh --ecosystem scoop) with its URL
pointed at a local HTTP server, so nothing is templated out.

## The user's own Scoop install is NOT touched

$env:SCOOP is redirected to a scratch root for the whole arm, so the apps
and buckets created here live and die in a temp directory. The arm asserts
the redirection took effect before installing anything: without that
check, a failed redirect would silently install into the developer's real
Scoop root.
#>
[CmdletBinding()]
param(
  [int]$Port = 8733,
  [string]$WorkRoot = ''
)

$ErrorActionPreference = 'Continue'
Set-StrictMode -Version Latest

$RepoRoot = (Resolve-Path -LiteralPath (Join-Path $PSScriptRoot '..\..\..')).Path
$InstallPs1 = Join-Path $RepoRoot 'scripts\install\repro-install.ps1'
$Publish = Join-Path $RepoRoot 'scripts\release\repro-publish-repos.sh'
$SignDir = Join-Path $RepoRoot 'scripts\release-signing'

if (-not $WorkRoot) { $WorkRoot = Join-Path $env:TEMP 'm3-install-scoop' }
$Www = Join-Path $WorkRoot 'www'
$Base = "http://127.0.0.1:$Port"
$V1 = '0.1.3'
$V2 = '0.1.4'
$AppName = 'reprobuild'
$BucketName = 'reprobuild'

$script:checks = 0
$script:fails = 0
# The number of checks a COMPLETE run performs. Asserted at the end,
# because the first version of this arm threw at step 3 and still printed
# "2 checks, 0 failure(s)" -- an arm that dies early must never look
# green. This is the same class of false green the campaign keeps
# catching, produced by the test harness itself.
$script:ExpectedMinChecks = 45
function Step { param([string]$m) Write-Host "`n=== $m ===" }
function Ok   { param([string]$m) $script:checks++; Write-Host "PASS  $m" }
function Bad  { param([string]$m) $script:checks++; $script:fails++; Write-Host "FAIL  $m" }
function AssertEq {
  param($Got, $Want, [string]$What)
  if ([string]$Got -eq [string]$Want) { Ok "$What (= $Got)" } else { Bad "${What}: expected '$Want', got '$Got'" }
}
function AssertNe {
  param($A, $B, [string]$What)
  if ([string]$A -ne [string]$B) { Ok "$What ('$A' != '$B')" } else { Bad "${What}: both are '$A'" }
}
function AssertFile { param([string]$p, [string]$what)
  if (Test-Path -LiteralPath $p) { Ok "$what exists: $p" } else { Bad "$what missing: $p" } }
function AssertAbsent { param([string]$p, [string]$what)
  if (-not (Test-Path -LiteralPath $p)) { Ok "$what is absent: $p" } else { Bad "$what still present: $p" } }
# Counts, never truthiness: a regex that matched nothing is a vacuous pass.
function AssertMatches {
  param([string]$Text, [string]$Pattern, [string]$What)
  $n = ([regex]::Matches($Text, $Pattern, 'IgnoreCase')).Count
  if ($n -ge 1) { Ok "$What (matched $n occurrence(s) on '$Pattern')" }
  else {
    Bad "${What}: pattern '$Pattern' matched 0 times"
    Write-Host "vvv text vvv"; Write-Host ($Text -split "`n" | Select-Object -First 40 | Out-String); Write-Host "^^^ end ^^^"
  }
}

