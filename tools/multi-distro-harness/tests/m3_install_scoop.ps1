Step 'preconditions'
# ---------------------------------------------------------------------
foreach ($f in @($InstallPs1, $Publish, (Join-Path $SignDir 'make-test-key.sh'))) {
  if (-not (Test-Path -LiteralPath $f)) { Write-Host "missing required file: $f"; exit 1 }
}
foreach ($c in @('scoop', 'git', 'python')) {
  if (-not (Get-Command $c -ErrorAction SilentlyContinue)) {
    if ($c -eq 'python') {
      if (-not (Get-Command 'python3' -ErrorAction SilentlyContinue)) {
        Write-Host "missing required tool: python/python3 (needed for the local HTTP server)"; exit 1
      }
    } else { Write-Host "missing required tool: $c"; exit 1 }
  }
}
$Py = if (Get-Command 'python' -ErrorAction SilentlyContinue) { 'python' } else { 'python3' }
# The repo metadata generator is a POSIX shell script; on Windows it runs
# under Git for Windows' sh, which release.yml already assumes.
$Sh = (Get-Command 'sh' -ErrorAction SilentlyContinue)
if (-not $Sh) { Write-Host 'missing required tool: sh (Git for Windows)'; exit 1 }
$ShExe = $Sh.Source
Write-Host "scoop=$((scoop --version 2>&1 | Select-Object -First 1)) git=$(git --version) sh=$ShExe python=$Py"

if (Test-Path -LiteralPath $WorkRoot) { Remove-Item -LiteralPath $WorkRoot -Recurse -Force -ErrorAction SilentlyContinue }
New-Item -ItemType Directory -Path $Www -Force | Out-Null

# ---------------------------------------------------------------------
Step 'isolate SCOOP so the developer''s real install is untouched'
# ---------------------------------------------------------------------
$RealScoop = $env:SCOOP
$ScoopRoot = Join-Path $WorkRoot 'scoop'
New-Item -ItemType Directory -Path $ScoopRoot -Force | Out-Null
$env:SCOOP = $ScoopRoot
# Scoop expects its root to already have this skeleton; pointing $SCOOP
# at a bare empty directory makes `scoop bucket add` die inside Scoop's
# own commands.ps1 with "Cannot find path ...\shims". Creating the
# directories is all that is needed -- Scoop's CODE still comes from the
# real installation, only its DATA is redirected here.
foreach ($d in @('shims', 'buckets', 'apps', 'cache', 'persist')) {
  New-Item -ItemType Directory -Path (Join-Path $ScoopRoot $d) -Force | Out-Null
}
# Scoop resolves its SUPPORTING FILES out of $SCOOP\apps\scoop\current --
# notably supporting\shims\kiennq\shim.exe, which it copies when creating
# an app's shim. Without it `scoop install` gets as far as downloading,
# hash-checking and extracting, then fails at "Creating shim for 'repro'",
# and the app is left "not installed correctly" -- which in turn makes
# `scoop update` refuse it and `scoop uninstall` fail. So Scoop's own app
# tree is copied into the scratch root.
#
# Copied, not symlinked, and never written back: the real installation is
# only ever read. The final step of this arm asserts the real root's
# bucket count is unchanged.
$RealRootForCopy = $(if ($env:SCOOP -and $RealScoop) { $RealScoop } else { Join-Path $env:USERPROFILE 'scoop' })
$RealScoopApp = Join-Path $RealRootForCopy 'apps\scoop'
if (Test-Path -LiteralPath $RealScoopApp) {
  Copy-Item -LiteralPath $RealScoopApp -Destination (Join-Path $ScoopRoot 'apps\scoop') -Recurse -Force -ErrorAction SilentlyContinue
}
$ShimSrc = Join-Path $ScoopRoot 'apps\scoop\current\supporting\shims\kiennq\shim.exe'
# Asserted: if this is missing, every install below fails at the shim step
# and the arm's later phases would report confusing, unrelated failures.
AssertFile $ShimSrc 'the scratch Scoop root has Scoop''s own shim helper'
# `scoop update <app>` runs "Updating Buckets..." first, and with no
# 'main' bucket present it tries to convert one, fails with
# "ERROR 'main' bucket not found. / Failed to remove local 'main' bucket."
# and ABORTS before it ever looks at our app. So a minimal, empty 'main'
# bucket is created as a git repo to satisfy that maintenance pass.
#
# It is empty on purpose: cloning the real ScoopInstaller/Main would pull
# ~1600 manifests over the network for no benefit, and an empty bucket
# cannot accidentally supply the package under test -- every install below
# is addressed as `reprobuild/reprobuild`, so the app can only come from
# OUR bucket.
# It must be a CLONE, not a bare `git init`: Scoop's bucket refresh runs
# `git pull`, and a repo with no upstream fails with "There is no tracking
# information for the current branch", which aborts `scoop install` before
# it installs anything. So an origin is created and cloned from.
$MainOrigin = Join-Path $WorkRoot 'main-bucket-origin'
New-Item -ItemType Directory -Path (Join-Path $MainOrigin 'bucket') -Force | Out-Null
Set-Content -LiteralPath (Join-Path $MainOrigin 'bucket\.gitkeep') -Value '' -NoNewline
Push-Location $MainOrigin
& git init -q 2>&1 | Out-Null
& git config user.email 'm3-gate@reprobuild.invalid' | Out-Null
& git config user.name 'M3 Gate' | Out-Null
& git add -A 2>&1 | Out-Null
& git -c commit.gpgsign=false commit -q -m 'empty placeholder main bucket' 2>&1 | Out-Null
Pop-Location
$MainBucket = Join-Path $ScoopRoot 'buckets\main'
# protocol.file.allow=always: git >= 2.38 refuses local-path transport in
# some contexts by default.
& git -c protocol.file.allow=always clone -q ($MainOrigin -replace '\\','/') ($MainBucket -replace '\\','/') 2>&1 | Out-Null
Push-Location $MainBucket
& git config user.email 'm3-gate@reprobuild.invalid' | Out-Null
& git config user.name 'M3 Gate' | Out-Null
Pop-Location
AssertFile (Join-Path $MainBucket '.git') 'the placeholder main bucket is a git clone (has an upstream)'
# ASSERTED, not assumed: if the redirect did not take, everything below
# would install into the developer's real Scoop root.
AssertEq $env:SCOOP $ScoopRoot 'SCOOP is redirected to a scratch root'
AssertFile (Join-Path $ScoopRoot 'buckets') 'the scratch Scoop root has a buckets/ directory'
AssertNe $env:SCOOP $RealScoop 'the scratch root differs from the real SCOOP root'
# `Join-Path (if ...)` is a parse-time trap: `if` is a statement and
# cannot be a command argument, and PowerShell reports it only at run
# time as "The term 'if' is not recognized". Use a subexpression.
$RealScoopRoot = $(if ($RealScoop) { $RealScoop } else { Join-Path $env:USERPROFILE 'scoop' })
$RealBuckets = Join-Path $RealScoopRoot 'buckets'
$RealBucketBefore = $(if (Test-Path -LiteralPath $RealBuckets) {
  @(Get-ChildItem -LiteralPath $RealBuckets -Directory).Count } else { 0 })

$HttpProc = $null
function Stop-Http { if ($script:HttpProc -and -not $script:HttpProc.HasExited) { $script:HttpProc.Kill(); $script:HttpProc.WaitForExit(3000) } }
function Cleanup {
  Stop-Http
  try {
    if (Get-Command scoop -ErrorAction SilentlyContinue) {
      & scoop uninstall $AppName 6>$null 2>$null | Out-Null
      & scoop bucket rm $BucketName 6>$null 2>$null | Out-Null
    }
  } catch { }
  $env:SCOOP = $RealScoop
}

