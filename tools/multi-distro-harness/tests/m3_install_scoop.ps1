# ---------------------------------------------------------------------
Step 'build two fixture Windows release archives (release.yml asset shape)'
# ---------------------------------------------------------------------
function New-FixtureZip {
  param([string]$Ver)
  $top = "reprobuild-$Ver-windows-x86_64"
  $d = Join-Path $WorkRoot "stage\$top"
  if (Test-Path -LiteralPath $d) { Remove-Item -LiteralPath $d -Recurse -Force }
  New-Item -ItemType Directory -Path (Join-Path $d 'bin') -Force | Out-Null
  New-Item -ItemType Directory -Path (Join-Path $d 'lib') -Force | Out-Null
  # A .exe that reports its version, so the upgrade can be asserted
  # against INSTALLED BYTES. A .cmd is used rather than a compiled exe
  # because building real reprobuild is a heavy compile and this arm's
  # subject is the hosting/bucket/update machinery -- stated plainly, with
  # the cost: this does NOT prove reprobuild builds on Windows.
  Set-Content -LiteralPath (Join-Path $d 'bin\repro.exe') -Value "fixture-binary-$Ver" -NoNewline
  Set-Content -LiteralPath (Join-Path $d 'bin\repro-version.txt') -Value $Ver -NoNewline
  Set-Content -LiteralPath (Join-Path $d 'lib\reprofixture.dll') -Value "fixture-lib-$Ver" -NoNewline
  $zip = Join-Path $WorkRoot "pkgs-$Ver\$top.zip"
  New-Item -ItemType Directory -Path (Split-Path -Parent $zip) -Force | Out-Null
  Compress-Archive -Path $d -DestinationPath $zip -Force
  return $zip
}
$Zip1 = New-FixtureZip -Ver $V1
$Zip2 = New-FixtureZip -Ver $V2
AssertFile $Zip1 "fixture archive $V1"
AssertFile $Zip2 "fixture archive $V2"

# The archives are also the download surface the manifest points at.
foreach ($v in @($V1, $V2)) {
  $dl = Join-Path $Www "downloads\v$v"
  New-Item -ItemType Directory -Path $dl -Force | Out-Null
}
Copy-Item -LiteralPath $Zip1 -Destination (Join-Path $Www "downloads\v$V1") -Force
Copy-Item -LiteralPath $Zip2 -Destination (Join-Path $Www "downloads\v$V2") -Force

# ---------------------------------------------------------------------
Step "generate the $V1 Scoop manifest with the REAL release step"
# ---------------------------------------------------------------------
function Invoke-PublishScoop {
  param([string]$Ver, [string]$PkgDir, [string]$RepoRootDir)
  # No --key and no GNUPGHOME: a Scoop manifest is not signed, and the
  # publish step asks for a signing key only for the ecosystems that
  # actually sign. Passing one here would be accepted and never used.
  $pargs = @(
    ($Publish -replace '\\','/'),
    '--version', $Ver,
    '--packages', ($PkgDir -replace '\\','/'),
    '--ecosystem', 'scoop',
    '--repo-root', ($RepoRootDir -replace '\\','/'),
    '--target', ('local:' + ($Www -replace '\\','/')),
    '--scoop-downloads-base', "$Base/downloads",
    '--fetch-existing'
  )
  $out = & $ShExe @pargs 2>&1 | Out-String
  return $out
}
$pub1 = Invoke-PublishScoop -Ver $V1 -PkgDir (Join-Path $WorkRoot "pkgs-$V1") -RepoRootDir (Join-Path $WorkRoot 'repo1')
Write-Host $pub1
$ManifestPath = Join-Path $Www 'scoop\bucket\reprobuild.json'
AssertFile $ManifestPath 'published Scoop manifest'
AssertMatches $pub1 'scoop manifest: version=0\.1\.3' 'the publish step reported the manifest version'
$m1 = Get-Content -LiteralPath $ManifestPath -Raw
AssertMatches $m1 '"version":\s*"0\.1\.3"' 'manifest declares 0.1.3'
AssertMatches $m1 '"hash":\s*"sha256:[0-9a-f]{64}"' 'manifest carries a real sha256'
# The whole point of a local bucket: no placeholder survives.
AssertEq ([regex]::Matches($m1, '@SCOOP_URL@|@SCOOP_SHA256@').Count) 0 'manifest carries NO unsubstituted placeholder'
$expected1 = (Get-FileHash -Algorithm SHA256 -LiteralPath $Zip1).Hash.ToLowerInvariant()
AssertMatches $m1 ([regex]::Escape($expected1)) 'the manifest hash is the real digest of the archive'

# ---------------------------------------------------------------------
Step 'make the published bucket a git repository (what a bucket IS)'
# ---------------------------------------------------------------------
$BucketDir = Join-Path $Www 'scoop'
Push-Location $BucketDir
& git init -q 2>&1 | Out-Null
& git config user.email 'm3-gate@reprobuild.invalid' | Out-Null
& git config user.name 'M3 Gate' | Out-Null
& git add -A 2>&1 | Out-Null
& git -c commit.gpgsign=false commit -q -m "reprobuild $V1" 2>&1 | Out-Null
$headOk = (& git rev-parse --short HEAD 2>&1)
Pop-Location
AssertMatches "$headOk" '^[0-9a-f]{7,}$' 'the bucket is a git repo with a commit'

# ---------------------------------------------------------------------
Step 'serve the download surface over local HTTP (stands in for R2)'
# ---------------------------------------------------------------------
$psi = New-Object System.Diagnostics.ProcessStartInfo
$psi.FileName = (Get-Command $Py).Source
$psi.Arguments = "-m http.server $Port --bind 127.0.0.1"
$psi.WorkingDirectory = $Www
$psi.UseShellExecute = $false
$psi.RedirectStandardOutput = $true
$psi.RedirectStandardError = $true
$script:HttpProc = [System.Diagnostics.Process]::Start($psi)
$served = $false
for ($i = 0; $i -lt 50; $i++) {
  try {
    Invoke-WebRequest -Uri "$Base/downloads/v$V1/reprobuild-$V1-windows-x86_64.zip" -UseBasicParsing -Method Head -TimeoutSec 3 | Out-Null
    $served = $true; break
  } catch { Start-Sleep -Milliseconds 200 }
}
if ($served) { Ok "local HTTP server serves the archive over $Base" } else { Bad "local HTTP server did not serve $Base" }

# =====================================================================
Step "S1  the installer registers a bucket and Scoop installs $V1"
# =====================================================================
$s1 = & pwsh -NoProfile -File $InstallPs1 -Method scoop -BaseUrl $Base -BucketUrl ($BucketDir -replace '\\','/') 2>&1 | Out-String
$S1_RC = $LASTEXITCODE
Write-Host $s1
AssertEq $S1_RC 0 'S1 installer exited 0'
AssertMatches $s1 "registering scoop bucket" 'S1 the installer registered the bucket'
$buckets = @(Get-ChildItem -LiteralPath (Join-Path $ScoopRoot 'buckets') -Directory -ErrorAction SilentlyContinue | ForEach-Object { $_.Name })
AssertEq ($buckets -contains $BucketName) 'True' 'S1 the bucket is registered in the scratch Scoop root'
$appDir = Join-Path $ScoopRoot "apps\$AppName\current"
AssertFile $appDir 'S1 the app directory exists'
AssertFile (Join-Path $appDir 'bin\repro.exe') 'S1 the payload landed'
function Get-InstalledVersion {
  $p = Join-Path $ScoopRoot "apps\$AppName\current\bin\repro-version.txt"
  if (Test-Path -LiteralPath $p) { return (Get-Content -LiteralPath $p -Raw).Trim() }
  return ''
}
AssertEq (Get-InstalledVersion) $V1 "S1 the INSTALLED PAYLOAD reports $V1"
# Scoop's own view of what it installed.
$list1 = (& scoop list *>&1 | Out-String)
AssertMatches $list1 ([regex]::Escape($V1)) "S1 scoop list reports $V1"

# =====================================================================
Step 'S2  IDEMPOTENCE: a second identical run changes nothing (measured)'
# =====================================================================
$beforeBuckets = @(Get-ChildItem -LiteralPath (Join-Path $ScoopRoot 'buckets') -Directory).Count
$beforeApps = @(Get-ChildItem -LiteralPath (Join-Path $ScoopRoot 'apps') -Directory).Count
$beforeVersionDirs = @(Get-ChildItem -LiteralPath (Join-Path $ScoopRoot "apps\$AppName") -Directory).Count
$beforeVersion = Get-InstalledVersion

$s2 = & pwsh -NoProfile -File $InstallPs1 -Method scoop -BaseUrl $Base -BucketUrl ($BucketDir -replace '\\','/') 2>&1 | Out-String
$S2_RC = $LASTEXITCODE
Write-Host $s2
# VACUITY: "nothing changed" is trivially true of a run that crashed, so
# the exit code is asserted to be 0 first.
AssertEq $S2_RC 0 'S2 second run exited 0 (so "no change" is not "it crashed")'
AssertMatches $s2 'already registered' 'S2 the installer detected the existing bucket instead of re-adding it'
AssertEq @(Get-ChildItem -LiteralPath (Join-Path $ScoopRoot 'buckets') -Directory).Count $beforeBuckets 'S2 bucket count unchanged'
# TWO buckets exist by design: the empty placeholder 'main' that Scoop's
# maintenance pass requires, plus ours. What idempotence means here is
# exactly ONE 'reprobuild' bucket, not one bucket in total.
AssertEq @(Get-ChildItem -LiteralPath (Join-Path $ScoopRoot 'buckets') -Directory |
             Where-Object { $_.Name -eq $BucketName }).Count 1 'S2 exactly ONE reprobuild bucket'
AssertEq @(Get-ChildItem -LiteralPath (Join-Path $ScoopRoot 'apps') -Directory).Count $beforeApps 'S2 app count unchanged'
AssertEq @(Get-ChildItem -LiteralPath (Join-Path $ScoopRoot "apps\$AppName") -Directory).Count $beforeVersionDirs 'S2 no extra app version directory'
AssertEq (Get-InstalledVersion) $beforeVersion 'S2 installed payload version unchanged'
AssertMatches $s2 "already installed|is already installed" 'S2 scoop itself said it was already installed'

# =====================================================================
Step "S3  publish $V2 into the bucket; Scoop then reports an update"
# =====================================================================
$pub2 = Invoke-PublishScoop -Ver $V2 -PkgDir (Join-Path $WorkRoot "pkgs-$V2") -RepoRootDir (Join-Path $WorkRoot 'repo2')
Write-Host $pub2
$m2 = Get-Content -LiteralPath $ManifestPath -Raw
AssertMatches $m2 '"version":\s*"0\.1\.4"' 'S3 the published manifest now declares 0.1.4'
$expected2 = (Get-FileHash -Algorithm SHA256 -LiteralPath $Zip2).Hash.ToLowerInvariant()
AssertMatches $m2 ([regex]::Escape($expected2)) 'S3 the manifest hash is the real digest of the NEW archive'

Push-Location $BucketDir
& git add -A 2>&1 | Out-Null
& git -c commit.gpgsign=false commit -q -m "reprobuild $V2" 2>&1 | Out-Null
$srcHead = (& git rev-parse HEAD 2>&1).Trim()
Pop-Location

# A bucket is a git repo and Scoop keeps a CLONE of it under
# $SCOOP/buckets/<name>; refreshing manifests means pulling that clone,
# which is literally what `scoop update` does for buckets.
#
# `scoop update` with no arguments is NOT used here: it also updates
# Scoop ITSELF, and in a redirected $SCOOP root it tries to relocate the
# Scoop installation into the scratch root and fails with
# "Failed to remove local 'main' bucket". The git pull below is the
# bucket half of that command, done directly. The UPGRADE itself (S4)
# remains `scoop update reprobuild` -- Scoop's own action -- which is the
# part that has to be Scoop's rather than ours.
$BucketClone = Join-Path $ScoopRoot "buckets\$BucketName"
AssertFile $BucketClone 'S3 Scoop keeps a clone of the bucket'
Push-Location $BucketClone
& git -c protocol.file.allow=always pull --no-rebase -q 2>&1 | Out-Null
$cloneHead = (& git rev-parse HEAD 2>&1).Trim()
Pop-Location
# The refresh must actually have advanced the clone, or S3/S4 would be
# testing the OLD manifest and S4's "no upgrade offered" would be
# indistinguishable from a broken pull.
AssertEq $cloneHead $srcHead 'S3 the bucket clone advanced to the new commit'
$cloneManifest = Get-Content -LiteralPath (Join-Path $BucketClone 'bucket\reprobuild.json') -Raw
AssertMatches $cloneManifest '"version":\s*"0\.1\.4"' 'S3 the CLONE now carries the 0.1.4 manifest'

$status = (& scoop status *>&1 | Out-String)
Write-Host $status
AssertMatches $status ([regex]::Escape($AppName)) 'S3 scoop status names reprobuild'
AssertMatches $status ([regex]::Escape($V2)) "S3 scoop status offers $V2"

# =====================================================================
Step "S4  scoop update MOVES the box from $V1 to $V2"
# =====================================================================
# VACUITY, the important one: a TRANSITION, not a first install. $V1 is
# asserted installed immediately before, the upgrade is SCOOP's own
# command with no installer involvement, and $V2 is asserted after.
AssertEq (Get-InstalledVersion) $V1 "S4 precondition: $V1 installed before the update"
$s4 = (& scoop update $AppName *>&1 | Out-String)
$S4_RC = $LASTEXITCODE
Write-Host $s4
AssertEq $S4_RC 0 'S4 scoop update exited 0'
AssertMatches $s4 "$([regex]::Escape($V1)).*$([regex]::Escape($V2))|Updating.*$([regex]::Escape($AppName))" 'S4 scoop reported the update transaction'
AssertEq (Get-InstalledVersion) $V2 "S4 the INSTALLED PAYLOAD now reports $V2"
$list2 = (& scoop list *>&1 | Out-String)
AssertMatches $list2 ([regex]::Escape($V2)) "S4 scoop list now reports $V2"

# =====================================================================
Step "S5  a TAMPERED archive is REJECTED by Scoop's own hash check"
# =====================================================================
# Same-size, in-place mutation, so nothing but the hash can fire.
# Derived from the manifest Scoop will actually use, so this step cannot
# end up tampering a file that is not in the install path. (It did, once:
# S4 had left 0.1.3 installed while this tampered 0.1.4, and `scoop
# install` then succeeded on an untouched archive.)
$liveManifest = Get-Content -LiteralPath (Join-Path $BucketClone 'bucket\reprobuild.json') -Raw | ConvertFrom-Json
$liveUrl = $liveManifest.architecture.'64bit'.url
AssertMatches $liveUrl '^http://127\.0\.0\.1:' 'S5 the manifest URL points at the local server'
$liveRel = ($liveUrl -replace '^http://127\.0\.0\.1:\d+/', '') -replace '/', '\'
$targetZip = Join-Path $Www $liveRel
AssertFile $targetZip 'S5 the artifact the manifest points at exists on the server'
Copy-Item -LiteralPath $targetZip -Destination (Join-Path $WorkRoot 'pristine-v2.zip') -Force
$sizeBefore = (Get-Item -LiteralPath $targetZip).Length
$bytes = [System.IO.File]::ReadAllBytes($targetZip)
$off = [int]($bytes.Length / 2)
for ($i = 0; $i -lt 8; $i++) { $bytes[$off + $i] = $bytes[$off + $i] -bxor 0xFF }
[System.IO.File]::WriteAllBytes($targetZip, $bytes)
AssertEq (Get-Item -LiteralPath $targetZip).Length $sizeBefore 'S5 the tampered archive has the SAME byte size'
AssertNe (Get-FileHash -Algorithm SHA256 -LiteralPath $targetZip).Hash `
         (Get-FileHash -Algorithm SHA256 -LiteralPath (Join-Path $WorkRoot 'pristine-v2.zip')).Hash `
         'S5 the tampered archive does differ in content'

# Remove the app and its cached download, so the tampered bytes are the
# ones Scoop actually fetches. Without clearing the cache this step would
# "pass" by reinstalling the cached GOOD archive.
& scoop uninstall $AppName 6>$null 2>$null | Out-Null
& scoop cache rm $AppName 6>$null 2>$null | Out-Null
$cacheDir = Join-Path $ScoopRoot 'cache'
if (Test-Path -LiteralPath $cacheDir) {
  Get-ChildItem -LiteralPath $cacheDir -Filter "*$AppName*" -ErrorAction SilentlyContinue | Remove-Item -Force -ErrorAction SilentlyContinue
}
AssertEq @(Get-ChildItem -LiteralPath $cacheDir -Filter "*$AppName*" -ErrorAction SilentlyContinue).Count 0 `
  'S5 the Scoop download cache holds no reprobuild archive (so the tampered bytes are fetched)'

$s5 = (& scoop install "$BucketName/$AppName" *>&1 | Out-String)
$S5_RC = $LASTEXITCODE
Write-Host $s5
AssertNe $S5_RC 0 'S5 scoop install exited non-zero on the tampered archive'
AssertMatches $s5 "hash check failed|Hash check failed|doesn't match|does not match" `
  "S5 scoop reported a HASH CHECK FAILURE in its own words"
AssertAbsent (Join-Path $ScoopRoot "apps\$AppName\current\bin\repro.exe") 'S5 nothing was installed from the tampered archive'

# N0 control: restore the genuine archive; the SAME manifest and URL must
# now install. Without this, S5 could be passing because the download or
# the bucket was broken rather than because the hash was checked.
Copy-Item -LiteralPath (Join-Path $WorkRoot 'pristine-v2.zip') -Destination $targetZip -Force
$n0 = (& scoop install "$BucketName/$AppName" *>&1 | Out-String)
$N0_RC = $LASTEXITCODE
Write-Host $n0
AssertEq $N0_RC 0 'N0 the GENUINE archive installs from the same manifest and URL'
AssertEq (Get-InstalledVersion) $V2 "N0 the restored install reports $V2"

# =====================================================================
Step 'S6  -Uninstall leaves no app and no bucket'
# =====================================================================
AssertFile (Join-Path $ScoopRoot "apps\$AppName\current\bin\repro.exe") 'S6 precondition: the app is installed'
$s6 = & pwsh -NoProfile -File $InstallPs1 -Method scoop -BaseUrl $Base -Uninstall 2>&1 | Out-String
$S6_RC = $LASTEXITCODE
Write-Host $s6
AssertEq $S6_RC 0 'S6 uninstaller exited 0'
AssertAbsent (Join-Path $ScoopRoot "apps\$AppName") 'S6 the Scoop app directory'
$bucketsAfter = @(Get-ChildItem -LiteralPath (Join-Path $ScoopRoot 'buckets') -Directory -ErrorAction SilentlyContinue | ForEach-Object { $_.Name })
AssertEq ($bucketsAfter -contains $BucketName) 'False' 'S6 the Scoop bucket is deregistered'

$s6b = & pwsh -NoProfile -File $InstallPs1 -Method scoop -BaseUrl $Base -Uninstall 2>&1 | Out-String
AssertEq $LASTEXITCODE 0 'S6 a SECOND uninstall is a no-op, not an error'

