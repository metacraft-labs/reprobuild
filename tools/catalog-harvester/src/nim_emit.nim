## Deterministic emitter for the catalog harvester (GM4b).
##
## The harvester's parsers (``manifest_parser``, ``msys2_source``,
## ``gh_releases_source``) translate an upstream description into a
## ``VersionedProvisioning`` value — an in-memory parse model that is never
## persisted and never consulted for resolution. This module renders that
## model as what the engine actually resolves: ``tarball`` realizations of a
## package (Provisioning-Contributions.md §"Profile Package References").
##
## Two output shapes share one statement emitter:
##
## * ``emitPackageModule`` — the package module for a NEW tool:
##
##   .. code-block:: nim
##      ## Auto-generated by tools/catalog-harvester. DO NOT EDIT.
##      ## Harvested from bucket: scoopinstaller/main
##      ## Versions (default first): 1.2.0, 1.1.0
##
##      import repro_project_dsl
##      import repro_dsl_stdlib/packages_schema
##
##      package hello:
##        provisioning:
##          tarball url = "https://example.test/hello-1.2.0.zip",
##            sha256 = "…",
##            archiveType = "zip",
##            executablePath = "hello.exe",
##            version = "1.2.0",
##            packageId = "hello@1.2.0",
##            os = "windows"
##
##   For an EXISTING stdlib package, paste the emitted ``tarball``
##   statements into its ``provisioning:`` block after the statements it
##   already has: an unpinned reference takes the first eligible
##   realization in declaration order, so placement decides the default.
##
## * ``emitContributionModule`` — a ``provisioningFor`` contribution for a
##   package owned elsewhere (``--contributor``), pinned by
##   ``interfaceFingerprint`` or, when none is known, ``developInterface``
##   (which a published catalog must replace — §"Authoring Surface").
##
## Determinism (the idempotence gate): versions in the order given (the
## harvester sorts newest-first, so the newest is the default), arms in
## declaration order, ``env`` sorted by name, no timestamp or commit id.

import std/[algorithm, strutils, tables]
import repro_dsl_stdlib/packages_schema
import repro_project_dsl/selector_names

const Header = "## Auto-generated by tools/catalog-harvester. DO NOT EDIT.\n"

type EmitError* = object of ValueError
  ## An arm the DSL cannot express (e.g. a 32-bit x86 coordinate). Refused
  ## rather than emitted as text that would fail to compile later.

proc lit(s: string): string = s.escape()

proc packageNameSyntax(toolName: string): string =
  ## How ``package`` spells ``toolName``: bare when it is a Nim identifier
  ## (``package hello:``), else as a string (``package "7zip":``,
  ## ``package "nil":``), the form the macro accepts for any package name
  ## (Package-Model.md §"Package names"). ``isNimIdentifier`` decides, so a
  ## keyword — which ``strutils.validIdentifier`` accepts — is quoted.
  if toolName.isNimIdentifier: toolName else: lit(toolName)

proc harvestModuleName*(toolName: string): string =
  ## The basename (without ``.nim``) of the module written for ``toolName``.
  ## A Nim identifier names its own module, as it always has; any other name
  ## goes through ``selectorModuleName``, the mapping ``usesImportCode``
  ## imports a selector's stdlib module by (``7zip`` -> ``pkg_7zip``,
  ## ``nil`` -> ``pkg_nil``: a module named by a keyword cannot be imported).
  if toolName.isNimIdentifier: toolName else: selectorModuleName(toolName)

proc cpuToken(cpu: PlatformCpu): string =
  case cpu
  of pcAny: ""
  of pcX86_64: "x86_64"
  of pcAArch64: "aarch64"
  # The schema's own spelling (`PlatformCpu`'s string value), which
  # `parsePlatformCpuToken` reads back: the emitted statement round-trips.
  of pcArmv7: "armv7"
  of pcX86:
    raise newException(EmitError, "a 32-bit x86 arm cannot be expressed " &
      "as a tarball realization (cpu must be any, x86_64, aarch64 or armv7)")

proc osToken(os: PlatformOs): string =
  case os
  of poAny: ""
  of poWindows: "windows"
  of poLinux: "linux"
  of poMacos: "macos"

proc tarballStatement*(toolName: string; vp: VersionedProvisioning;
                       pb: PlatformBinary): string =
  ## One ``tarball`` statement (indented for a ``provisioning:`` block
  ## body, 4 spaces; continuation lines 6) for one (version, arm).
  var args: seq[string] = @[]
  args.add("url = " & lit(pb.url))
  # Exactly one digest, in verification precedence.
  if pb.sha256.len > 0: args.add("sha256 = " & lit(pb.sha256))
  elif pb.sha512.len > 0: args.add("sha512 = " & lit(pb.sha512))
  elif pb.sha1.len > 0: args.add("sha1 = " & lit(pb.sha1))
  let format =
    if pb.has_archive_format_override: pb.archive_format_override
    else: vp.archive_format
  args.add("archiveType = " & lit($format))
  let bins =
    if pb.bin_relpath_override.len > 0: pb.bin_relpath_override
    else: vp.bin_relpath
  if bins.len == 0:
    raise newException(EmitError, toolName & " " & vp.version &
      ": no executable path (bin_relpath is empty); pass --bin-default")
  args.add("executablePath = " & lit(bins[0]))
  for extra in bins[1 .. ^1]:
    args.add("extraExecutable = " & lit(extra))
  args.add("version = " & lit(vp.version))
  args.add("packageId = " & lit(toolName & "@" & vp.version))
  if vp.install_method != imExtract:
    args.add("installMethod = " & lit($vp.install_method))
  if pb.extract_path.len > 0:
    args.add("extractPath = " & lit(pb.extract_path))
  for a in vp.installer_args: args.add("installerArg = " & lit(a))
  for p in vp.pacman_packages: args.add("pacmanPackage = " & lit(p))
  for b in vp.bootstrap_argv: args.add("bootstrapArg = " & lit(b))
  var keys: seq[string] = @[]
  for k in vp.env.keys: keys.add(k)
  keys.sort()
  for k in keys: args.add("env = " & lit(k & "=" & vp.env[k]))
  if pb.nested_7z: args.add("nested7z = true")
  if pb.msi_admin_install: args.add("msiAdminInstall = true")
  for action in vp.pre_install_actions:
    args.add("preInstall = preInstallAction(" & lit($action.kind) & ", " &
      lit(action.source) & ", " & lit(action.target) & ", " &
      $action.recurse & ", " & lit(action.literal) & ")")
  for line in vp.pre_install_unrecognized:
    args.add("preInstallUnrecognized = " & lit(line))
  for spec in vp.launcher_emit:
    args.add("launcherEmit = launcherEmitSpec(" & lit($spec.kind) & ", " &
      lit(spec.target) & ", " & lit(spec.interpreter_package_id) & ", " &
      lit(spec.launcher_name) & ")")
  let cpu = cpuToken(pb.cpu)
  if cpu.len > 0: args.add("cpu = " & lit(cpu))
  let os = osToken(pb.os)
  if os.len > 0: args.add("os = " & lit(os))
  if pb.cpu_level != mlNone: args.add("cpuLevel = " & lit($pb.cpu_level))
  if pb.cpu_features != {}:
    args.add("cpuFeatures = " & lit(renderCpuFeatureTokens(pb.cpu_features)))
  result = "    tarball " & args[0]
  for a in args[1 .. ^1]:
    result.add(",\n      " & a)
  result.add("\n")

proc tarballStatements*(toolName: string;
                        catalog: openArray[VersionedProvisioning]): string =
  ## Every (version, arm) of ``catalog`` as ``tarball`` statements, in
  ## catalog order then arm order.
  for vp in catalog:
    for pb in vp.platforms:
      result.add(tarballStatement(toolName, vp, pb))

proc moduleHeader(bucketSpec: string;
                  catalog: openArray[VersionedProvisioning]): string =
  result = Header
  result.add("## Harvested from bucket: " & bucketSpec & "\n")
  if catalog.len > 0:
    var versions: seq[string] = @[]
    for vp in catalog: versions.add(vp.version)
    result.add("## Versions (default first): " & versions.join(", ") & "\n")

const Imports = "import repro_project_dsl\n" &
  "import repro_dsl_stdlib/packages_schema\n"

proc emitPackageModule*(toolName: string; bucketSpec: string;
                        catalog: openArray[VersionedProvisioning]): string =
  ## The ``packages/<tool>.nim`` module for a new tool: a ``package`` block
  ## whose ``provisioning:`` carries the harvested ``tarball`` realizations.
  result = moduleHeader(bucketSpec, catalog)
  result.add("\n" & Imports & "\n")
  result.add("package " & packageNameSyntax(toolName) & ":\n")
  result.add("  provisioning:\n")
  result.add(tarballStatements(toolName, catalog))

proc emitContributionModule*(toolName, bucketSpec, contributor,
                             interfaceFingerprint: string;
                             catalog: openArray[VersionedProvisioning]):
    string =
  ## A ``provisioningFor`` contribution of the harvested realizations to a
  ## package owned elsewhere. Without a fingerprint the contribution binds
  ## through ``developInterface``, which a published catalog must replace.
  result = moduleHeader(bucketSpec, catalog)
  if interfaceFingerprint.len == 0:
    result.add("## developInterface binds to the interface of the active " &
      "develop checkout;\n## a published catalog must replace it with " &
      "`interfaceFingerprint \"<hex>\"`\n## (Provisioning-Contributions.md " &
      "§Authoring Surface).\n")
  result.add("\n" & Imports & "\n")
  result.add("provisioningFor " & lit(toolName) & ":\n")
  if interfaceFingerprint.len > 0:
    result.add("  interfaceFingerprint " & lit(interfaceFingerprint) & "\n")
  else:
    result.add("  developInterface\n")
  result.add("  contributor " & lit(contributor) & "\n")
  # The statement emitter indents for a `provisioning:` body (4 spaces);
  # a provisioningFor body is one level shallower.
  for line in tarballStatements(toolName, catalog).splitLines:
    if line.len > 0:
      result.add(line[2 .. ^1] & "\n")

proc emitHarvestModule*(toolName, bucketSpec, contributor,
                        interfaceFingerprint: string;
                        catalog: openArray[VersionedProvisioning]): string =
  ## The CLI's emit entry point: a package module, or a contribution when
  ## ``contributor`` is set.
  if contributor.len > 0:
    emitContributionModule(toolName, bucketSpec, contributor,
      interfaceFingerprint, catalog)
  else:
    emitPackageModule(toolName, bucketSpec, catalog)
