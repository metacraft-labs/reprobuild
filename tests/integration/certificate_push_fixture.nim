## Shared fixture for the tests of certificate propagation through the managed
## ``pre-push`` hook: the REAL generated hooks on a real clone pushing to a real
## bare, with the reference library linked into the build under test.
##
## ``include``d, not a registered test. It includes ``tc8c_store_fixture``, so
## the store roots already point at the fixture's scratch directory, and a
## ``git push`` the fixture runs gets them through the environment.
##
## Every push runs with no ``test-certificates`` executable on ``PATH``: the
## linked library has to do the work, and a run on a machine that has the tool
## installed cannot pass because of it.

include tc8c_store_fixture

proc pathWithoutTool(): string =
  var kept: seq[string]
  for dir in getEnv("PATH").split(PathSep):
    if dir.len > 0 and
        not fileExists(dir / addFileExt("test-certificates", ExeExt)):
      kept.add(dir)
  kept.join($PathSep)

proc installHooks(fx: StoreFixture) =
  ## The real managed hooks, generated by the build under test, which also
  ## services them for the rest of this test process: a commit fires them too.
  putEnv("REPROBUILD_REPRO", fx.reproBin)
  let res = runArgv(@[fx.reproBin, "hooks", "ensure", "--vcs", fx.libAPath],
    env = @[(name: "REPROBUILD_REPRO", value: fx.reproBin)])
  doAssert res.code == 0, "hooks ensure failed:\n" & res.output

proc plainPush(fx: StoreFixture; args: seq[string] = @["main"];
               env: seq[tuple[name, value: string]] = @[]):
    tuple[code: int; output: string] =
  ## A plain ``git push origin <args>``: the managed hook runs.
  runArgv(@["git", "-C", fx.libAPath, "push", "origin"] & args,
    env = @[(name: "PATH", value: pathWithoutTool()),
            (name: "REPROBUILD_REPRO", value: fx.reproBin)] & env)

proc storeCertificateFor(fx: StoreFixture; commit: string) =
  ## Put a signed certificate for ``commit``'s tree in the local store: all a
  ## producer does. Nothing here writes a note.
  let cert = signedCertFor(fx, "git-tree-sha1:" & gitOut(fx.libAPath,
    "rev-parse", commit & "^{tree}"), commit)
  doAssert publishCertificateToLocalStore(cert, fx.libAPath).written

proc noteOnRemote(bare, annotated: string): string =
  ## The note on ``annotated`` in ``bare``'s certificate notes ref, or "".
  let res = execCmdEx(quoteShellCommand(@["git", "-C", bare, "notes", "--ref",
    certificateNotesRef, "show", annotated]))
  if res.exitCode == 0: res.output else: ""

proc remoteHasNotes(bare: string): bool =
  execCmdEx(quoteShellCommand(@["git", "-C", bare, "rev-parse", "--verify",
    "--quiet", certificateNotesRef])).exitCode == 0

proc installRemoteHook(fx: StoreFixture; body: string) =
  ## A real ``pre-receive`` on the receiving repository.
  let hook = fx.upstreamBare / "hooks" / "pre-receive"
  writeFile(hook, "#!/bin/sh\n" & body)
  setFilePermissions(hook, {fpUserRead, fpUserWrite, fpUserExec})
