## One machine, five power cycles, and what its TPM would and would not
## release.
##
## ## How these were taken
##
## `attested_boot/take-sealed-state-evidence.sh` built three unified
## kernel images, created two LUKS2 volumes inside a transient QEMU guest
## with a key drawn from the guest kernel's RNG, sealed that key to the
## register the stub measured the image into, and then power cycled the
## same machine four more times — twice on the same image, once on a
## second generation it had re-sealed for in advance, and once on an
## image whose kernel command line differs by ONE CHARACTER.
##
## The software TPM's state directory, the UEFI variable store and both
## block devices persist across all five cycles. Each cycle is a separate
## firmware start, so every register is re-extended from its reset value
## and nothing survives except what is on a disk or inside the TPM.
##
## Everything below is what that machine produced. No value here was
## computed by this repository and then written down as if a machine had
## said it.
##
## ## What the constants are
##
## | constant | what it is |
## |---|---|
## | `SealedState*Template` | the sections a stub measures, as digests |
## | `SealedState*PredictedPcr11` | what the image bytes say register 11 will hold |
## | `SealedStateSeal?PublicHex` | the sealed object's `TPM2B_PUBLIC` |
## | `SealedStateSeal?NameHex` | that object's `TPM2B_NAME`, as the TPM wrote it |
## | `SealedStateSeal?PolicyHex` | the policy digest the TPM's own trial session computed |
## | `SealedState*EventLogHex` | the TCG event log THAT boot's firmware wrote |
## | `SealedState*Report` | the guest's own account of each cycle |
##
## ## PIN THE PUBLIC AREA WITH THE NAME
##
## The name and the public area check each other: the name is
## `nameAlg ‖ H(TPMT_PUBLIC)`, so a typo in either is caught by the
## other. A public area pinned alone would be a byte string nothing
## contradicts. This is the same discipline `attested_boot_vectors`
## records for an attestation key, arriving at a different structure.
##
## The policy digest is pinned separately from the public area that
## carries it for the same reason, and it is a stronger check than it
## looks: the TPM computed it in a trial session, and the public area is
## what it then sealed under. Two artifacts, one number, produced by two
## different commands.
##
## ## WHAT IS NOT PINNED, AND WHY
##
## **No key material appears here.** The volume key existed only inside
## the guest and inside the sealed objects, which are ciphertext under a
## TPM-held parent. The markers are 32 random bytes written in PLAINTEXT
## to the front of each opened volume so that a later cycle can prove it
## opened the same volume — they are a marker, not a secret, and they are
## useless to anyone who does not already have the key.
##
## The sealed objects' PRIVATE areas are not pinned either. They are
## encrypted to a parent this TPM destroyed with the guest, so they would
## be unusable bytes, and the public area is where the policy lives.
##
## ## What is reproducible, and what is not
##
## The three images are a function of their inputs and nothing else: the
## harness fixes every mtime in the initramfs and sorts its member list.
## A SECOND, INDEPENDENT run of the whole experiment rebuilt all three,
## and the one image both runs PINNED — the tampered one — carries the
## same digest in both, which the third gate checks. The other two
## generations' digests from that second run were observed to agree but
## are not pinned here, so reproducibility is RECORDED for one image of
## the three and ASSERTED for none of the others.
##
## What licenses reading `.cmdline` as the only difference between them is
## therefore not that observation but the templates themselves: five of
## the six measured section digests are byte-identical across all three,
## and two gates check exactly that.
##
## The TPM is not reproducible: a fresh run creates a fresh primary seed,
## so the sealed objects and their names differ on every run. What does
## not differ is the POLICY DIGEST, because it is a function of the image
## alone — and that is the whole point of the arrangement rather than an
## incidental property of it.
##
## ## The negative control is a REAL BOOT, not a construction
##
## `UnlockedDespiteRefusalTamperReport` comes from a second full run of
## the same harness with `SEAL_RECOVERY_FALLBACK=1`, which enrols a
## recovery key slot and falls back to it when the TPM refuses. It is the
## vulnerability in evidence form: the TPM refused with the SAME code, on
## the SAME tampered image (the digests are identical, and both are
## pinned), and the volumes opened anyway and the markers are readable.
##
## It exists because "the unseal failed" and "the volumes stayed locked"
## are two questions, and a gate that asked only one of them would pass
## on this report. Both halves are checked against it: the refusal half
## must still be TRUE, and the locked half must be FALSE.
##
## ## Mocking
##
## None. Every byte here came off a machine.

