## The ``.envrc`` block ``repro hooks ensure --shell-direnv`` generates does
## not run ``repro hooks ensure``, and a block an older build wrote (which
## did) is replaced by the next ``ensure --shell-direnv``.
##
## Recorded in reprobuild-pm
## ``issues/2026-11-12-ambient-hooks-ensure-is-declared-safe-even-though-it-is-the-documented-self-concealing.md``;
## the contract is reprobuild-pm ``spec/CLI/hooks.md`` §"Direnv Integration"
## (amended 2026-11-16).
##
## Why. The block used to run ``"$repro_cmd" hooks ensure --vcs "$PWD"
## >/dev/null 2>&1 || true`` on every directory entry: output discarded,
## failure swallowed, from whichever ``repro`` that shell resolved. That is the
## one command whose refusals report a hook-contract mismatch, run where nobody
## can read them -- and, before ``ensure`` learned to refuse a body whose
## contract it does not generate, the command that re-authored current hooks
## with a stale shell's older body.
##
## Arms:
##   (A) A fresh block still activates the dev environment and does not call
##       ``hooks ensure`` in any form.
##   (B) A block carrying the old line, as an earlier build wrote it, is
##       rewritten to the current block by the next ``ensure --shell-direnv``;
##       the user's bytes outside the block are kept.
##
## No stub: the real built ``repro`` writes the real ``.envrc``. The old block
## is the current block with the removed line put back in its old place, which
## is the only difference between the two generations.
##
## Hermetic: one ``createTempDir``; nothing is activated, so neither direnv nor
## a dev environment is needed.

import std/[os, osproc, strutils, tempfiles, unittest]

import repro_test_support

proc repoRoot(): string =
  currentSourcePath().parentDir.parentDir.parentDir

proc reproBinary(): string =
  requireBinary(repoRoot() / "build" / "bin" / addFileExt("repro", ExeExt),
    "reprobuild.apps.repro")

const
  legacyLine =
    "  \"$repro_cmd\" hooks ensure --vcs \"$PWD\" >/dev/null 2>&1 || true\n"
  # The line the legacy call followed in every generation that carried it.
  legacyAnchor = "  local repro_status=0\n"
  userBytes = "export USER_OWNED=1\n"

suite "the generated .envrc block never runs hooks ensure":

  test "a fresh block activates without hooks ensure, and an old block is replaced":
    let scratch = createTempDir("repro-envrc-no-ensure-", "")
    defer: removeDir(scratch)
    let project = scratch / "project"
    createDir(project)
    let envrc = project / ".envrc"
    writeFile(envrc, userBytes)

    let ensured = runShell(shellCommand(@[reproBinary(), "hooks", "ensure",
      "--shell-direnv", project]))
    checkpoint("ensure --shell-direnv:\n" & ensured.output)
    check ensured.code == 0

    # ---- (A) --------------------------------------------------------------
    let fresh = readFile(envrc)
    checkpoint(".envrc:\n" & fresh)
    check "repro-managed:repro-dev-env-direnv" in fresh
    check "__repro-direnv-activate" in fresh
    check "hooks ensure" notin fresh.replace(
      "# Generated by repro hooks ensure --shell-direnv.", "")
    check legacyLine notin fresh
    check fresh.startsWith(userBytes)

    # ---- (B) --------------------------------------------------------------
    check legacyAnchor in fresh
    let old = fresh.replace(legacyAnchor, legacyLine & legacyAnchor)
    check old != fresh
    writeFile(envrc, old)
    let replaced = runShell(shellCommand(@[reproBinary(), "hooks", "ensure",
      "--shell-direnv", project]))
    checkpoint("ensure --shell-direnv over an old block:\n" & replaced.output)
    check replaced.code == 0
    check readFile(envrc) == fresh
