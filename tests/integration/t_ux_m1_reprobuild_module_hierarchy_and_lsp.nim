## The canonical ``reprobuild`` import tree resolves through ``--path`` alone,
## under the real compiler and the real ``nimsuggest``.
##
## WHAT IS UNDER TEST. A recipe names its DSL with an ordinary import --
## ``import reprobuild``, ``reprobuild/dsl``, ``reprobuild/dsl/<module>``,
## ``reprobuild/home``, ``reprobuild/system`` -- and the older names
## (``repro_project_dsl``, ``repro_dsl_stdlib[/...]``) keep working as
## re-exports of the same symbols. Editor tooling must open such a recipe COLD
## (no Reprobuild-specific flags, only a ``--path`` set in a config file) and:
##
##   * report zero errors and zero ``[UnusedImport]`` warnings, even with
##     ``--warningAsError[UnusedImport]:on``;
##   * resolve ``def`` on DSL symbols to their single definition;
##   * leave an application's own ``src/main.nim`` -- which defines its own
##     ``let package = ...`` -- untouched by the DSL vocabulary.
##
## The ``--path`` set written into each fixture's ``nim.cfg`` is not
## hand-assembled: it is ``consumerCompilePathFlags``, the flag set the engine
## itself uses for the interface-extraction and provider compiles of a recipe
## outside this repository. So the test also proves that that set reaches the
## new tree, and that it carries only ``--path`` (plus C/link flags) -- never
## ``--import:`` or ``--include:``.
##
## THE NEGATIVE CONTROL. The obvious alternative -- a directory ``nim.cfg``
## with ``--import:reprobuild`` so recipes need no import line -- is exactly
## what this design rejects, because Nim applies ``--import:`` to every module
## of the compilation. The last suite writes that ``nim.cfg`` and asserts the
## same detectors the positive cases rely on now FIRE on ``src/main.nim``
## (``imported and not used: 'reprobuild' [UnusedImport]``), under both
## ``nim check`` and ``nimsuggest``. A detector that cannot fire would make
## every "zero findings" above vacuous; this proves it can.
##
## NO MOCKS. Every case runs the real ``nim`` on ``PATH`` and the real
## ``nimsuggest`` (the one installed beside that ``nim``, or ``$NIMSUGGEST``)
## against real fixture files and the real library tree. A missing
## ``nimsuggest`` is a failure with a remedy, not a skip: the property under
## test is editor behaviour, and no other tool can stand in for it.

