proc discoveryFlags(workDir: string): seq[string] =
  ## The engine's own consumer-compile flag set for a recipe in ``workDir``,
  ## with ``$REPROBUILD_LIBS_DIR`` naming THIS checkout's libraries (the
  ## operator override; without it a dev shell may point at a pinned
  ## snapshot that predates the tree under test).
  let saved = getEnv("REPROBUILD_LIBS_DIR")
  putEnv("REPROBUILD_LIBS_DIR", LibsRoot)
  try:
    result = consumerCompilePathFlags(workDir)
  finally:
    if saved.len > 0: putEnv("REPROBUILD_LIBS_DIR", saved)
    else: delEnv("REPROBUILD_LIBS_DIR")

proc nimCfgFor(flags: seq[string]): string =
  ## A project ``nim.cfg`` carrying the ``--path`` entries: what an editor
  ## needs to resolve the DSL. Quoted so a path with spaces survives. It also
  ## selects the full DSL (``ReproEvalModeFlag``): these fixtures use the
  ## engine's vocabulary, and without a mode define ``import reprobuild`` is
  ## the thin mode.
  result.add(ReproEvalModeFlag & "\n")
  for flag in flags:
    if flag.startsWith("--path:"):
      result.add("--path:\"" & flag["--path:".len .. ^1] & "\"\n")

const
  ReproRecipe = """import reprobuild

package hellodemo:
  build:
    discard writeText("build/greeting.txt", "hello")
"""
    ## Line 3 col 1 is ``package``; line 5 col 13 is ``writeText``.
  AppMain = """let package = "the application's own name"
echo package
"""
    ## Line 2 col 6 is the use of the application's ``package``.

proc writeProject(root, nimCfg: string) =
  createDir(root / "src")
  writeFile(root / "nim.cfg", nimCfg)
  writeFile(root / "repro.nim", ReproRecipe)
  writeFile(root / "src" / "main.nim", AppMain)

proc nimCheck(dir, file: string; extra: openArray[string] = []):
    tuple[output: string, exitCode: int] =
  ## ``nim check`` run FROM the project directory with no ``--path`` on the
  ## command line: everything must come from the project's ``nim.cfg``.
  var parts = @[nimExe().quoteShell, "check", "--hints:off",
    "--colors:off", ("--nimcache:" & dir / "nimcache" /
    file.splitFile.name).quoteShell]
  for e in extra: parts.add(e.quoteShell)
  parts.add(file.quoteShell)
  uncontrolledExecCmdEx(parts.join(" "), options = {poStdErrToStdOut},
    workingDir = dir)

proc nimsuggest(dir, project: string; queries: openArray[string]):
    tuple[output: string, exitCode: int] =
  ## A cold ``nimsuggest --v3 --tester`` session on ``project``, fed
  ## ``queries`` (``"<cmd> <line>:<col>"``, against ``project``) and ``quit``.
  let abs = dir / project
  var input = ""
  for q in queries:
    let parts = q.split(' ', 1)
    input.add(parts[0] & " " & abs & ":" & parts[1] & "\n")
  input.add("quit\n")
  let cmd = [nimsuggestExe().quoteShell, "--v3", "--tester",
    project.quoteShell].join(" ")
  uncontrolledExecCmdEx(cmd, options = {poStdErrToStdOut}, workingDir = dir,
    input = input)

proc samePath(a, b: string): bool =
  ## ``sameFile`` that answers ``false`` instead of raising when either side
  ## does not exist (a search-path list may name directories that do not).
  (fileExists(a) or dirExists(a)) and (fileExists(b) or dirExists(b)) and
    os.sameFile(a, b)

proc declaresAt(file: string; line: int; needle: string): bool =
  ## True when ``file``'s 1-based ``line`` contains ``needle``: the ``def``
  ## answer names the declaration, not merely some line of the right file.
  if not fileExists(file): return false
  let lines = readFile(file).splitLines
  line >= 1 and line <= lines.len and needle in lines[line - 1]

