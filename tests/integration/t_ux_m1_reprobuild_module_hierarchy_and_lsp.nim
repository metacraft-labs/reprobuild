proc nimExe(): string =
  result = uncontrolledFindExe("nim")
  if result.len == 0:
    raise newException(IOError, "no `nim` on PATH; run inside the dev shell")

proc nimsuggestExe(): string =
  ## ``$NIMSUGGEST``, else the ``nimsuggest`` that belongs to the ``nim`` on
  ## ``PATH`` (the toolchain ships it in ``libexec/`` beside ``bin/``, or in
  ## ``bin/`` itself), else one on ``PATH``. The first two keep the language
  ## server and the compiler on the same stdlib.
  let explicit = getEnv("NIMSUGGEST")
  if explicit.len > 0 and fileExists(explicit):
    return explicit
  let nimBin = expandFilename(nimExe()).parentDir
  for candidate in [nimBin.parentDir / "libexec" / "nimsuggest",
                    nimBin / "nimsuggest"]:
    if fileExists(candidate.addFileExt(ExeExt)):
      return candidate.addFileExt(ExeExt)
  result = uncontrolledFindExe("nimsuggest")
  if result.len == 0:
    raise newException(IOError,
      "no nimsuggest found (looked at $NIMSUGGEST, beside " & nimExe() &
      " and on PATH); set NIMSUGGEST to the nimsuggest of this Nim toolchain")

# ---------------------------------------------------------------------------
# Detectors. Every assertion about findings goes through these, and the
# negative control proves they fire.
# ---------------------------------------------------------------------------

proc unusedImportFindings(output: string): seq[string] =
  ## Every ``[UnusedImport]`` diagnostic, from ``nim check`` text or from
  ## ``nimsuggest`` ``chk`` records alike.
  output.splitLines.filterIt("[UnusedImport]" in it)

proc nimCheckErrors(output: string): seq[string] =
  output.splitLines.filterIt(" Error: " in it)

type SuggestRecord = object
  ## One tab-separated ``nimsuggest --v3`` answer line.
  command, symKind, qualifiedName, typ, file: string
  line, col: int
  severity: string  ## For ``chk``: ``Error`` / ``Warning`` / ``Hint``.

proc parseSuggest(output: string): seq[SuggestRecord] =
  ## ``nimsuggest`` answers: command, symkind, qualified name, type (for
  ## ``chk``: the severity), file, line, column, doc, quality. Lines that do
  ## not have that shape (``!EOF!`` separators, banners) are skipped.
  for line in output.splitLines:
    let f = line.split('\t')
    if f.len < 7 or f[0] notin ["chk", "def"]:
      continue
    var rec = SuggestRecord(command: f[0], symKind: f[1],
      qualifiedName: f[2], typ: f[3], file: f[4], severity: f[3])
    try:
      rec.line = parseInt(f[5])
      rec.col = parseInt(f[6])
    except ValueError:
      continue
    result.add(rec)

proc chkErrors(records: seq[SuggestRecord]): seq[SuggestRecord] =
  records.filterIt(it.command == "chk" and it.severity == "Error")

proc defs(records: seq[SuggestRecord]): seq[SuggestRecord] =
  records.filterIt(it.command == "def")

