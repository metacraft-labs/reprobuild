let scratch = createTempDir("reprobuild-imports-", "")
let flags = discoveryFlags(scratch / "project")
let pathCfg = nimCfgFor(flags)

suite "the reprobuild tree is discoverable through --path only":
  test "the repository's own compiles put libs/reprobuild/src on the search path":
    check CompileSearchPaths.anyIt(samePath(it, CanonicalSrc))

  test "the engine's consumer-compile flags carry the tree and no --import/--include":
    checkpoint flags.join("\n")
    check flags.anyIt(it.startsWith("--path:") and
      samePath(it["--path:".len .. ^1], CanonicalSrc))
    for flag in flags:
      check flag.startsWith("--path:") or flag.startsWith("--passC:") or
        flag.startsWith("--passL:")
      check not flag.startsWith("--import")
      check not flag.startsWith("--include")

  test "every repro_dsl_stdlib module has its reprobuild/dsl re-export, and no other":
    var expected: seq[string]
    for path in walkDirRec(StdlibRoot):
      if not path.endsWith(".nim"): continue
      let isMovedStub = readFile(path).splitLines.anyIt(
        it.startsWith("{.error:"))
      if isMovedStub: continue
      let rel = path.relativePath(StdlibRoot).changeFileExt("")
        .replace('\\', '/')
      expected.add(rel)
      let facade = CanonicalDslRoot / (rel & ".nim")
      checkpoint "reprobuild/dsl/" & rel & " (run " & GeneratorScript & ")"
      check fileExists(facade)
      if fileExists(facade):
        let text = readFile(facade)
        check ("import repro_dsl_stdlib/" & rel & " as impl\nexport impl\n") in
          text
        check "--import" notin text and "include " notin text
    check expected.len > 300
    for path in walkDirRec(CanonicalDslRoot):
      if path.endsWith(".nim") and readFile(path).startsWith(GeneratedMarker):
        let rel = path.relativePath(CanonicalDslRoot).changeFileExt("")
          .replace('\\', '/')
        checkpoint "stale reprobuild/dsl/" & rel & " (run " & GeneratorScript & ")"
        check rel in expected

suite "every canonical and legacy import compiles with UnusedImport as an error":
  let dir = scratch / "imports"
  createDir(dir)
  writeFile(dir / "nim.cfg", pathCfg)

  # (file name, source). Each fixture USES what it imports, so an import
  # that resolved to the wrong module, or to nothing, fails the compile.
  const fixtures = [
    ("umbrella", "import reprobuild\n\npackage umbrella:\n  build:\n" &
      "    discard writeText(\"build/a.txt\", \"a\")\n"),
    ("core_dsl", "import reprobuild/dsl\n\npackage coreDsl:\n  build:\n" &
      "    shell(command = \"true\")\n"),
    ("dsl_fs", "import reprobuild/dsl/fs\n\n" &
      "discard ensureDir(\"build/x\")\n"),
    ("dsl_packages_nim", "import reprobuild/dsl/packages/nim\n\n" &
      "proc usesNim(p: NimPackage) = discard p\n"),
    ("dsl_packaging", "import reprobuild/dsl/packaging\n\n" &
      "proc usesPackaging(d: Distribution) = discard d\n"),
    ("home_profile", "import reprobuild/home\n\nprofile \"demo-home\":\n" &
      "  activity default:\n    git\n"),
    ("system_profile", "import reprobuild/system\n\n" &
      "profile \"demo-system\":\n  resources:\n" &
      "    fsSystemDirectory(path = \"/etc/demo.d\", address = \"demoDir\")\n"),
    ("legacy_project_dsl", "import repro_project_dsl\n\n" &
      "package legacyDsl:\n  build:\n    shell(command = \"true\")\n"),
    ("legacy_stdlib", "import repro_dsl_stdlib\n\npackage legacyStdlib:\n" &
      "  build:\n    discard writeText(\"build/b.txt\", \"b\")\n"),
    ("legacy_stdlib_nim", "import repro_dsl_stdlib/packages/nim\n\n" &
      "proc usesNim(p: NimPackage) = discard p\n"),
  ]

  for (name, source) in fixtures:
    test "import fixture " & name:
      writeFile(dir / (name & ".nim"), source)
      let (output, exitCode) = nimCheck(dir, name & ".nim",
        ["--warningAsError[UnusedImport]:on"])
      checkpoint output
      check exitCode == 0
      check nimCheckErrors(output).len == 0
      check unusedImportFindings(output).len == 0

  test "old and new names denote the same symbols (no ambiguity when mixed)":
    writeFile(dir / "mixed.nim",
      "import reprobuild/dsl/packages/nim\n" &
      "import repro_dsl_stdlib/packages/nim\n" &
      "import reprobuild/dsl\nimport repro_project_dsl\n\n" &
      "proc usesNim(p: NimPackage) = discard p\n\n" &
      "package mixedNames:\n  build:\n    shell(command = \"true\")\n")
    # Two names for one module: Nim may report one of them as the unused
    # one, which is not what this case is about. Ambiguity would be an error.
    let (output, exitCode) = nimCheck(dir, "mixed.nim",
      ["--warning[UnusedImport]:off"])
    checkpoint output
    check exitCode == 0
    check "ambiguous" notin output

  test "a legacy-named reprobuild.nim project file compiles with reprobuild/dsl":
    # `import reprobuild` from a file itself named `reprobuild.nim` finds the
    # file (Nim searches the importer's directory first); the README tells
    # such files to import `reprobuild/dsl`, and this holds it to that.
    let legacyDir = dir / "legacy-name"
    createDir(legacyDir)
    writeFile(legacyDir / "nim.cfg", pathCfg)
    writeFile(legacyDir / "reprobuild.nim", "import reprobuild/dsl\n\n" &
      "package legacyName:\n  build:\n    shell(command = \"true\")\n")
    let (output, exitCode) = nimCheck(legacyDir, "reprobuild.nim",
      ["--warningAsError[UnusedImport]:on"])
    checkpoint output
    check exitCode == 0
    check unusedImportFindings(output).len == 0

  test "reprobuild/dsl carries the core DSL only, not the standard prelude":
    # ``currentBuildContext`` is declared only by the prelude
    # (``repro_dsl_stdlib/active_context``), which ``reprobuild`` re-exports
    # and ``reprobuild/dsl`` must not. The same file must compile under the
    # umbrella, so the failure below is the missing prelude and nothing else.
    # (``writeText`` cannot tell the two apart -- the core keeps a
    # ``ReproFs``-receiver overload of it -- and neither can a catalog type
    # such as ``NimPackage``, which neither name exports.)
    const body = "\n\ndiscard currentBuildContext()\n"
    writeFile(dir / "prelude_umbrella.nim", "import reprobuild" & body)
    let (umbrellaOut, umbrellaExit) = nimCheck(dir, "prelude_umbrella.nim",
      ["--warningAsError[UnusedImport]:on"])
    checkpoint umbrellaOut
    check umbrellaExit == 0
    writeFile(dir / "core_only.nim", "import reprobuild/dsl" & body)
    let (output, exitCode) = nimCheck(dir, "core_only.nim")
    checkpoint output
    check exitCode != 0
    check "undeclared identifier: 'currentBuildContext'" in output

suite "nim check and nimsuggest open repro.nim and src/main.nim cold":
  let dir = scratch / "project"
  writeProject(dir, pathCfg)

  test "nim check: repro.nim and src/main.nim are clean":
    for file in ["repro.nim", "src" / "main.nim"]:
      let (output, exitCode) = nimCheck(dir, file,
        ["--warningAsError[UnusedImport]:on"])
      checkpoint file & ":\n" & output
      check exitCode == 0
      check nimCheckErrors(output).len == 0
      check unusedImportFindings(output).len == 0

  test "nimsuggest on repro.nim: no errors, exact def for package and writeText":
    let (output, exitCode) = nimsuggest(dir, "repro.nim",
      ["chk 1:1", "def 3:1", "def 5:13"])
    let records = parseSuggest(output)
    checkpoint output.splitLines.filterIt("\tHint\t" notin it).join("\n")
    check exitCode == 0
    check chkErrors(records).len == 0
    check unusedImportFindings(output).len == 0
    let answers = defs(records)
    check answers.len == 2
    if answers.len == 2:
      let pkg = answers[0]
      check pkg.symKind == "skMacro"
      # The full DSL's module (`repro_project_dsl/full`), which the umbrella
      # re-exports in every mode but the thin one.
      check pkg.qualifiedName == "full.package"
      check samePath(pkg.file, ProjectDslMacros)
      check declaresAt(pkg.file, pkg.line, "macro package*")
      let write = answers[1]
      check write.symKind == "skProc"
      check write.qualifiedName.endsWith(".writeText")
      check samePath(write.file, StdlibFs)
      check declaresAt(write.file, write.line, "proc writeText*")

  test "nimsuggest on src/main.nim: its package is its own let, untouched":
    let (output, exitCode) = nimsuggest(dir, "src" / "main.nim",
      ["chk 1:1", "def 2:6"])
    let records = parseSuggest(output)
    checkpoint output.splitLines.filterIt("\tHint\t" notin it).join("\n")
    check exitCode == 0
    check chkErrors(records).len == 0
    check unusedImportFindings(output).len == 0
    let answers = defs(records)
    check answers.len == 1
    if answers.len == 1:
      check answers[0].symKind == "skLet"
      check answers[0].qualifiedName == "main.package"
      check samePath(answers[0].file, dir / "src" / "main.nim")
      check answers[0].line == 1

suite "negative control: a directory-wide --import:reprobuild is caught":
  let dir = scratch / "polluted"
  writeProject(dir, pathCfg & "--import:reprobuild\n")

  test "nim check flags the injected import in src/main.nim":
    let (output, exitCode) = nimCheck(dir, "src" / "main.nim")
    checkpoint output
    check exitCode == 0  # a warning, not an error, by default...
    let findings = unusedImportFindings(output)
    check findings.len > 0
    check findings.anyIt("main.nim" in it and
      "imported and not used: 'reprobuild'" in it)
    # ...and fatal under the setting the positive cases use.
    let (_, strictExit) = nimCheck(dir, "src" / "main.nim",
      ["--warningAsError[UnusedImport]:on"])
    check strictExit != 0

  test "nimsuggest chk flags the injected import in src/main.nim":
    let (output, _) = nimsuggest(dir, "src" / "main.nim", ["chk 1:1"])
    checkpoint output.splitLines.filterIt("\tHint\t" notin it).join("\n")
    # nimsuggest escapes the quotes (``\'reprobuild\'``), so match the words.
    check unusedImportFindings(output).anyIt("main.nim" in it and
      "imported and not used" in it and "reprobuild" in it)

removeDir(scratch)
