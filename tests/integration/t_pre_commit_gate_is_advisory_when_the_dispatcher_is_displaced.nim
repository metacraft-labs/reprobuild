## TC-8g — a displaced dispatcher's certificate gate is advisory
## (CLI/hooks.md §"Coexistence Model").
##
## When prek is installed over the managed dispatcher, the dispatcher becomes
## ``pre-commit.legacy`` and prek's shim runs it as part of prek's own run —
## and prek runs its OWN hooks after it. Those may still rewrite and restage
## files, so the gate cannot know it judged the content the commit records
## (test-certificates Standard §5.1). In that layout, under ``gate_mode =
## required``:
##
##   1. an uncovered commit is NOT refused: it is reported as advisory, names
##      ``repro hooks ensure --vcs``, and the gate's log line says it ran and
##      reported (so "not refused" is not "never ran");
##   2. control: after ``repro hooks ensure --vcs`` restores the canonical
##      layout, the same kind of uncovered commit IS refused.
##
## Falsifiability: ignoring the displacement flag (treating ``.legacy`` like
## the canonical slot) refuses case 1.
##
## NO MOCKS: real git, real prek, the hooks ``repro hooks ensure --vcs``
## installs. Skip rule: ``git``, ``ssh-keygen`` or ``prek`` missing (the
## reprobuild dev shell provides all three).

import repro_test_support/reasoned_skip
import std/[os, osproc, sequtils, strutils, unittest]

include pre_commit_gate_fixture

proc prekInstall(fx: StoreFixture; prekHome: string) =
  ## What git-hooks.nix's installation script does on every dev-shell entry.
  let env = fx.hookEnv & @[(name: "PREK_HOME", value: prekHome)]
  for hook in ["pre-commit", "pre-push", "post-commit", "post-merge",
      "post-checkout", "commit-msg"]:
    discard runArgv(@[findExe("prek"), "uninstall", "-t", hook], fx.libAPath,
      env)
  let res = runArgv(@[findExe("prek"), "install", "-c",
    ".pre-commit-config.yaml", "-t", "pre-commit"], fx.libAPath, env)
  doAssert res.code == 0, res.output

suite "TC-8g — a displaced dispatcher's gate is advisory":

  test "t_pre_commit_gate_is_advisory_when_the_dispatcher_is_displaced":
    if findExe("git").len == 0 or findExe("ssh-keygen").len == 0 or
        findExe("prek").len == 0:
      skip("needs git, ssh-keygen and prek on PATH (the reprobuild dev " &
        "shell has all three)")
    else:
      let fx = setupStoreFixture(
        requiredPolicy(@["t-unit"], @[currentPlatformTag()]), "tc8g-prek")
      defer: removeDir(fx.scratch)
      let prekHome = fx.scratch / "prek-home"
      createDir(prekHome)
      let ranFile = fx.scratch / "prek-ran.txt"
      writeFile(fx.libAPath / ".pre-commit-config.yaml",
        "repos:\n" &
        "- repo: local\n" &
        "  hooks:\n" &
        "  - id: record\n" &
        "    name: record\n" &
        "    entry: sh -c 'echo ran >> " & ranFile & "'\n" &
        "    language: system\n" &
        "    pass_filenames: false\n" &
        "    always_run: true\n")
      discard fx.mustGit("add", ".pre-commit-config.yaml")
      discard fx.mustGit("commit", "-q", "--no-verify", "-m", "prek config")

      # The dev-shell steady state, then a dev-shell re-entry displaces the
      # dispatcher.
      fx.ensureHooks()
      fx.prekInstall(prekHome)
      let hooks = fx.libAPath / ".git" / "hooks"
      check readFile(hooks / "pre-commit").contains("File generated by prek")
      check readFile(hooks / "pre-commit.legacy").contains(
        "reprobuild hook dispatcher")

      # ---- 1. displaced: reported as advisory, not refused ----------------
      writeFile(fx.libAPath / "a.txt", "never tested\n")
      discard fx.mustGit("add", "a.txt")
      let before = fx.head
      let env = fx.hookEnv & @[(name: "PREK_HOME", value: prekHome)]
      let displaced = runArgv(@["git", "-C", fx.libAPath, "commit", "-m",
        "uncovered, displaced"], fx.libAPath, env)
      checkpoint("displaced:\n" & displaced.output)
      check displaced.code == 0
      check fx.head != before
      check "running as pre-commit.legacy" in displaced.output
      check "no trusted certificate covers the content being committed" in
        displaced.output
      check "ADVISORY" in displaced.output
      check "repro hooks ensure --vcs" in displaced.output
      check "REFUSED" notin displaced.output
      check fileExists(ranFile)                 # prek's own hooks ran too
      check fx.gateLogLines("reported not-covered") == 1
      check "(dispatcher displaced)" in fx.gateLog

      # ---- 2. control: restored, the same kind of commit is refused -------
      let restored = runArgv(@[fx.reproBin, "hooks", "ensure", "--vcs",
        fx.libAPath], fx.libAPath, env)
      checkpoint("ensure:\n" & restored.output)
      check restored.code == 0
      check readFile(hooks / "pre-commit").contains(
        "reprobuild hook dispatcher")
      writeFile(fx.libAPath / "b.txt", "never tested either\n")
      discard fx.mustGit("add", "b.txt")
      let before2 = fx.head
      let canonical = runArgv(@["git", "-C", fx.libAPath, "commit", "-m",
        "uncovered, canonical"], fx.libAPath, env)
      checkpoint("canonical:\n" & canonical.output)
      check canonical.code != 0
      check fx.head == before2
      check "REFUSED (commit_gate = required)" in canonical.output
      check "ADVISORY" notin canonical.output
