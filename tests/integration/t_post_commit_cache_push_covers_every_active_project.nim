## Regression — the eager cache push covers EVERY active project of a
## multi-project workspace, not only the primary one.
##
## `resolveWorkspaceReposForHook` (the repo enumeration the post-commit hook's
## cache push, evidence refresh and sibling-ignore regeneration share) used to
## resolve only the PRIMARY project named by `[workspace] project`. A commit in
## a repo that only another member of `[workspace] projects` declares matched
## nothing, and the best-effort path returned 0 without writing a ref.
##
## Fixture: one workspace, two projects (`p` -> repo `r`, `q` -> repo `s`),
## state `project = "p"`, `projects = ["p", "q"]`; every repo wired to its own
## shared bare. After `repro hooks cache-push` for each repo:
##
##   - `r` (primary project): ref present (control; passed before the fix);
##   - `s` (non-primary active project): ref present (FAILED before the fix);
##   - single-project workspace (`projects` absent): `s` is NOT a member, so
##     no ref is written for it — the widening is by the recorded set only;
##   - a multi-project workspace whose second project no longer resolves:
##     the resolver falls back to the primary project's repos (the pre-fix
##     behaviour) instead of returning no repos at all, so `r` still pushes;
##   - the sibling-ignore block of the workspace root, regenerated by
##     `repro workspace enable`, lists a NESTED checkout that only the
##     non-primary project declares (the block takes declared paths from the
##     same resolver; a directory scan alone would not see a nested path).
##
## No mocks: real git repositories, the real `repro`. Skip: no git.

import std/[json, os, osproc, strutils, tempfiles, unittest]

import repro_test_support
import repro_test_support/reasoned_skip

proc q(value: string): string = quoteShell(value)

proc runCmd(command: string; cwd = ""): tuple[code: int; output: string] =
  let res = execCmdEx(command, workingDir = cwd)
  (code: res.exitCode, output: res.output)

proc requireGit(command: string; cwd = ""): string =
  let res = runCmd(command, cwd)
  if res.code != 0:
    stderr.writeLine("command failed: " & command & "\nexit=" & $res.code &
      "\n" & res.output)
    quit 1
  res.output

proc reproBinary(): string =
  requireBinary(currentSourcePath().parentDir.parentDir.parentDir / "build" /
    "bin" / addFileExt("repro", ExeExt), "reprobuild.apps.repro")

proc seedOrigin(gitBin, scratch, name: string): string =
  ## A bare upstream `<name>.git` with one commit on `main`.
  result = scratch / (name & ".git")
  discard requireGit(q(gitBin) & " init --bare -b main " & q(result))
  let seed = scratch / ("seed-" & name)
  discard requireGit(q(gitBin) & " init -b main " & q(seed))
  discard requireGit(q(gitBin) & " -C " & q(seed) &
    " config user.email t@example.invalid")
  discard requireGit(q(gitBin) & " -C " & q(seed) & " config user.name T")
  writeFile(seed / "a.txt", "1\n")
  discard requireGit(q(gitBin) & " -C " & q(seed) & " add a.txt")
  discard requireGit(q(gitBin) & " -C " & q(seed) & " commit -m base")
  discard requireGit(q(gitBin) & " -C " & q(seed) &
    " remote add origin " & q(result))
  discard requireGit(q(gitBin) & " -C " & q(seed) & " push origin main")

proc writeProject(ws, project, repo, origin: string; path = "") =
  writeFile(ws / "projects" / (project & ".toml"),
    "schema = \"reprobuild.workspace.project.v1\"\n\n" &
    "[project]\nname = \"" & project & "\"\n\n" &
    "[[remote]]\nname = \"o\"\nfetch = \"file://" & origin &
    "\"\n\nincludes = [\n  \"repos/" & repo & ".toml\",\n]\n")
  writeFile(ws / "repos" / (repo & ".toml"),
    "schema = \"reprobuild.workspace.repo.v2\"\n\n" &
    "[repo]\nname = \"" & repo & "\"\npath = \"" &
    (if path.len > 0: path else: repo) & "\"\n" &
    "remote = \"o\"\nmainline = \"main\"\n")

proc commitIn(gitBin, repo: string) =
  writeFile(repo / "b.txt", "2\n")
  discard requireGit(q(gitBin) & " -C " & q(repo) & " add b.txt")
  discard requireGit(q(gitBin) & " -C " & q(repo) & " commit -m more")

proc cacheRefs(gitBin, bare: string): string =
  requireGit(q(gitBin) & " -C " & q(bare) &
    " for-each-ref --format=" & q("%(refname)") & " refs/cache/").strip()

proc buildWorkspace(gitBin, reproBin, scratch, stateProjects: string):
    tuple[ws: string, bares: array[2, string]] =
  ## `stateProjects` is the `projects = [...]` line ("" for a single-project
  ## workspace). Returns the workspace and the shared bares of `r` and `s`.
  let ws = scratch / "ws"
  result.ws = ws
  createDir(ws / "projects")
  createDir(ws / "repos")
  createDir(ws / ".repro")
  let repos = ["r", "s"]
  # Both upstreams live in `scratch`; the project's remote fetch base is that
  # directory, so repo `r` resolves to `<scratch>/r.git`.
  for name in repos:
    discard seedOrigin(gitBin, scratch, name)
  writeProject(ws, "p", "r", scratch / "r.git")
  writeProject(ws, "q", "s", scratch / "s.git")
  writeFile(ws / ".repro" / "workspace-state.toml",
    "schema = \"reprobuild.workspace.state.v1\"\n\n[workspace]\n" &
    "project = \"p\"\n" & stateProjects)
  for name in repos:
    discard requireGit(q(gitBin) & " clone " &
      q("file://" & scratch / (name & ".git")) & " " & q(ws / name))
    discard requireGit(q(gitBin) & " -C " & q(ws / name) &
      " config user.email t@example.invalid")
    discard requireGit(q(gitBin) & " -C " & q(ws / name) &
      " config user.name T")
  let rewire = runCmd(q(reproBin) & " workspace shared-clones rewire" &
    " --workspace-root=" & q(ws) & " --json")
  if rewire.code != 0:
    checkpoint("rewire output: " & rewire.output)
  doAssert rewire.code == 0, "rewire failed"
  for entry in parseJson(rewire.output)["repos"]:
    case entry["path"].getStr()
    of "r": result.bares[0] = entry["sharedBarePath"].getStr()
    of "s": result.bares[1] = entry["sharedBarePath"].getStr()
    else: discard

proc cachePush(reproBin, ws, repo: string): int =
  let r = runCmd(q(reproBin) & " hooks cache-push --repo-root=" &
    q(ws / repo) & " --workspace-name=ws")
  if r.code != 0: checkpoint("cache-push output: " & r.output)
  r.code

suite "regression — eager cache push covers every active project":

  test "t_post_commit_cache_push_covers_every_active_project":
    let gitBin = findExe("git")
    if gitBin.len == 0:
      skip("git is not on PATH; this case needs a repository")
    else:
      let scratch = createTempDir("repro-cpush-projects-", "")
      defer: removeDir(scratch)
      let reproBin = reproBinary()
      putEnv("REPRO_WORKSPACE_CLONES", scratch / "cache")
      defer: delEnv("REPRO_WORKSPACE_CLONES")
      let f = buildWorkspace(gitBin, reproBin, scratch,
        "projects = [\"p\", \"q\"]\n")
      check f.bares[0].len > 0 and f.bares[1].len > 0
      check cacheRefs(gitBin, f.bares[0]) == ""
      check cacheRefs(gitBin, f.bares[1]) == ""

      commitIn(gitBin, f.ws / "r")
      check cachePush(reproBin, f.ws, "r") == 0
      check cacheRefs(gitBin, f.bares[0]) == "refs/cache/ws/main"

      # The non-primary active project's repo: absent before the fix.
      commitIn(gitBin, f.ws / "s")
      check cachePush(reproBin, f.ws, "s") == 0
      check cacheRefs(gitBin, f.bares[1]) == "refs/cache/ws/main"

  test "t_post_commit_cache_push_single_project_ignores_unlisted_project":
    let gitBin = findExe("git")
    if gitBin.len == 0:
      skip("git is not on PATH; this case needs a repository")
    else:
      let scratch = createTempDir("repro-cpush-single-", "")
      defer: removeDir(scratch)
      let reproBin = reproBinary()
      putEnv("REPRO_WORKSPACE_CLONES", scratch / "cache")
      defer: delEnv("REPRO_WORKSPACE_CLONES")
      # No `projects` list: only the primary project `p` is active.
      let f = buildWorkspace(gitBin, reproBin, scratch, "")
      commitIn(gitBin, f.ws / "r")
      check cachePush(reproBin, f.ws, "r") == 0
      check cacheRefs(gitBin, f.bares[0]) == "refs/cache/ws/main"
      # `s` belongs only to the inactive project `q`: behaviour unchanged.
      commitIn(gitBin, f.ws / "s")
      check cachePush(reproBin, f.ws, "s") == 0
      check cacheRefs(gitBin, f.bares[1]) == ""
      # ...and the skip is no longer silent: the log names the repo.
      let log = f.ws / ".repro" / "build" / "reports" / "post-commit-lock.log"
      check fileExists(log)
      if fileExists(log):
        let text = readFile(log)
        check "cache-push: skipped" in text and (f.ws / "s") in text

  test "t_post_commit_cache_push_falls_back_to_primary_when_a_member_is_broken":
    let gitBin = findExe("git")
    if gitBin.len == 0:
      skip("git is not on PATH; this case needs a repository")
    else:
      let scratch = createTempDir("repro-cpush-broken-", "")
      defer: removeDir(scratch)
      let reproBin = reproBinary()
      putEnv("REPRO_WORKSPACE_CLONES", scratch / "cache")
      defer: delEnv("REPRO_WORKSPACE_CLONES")
      let f = buildWorkspace(gitBin, reproBin, scratch,
        "projects = [\"p\", \"q\"]\n")
      # `q` is recorded as active but its manifest is gone: extending the
      # primary with it cannot resolve.
      removeFile(f.ws / "projects" / "q.toml")
      commitIn(gitBin, f.ws / "r")
      check cachePush(reproBin, f.ws, "r") == 0
      # One broken member must not blank the healthy primary's repo set.
      check cacheRefs(gitBin, f.bares[0]) == "refs/cache/ws/main"

  test "t_workspace_sibling_ignores_cover_every_active_projects_nested_repos":
    let gitBin = findExe("git")
    if gitBin.len == 0:
      skip("git is not on PATH; this case needs a repository")
    else:
      let scratch = createTempDir("repro-ignores-projects-", "")
      defer: removeDir(scratch)
      let reproBin = reproBinary()
      putEnv("REPRO_WORKSPACE_CLONES", scratch / "cache")
      defer: delEnv("REPRO_WORKSPACE_CLONES")
      let ws = scratch / "ws"
      createDir(ws / "projects")
      createDir(ws / "repos")
      createDir(ws / ".repro")
      for name in ["r", "s"]:
        discard seedOrigin(gitBin, scratch, name)
      # `s` belongs to the non-primary project `q`, at a NESTED path.
      writeProject(ws, "p", "r", scratch / "r.git")
      writeProject(ws, "q", "s", scratch / "s.git", "grp/deep/s")
      writeFile(ws / ".repro" / "workspace-state.toml",
        "schema = \"reprobuild.workspace.state.v1\"\n\n[workspace]\n" &
        "project = \"p\"\nprojects = [\"p\", \"q\"]\n")
      discard requireGit(q(gitBin) & " clone " &
        q("file://" & scratch / "r.git") & " " & q(ws / "r"))
      createDir(ws / "grp" / "deep")
      discard requireGit(q(gitBin) & " clone " &
        q("file://" & scratch / "s.git") & " " & q(ws / "grp" / "deep" / "s"))
      discard requireGit(q(gitBin) & " -C " & q(ws) & " init -q -b main")
      discard requireGit(q(gitBin) & " -C " & q(ws) & " add projects repos")
      discard requireGit(q(gitBin) & " -C " & q(ws) &
        " -c user.email=t@example.invalid -c user.name=T commit -q -m m")
      let res = runCmd(q(reproBin) & " workspace enable q --no-sync" &
        " --workspace-root=" & q(ws))
      checkpoint("enable output: " & res.output)
      check res.code == 0
      let excl = readFile(ws / ".git" / "info" / "exclude")
      checkpoint("info/exclude:\n" & excl)
      check "/r/" in excl.splitLines()
      # Only the declared-path list can name the nested checkout.
      check "/grp/deep/s/" in excl.splitLines()
