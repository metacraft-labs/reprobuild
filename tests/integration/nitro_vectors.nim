## The exact digests are asserted by the gate against these bytes; the
## table is a reader's index, not the check.
##
## Two of the five are redistributions in a transport wrapper rather than
## raw CBOR, and the pinned hex is of the DECODED bytes:
## `OpenGradient` stores base64 and `SyndicateProtocol` stores hex. Their
## digests above are of the decoded documents.
##
## `SyndicateProtocol` also redistributes `att_doc_sample.bin`
## byte-for-byte from `aws-samples`, and says so in its own README. It is
## therefore *not* counted as a second publisher of that document, and
## only its second, distinct document is pinned here.
##
## **The instance identifiers inside these documents are third parties'
## published test material**, not this project's. They are load-bearing:
## PCR4 is a function of the parent instance's ID, and the gate
## reproduces it, so removing them would delete the measurement.
##
## ## What makes them genuine, established before any of this code ran
##
## With OpenSSL 3.6.1 and a CBOR decoder written for the purpose, outside
## this repository:
##
##   * every one is an UNTAGGED `COSE_Sign1` — a bare four-element CBOR
##     array, first byte `0x84`, protected bucket `a1013822` (`{1: -35}`,
##     ES384) and an EMPTY unprotected bucket;
##   * every one's 96-byte signature verifies, under the P-384 key of the
##     certificate the document itself carries, over the RFC 9052 §4.4
##     `Sig_structure`;
##   * every one's `cabundle[0]` is byte-identical to the vendor root
##     above, and the leaf chains to it through the bundle — `OK` from
##     `openssl verify` when evaluated at the document's own timestamp;
##   * `zkVerify` also publishes a deliberately corrupted copy of its
##     2022 document. It is not pinned here (the gate mutates bytes
##     itself), but it was checked: signature FAILS, chain still OK.
##
## Every leaf validity window is about three hours wide
## (`2026-02-12 17:55:59 → 20:56:02` for one of them), so none of these
## chains validates at today's date and a verifier that replays a stored
## document has to evaluate the chain at the document's own time. That is
## a property of the surface, not of the corpus.
##
## ## The corpus is checked for degeneracy rather than hoped free of it
##
## The vendor's OWN sample is degenerate and that is exactly why it is
## kept: `AwsSample2023DocHex` was produced by an enclave launched in
## debug mode, so PCR0, PCR1 and PCR2 are all forty-eight zero bytes and
## `public_key`, `user_data` and `nonce` are all CBOR `null`. A locator
## that returned a constant, or a field reader that returned nothing,
## would pass against it alone. The other four are non-degenerate and
## spread deliberately:
##
##   | document | PCR0/1/2 | user_data | nonce | public_key | payload map |
##   |----------+----------+-----------+-------+------------+-------------|
##   | `AwsSample2023`  | all zero | null | null | null      | definite |
##   | `ZkvEuWest2022`  | non-zero | 32 B | 32 B | null      | definite |
##   | `SyndUsEast2025` | non-zero | null | null | 65 B       | definite |
##   | `OgUsEast2026`   | non-zero | 68 B | 20 B | 5 B        | indefinite |
##   | `ZkvEuWest2026`  | non-zero | 20 B | null | 133 B      | indefinite |
##
## Each optional field is present in at least two documents and absent in
## at least two, so a reader that always returned "absent" and a reader
## that always returned "present" both fail.
##
## ## `…LeafPointHex` — a second reader for the same bytes
##
## Each of the five is the uncompressed SEC 1 point
## (`0x04 ‖ X(48) ‖ Y(48)`, 97 bytes) of that document's leaf
## certificate, as **OpenSSL 3.6.1** read it out of the DER. The gate
## walks the same DER with this repository's own reader and requires the
## same answer. Two transcriptions of one field held together by
## measurement: it catches a walk that lands on the wrong TLV, and it
## does not catch two readers wrong the same way — which is the same
## limit the sibling corpora record for the same technique.
##
## ## Vendor-published worked examples
##
## `AwsDocumentedPcr4Input` / `…Output` and `AwsDocumentedPcr3Input` /
## `…Output` are transcribed verbatim from the vendor's own
## documentation, which publishes a one-line command and its output for
## each. They pin the register construction against numbers the vendor
## computed, independently of any document. The account number inside the
## PCR3 example is the vendor's documentation placeholder.
##
