## Pinned AWS Nitro Enclaves attestation material: what it is, where
## every byte came from, and what it is and is not evidence of.
##
## ## The short version
##
## **Everything here is genuine.** Five attestation documents produced by
## the Nitro Hypervisor for five different enclaves, on five different
## EC2 instances, across two AWS regions and four calendar years, plus
## the vendor's published root certificate. Nothing in this file was
## signed by the code the gate exercises, and nothing in it was produced
## by this repository.
##
## There is **no fabricated bundle** here, deliberately. The negative
## cases in the gate are built by mutating these bytes at run time — a
## flipped bit, a document verified under a neighbour's key — so a
## reader does not have to take anyone's word for what a "bad" fixture
## contains.
##
## ## The root certificate, and why four publishers were checked
##
## `NitroRootG1DerHex` is the DER form of the single certificate inside
##
##   https://aws-nitro-enclaves.amazonaws.com/AWS_NitroEnclaves_Root-G1.zip
##
## fetched 2026-09-27. Two digests, and which is which matters. The ZIP
## is `sha256
## 8cf60e2b2efca96c6a9e71e851d00c1b6991cc09eadbe64a6a1d1b1eb9faff7c`
## and the `root.pem` it holds is `sha256
## 6eb9688305e4bbca67f44b59c29a0661ae930f09b5945b5d1d9ae01125c8d6c0`,
## but BOTH of those are measured here and NEITHER is published by the
## vendor. What the vendor publishes is the CERTIFICATE's SHA-256
## fingerprint:
##
##   64:1A:03:21:A3:E2:44:EF:E4:56:46:31:95:D6:06:31:
##   7E:D7:CD:CC:3C:17:56:E0:98:93:F3:C6:8F:79:BB:5B
##
## which is exactly the sha256 of the DER pinned below. So the constant
## in this file is anchored to a number the vendor published, not to a
## download — and an earlier draft of this header said the ZIP digest was
## the published one, which it is not.
##
## The certificate is self-signed, P-384, `CN=aws.nitro-enclaves`, valid
## 2019-10-28 → 2049-10-28.
##
## A single fetch is a single point of trust, so the same bytes were
## taken from three other publishers and all four agree:
##
##   | publisher | form | agrees |
##   |-----------+------+--------|
##   | the vendor's own ZIP, above                                   | PEM | — |
##   | `aws-samples/aws-iot-validate-enclave-attestation` `validate_doc/AWS_NitroEnclaves_Root-G1.pem` | PEM | byte-identical |
##   | `SyndicateProtocol/syndicate-appchains` `…/aws-nitro/src/testdata/aws_nitro_root.pem` | PEM | byte-identical |
##   | `zkVerify/tee-verifier` `assets/aws_nitro_root_g1.der` | DER | byte-identical |
##   | `escrin/escrin` `ssss/src/verify/nitro/root.der` | DER | byte-identical |
##
## The two DER publishers agree with each other and with the DER this
## file pins, whose `sha256
## 641a0321a3e244efe456463195d606317ed7cdcc3c1756e09893f3c68f79bb5b`
## is the vendor's published fingerprint above, and is also what
## OpenSSL 3.6.1 computes from the vendor's own PEM. Five sources and one
## published fingerprint, all naming one certificate.
